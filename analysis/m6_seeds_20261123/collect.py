#!/usr/bin/env python3
"""results.md: the six-tumor SNV models of the current pipeline on HPRC v2.1, seeds 0 / 1 / 2, chr1 of HCC1395T,
COLO829T and HG008T, benchmark BED, after the population filter, PASS at rule 2. Seeds 1 and 2: eval_bed/report.json
of this batch (TP / FP / FN / P / R / F1). Seed 0 (snv_newpipe_20261109/multicancer6_<P>_SNV_newpipe, old cluster):
P / R / F1 of the six-tumor column of Supplementary Table R1.7b (r17b_latest.md), the same test sets and rule. Mean and
SD (n - 1) of F1 over the seeds that have a result. A cell whose job has not finished says "pending".
usage: python3 collect.py   (login node, standard library)"""
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = Path("/storage2/fs1/epigenome/Active/jiawei.s/pansoma_net_v2_runs/m6_seeds_20261123")
R17B = HERE.parent / "reviewer_response_20261011/experiments/E27_assessment_20261030/v3/r17_normbq/r17b_latest.md"
TUMORS = ("HCC1395T", "COLO829T", "HG008T")
PLATFORMS = ("Illumina", "PacBio", "ONT")
SEEDS = (1, 2)


def test_set(tumor, p):
    cp = "fiberseq" if (tumor, p) == ("COLO829T", "PacBio") else p
    af = "_snvaf05" if p != "ONT" and tumor != "HG008T" else ""
    return f"{tumor}_{cp}_d46{af}"


def plat(tumor, p):
    return {"Illumina": "Illumina", "ONT": "ONT", "PacBio": "Fiber-seq" if tumor == "COLO829T" else "PacBio HiFi"}[p]


def seed0():
    """{'<tumor> <platform label>': (P, R, F1)} of the six-tumor column of r17b_latest.md (first table)."""
    out, head = {}, None
    for line in R17B.read_text().splitlines():
        if not line.startswith("|"):
            if head and out:
                break
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if line.startswith("|---"):
            continue
        if head is None:
            head = cells
            continue
        v = cells[head.index("six-tumor model")].rstrip(" †")
        out[cells[0]] = tuple(float(x) for x in v.split(" / "))
    return out


def main():
    s0 = seed0()
    lines = ["# Six-tumor SNV models of the current pipeline on HPRC v2.1, three seeds: chr1 results", "",
             "Generated by `collect.py`. chr1, benchmark BED, after the population filter; PASS = rule 2 (post-filter "
             "validation recall 0.95 of the callable positives). Seed 0: `snv_newpipe_20261109/multicancer6_<P>_SNV_newpipe` "
             "(old cluster; P / R / F1 from Supplementary Table R1.7b, `r17b_latest.md`); seeds 1 and 2: "
             "`$PANSOMA_RUNS/m6_seeds_20261123/multicancer6_<P>_SNV_newpipe_s<SEED>`.", "",
             "| tumor | platform | seed | best epoch | truth | TP | FP | FN | P | R | F1 |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    summary = []
    for tumor in TUMORS:
        for p in PLATFORMS:
            f1s, truth = [], set()
            key = f"{tumor} {plat(tumor, p)}"
            if key in s0:
                P, R, F = s0[key]
                f1s.append(F)
                lines.append(f"| {tumor} | {plat(tumor, p)} | 0 | | | | | | {P:.3f} | {R:.3f} | {F:.3f} |")
            for seed in SEEDS:
                run = RUNS / f"multicancer6_{p}_SNV_newpipe_s{seed}"
                f = run / f"vcf_chr1_{test_set(tumor, p)}" / "eval_bed" / "report.json"
                if not f.exists():
                    lines.append(f"| {tumor} | {plat(tumor, p)} | {seed} | pending |" + " |" * 7)
                    continue
                r = json.loads(f.read_text())
                a = r["pon"]["at_threshold"]
                truth.add(a["tp_baseline"] + a["fn"])
                ep = next((ln.split()[3] for ln in (run / "train.log").read_text().splitlines()
                           if ln.startswith("done; best epoch")), "")
                f1s.append(a["f1"])
                lines.append(f"| {tumor} | {plat(tumor, p)} | {seed} | {ep} | {a['tp_baseline'] + a['fn']} | {a['tp_baseline']} | "
                             f"{a['fp']} | {a['fn']} | {a['precision']:.3f} | {a['recall']:.3f} | {a['f1']:.3f} |")
            assert len(truth) <= 1, (tumor, p, truth)
            sd = f"{statistics.stdev(f1s):.3f}" if len(f1s) > 1 else ""
            summary.append(f"| {tumor} | {plat(tumor, p)} | {len(f1s)} | {' / '.join(f'{x:.3f}' for x in f1s)} | "
                           f"{statistics.mean(f1s):.3f} | {sd} |" if f1s else f"| {tumor} | {plat(tumor, p)} | 0 | | | |")
    lines += ["", "## PASS F1 over the seeds", "", "| tumor | platform | seeds | F1 (seed 0 / 1 / 2) | mean | SD |",
              "|---|---|---|---|---|---|"] + summary
    (HERE / "results.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
