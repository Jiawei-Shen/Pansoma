#!/usr/bin/env python3
"""results_indel.md: chr1 of HCC1395T / COLO829T / HG008T, benchmark BED, rtg vcfeval, PASS calls, for the six-tumor
INDEL models without the population site features as a model input on HPRC v1.1 / v2.1 (lab cluster,
submit_indel_lab.sh; eval_bed/report.json of every vcf_<rule>_chr1_<tumor>, "raw" = before, "pon" = after the
population filter). PASS: ppr8 (Illumina / PacBio HiFi / Fiber-seq), pp (ONT). Second table: PASS after the filter
next to the six-tumor models of the same recipe: GRCh38-only without the features
(m4m6_graphs_20261110/multicancer6_<P>_INDEL_linear_nositef), v1.1 with them (..._d9), v2.1 with them
(release_s0_<P>_INDEL), all seed 0. The truth count (TP + FN) of every cell of a row is asserted equal. A call set
that does not exist yet prints "pending".
usage: python3 collect_indel_lab.py > results_indel.md   (login node, standard library)"""
import json
import re
from pathlib import Path

R = Path("/scratch/jshen/data/pansoma_net_v2_runs")
NEW = R / "m6_nositef_graphs_20261118"
G = R / "m4m6_graphs_20261110"
TUMORS = ("HCC1395T", "COLO829T", "HG008T")
PLATFORMS = ("Illumina", "PacBio", "ONT")


def plat(tumor, p):
    return {"Illumina": "Illumina", "ONT": "ONT", "PacBio": "Fiber-seq" if tumor == "COLO829T" else "PacBio HiFi"}[p]


def vcf(model, p, tumor):
    """model: nositef_d9 | nositef_d46 | linear_nositef | d9 | d46 -> (run directory, call-set directory)."""
    r = "pp" if p == "ONT" else "ppr8"
    if model.startswith("nositef_"):
        run = NEW / f"multicancer6_{p}_INDEL_{model[8:]}_nositef"
    elif model == "d46":
        run = R / f"release_s0_{p}_INDEL"
        cp = "fiberseq" if (tumor, p) == ("COLO829T", "PacBio") else p
        return run, run / f"vcf_{r}_chr1_{tumor}_{cp}_d46"
    else:
        run = G / f"multicancer6_{p}_INDEL_{model}"
    return run, run / f"vcf_{r}_chr1_{tumor}"


def rep(d, stage):
    f = d / "eval_bed" / "report.json"
    return json.loads(f.read_text())[stage]["at_threshold"] if f.exists() else None


def prf(a):
    return "pending" if a is None else f"{a['precision']:.3f} / {a['recall']:.3f} / {a['f1']:.3f}"


def best_epoch(run):
    log = run / "train.log"
    m = re.findall(r"^done; best epoch (\d+)", log.read_text(), re.M) if log.exists() else []
    return m[-1] if m else "-"


def same_truth(cells, row):
    n = {a["tp_baseline"] + a["fn"] for a in cells if a}
    assert len(n) <= 1, (row, n)


print("# Six-tumor INDEL models without the population site features as a model input, HPRC v1.1 / v2.1 "
      "(generated by `collect_indel_lab.py`)\n")
print("chr1 of the test tumor (held out of training and validation), benchmark regions, rtg vcfeval, PASS calls "
      "(ppr8; ONT pp), seed 0.\n")
print("## 1. The no-site-feature models, chr1, before and after the population filter\n")
print("| tumor, chr1 | platform | graph | best epoch | truth | TP | FP | FN | P / R / F1 after the filter, chr1 | "
      "P / R / F1 before the filter, chr1 |")
print("|---|---|---|---|---|---|---|---|---|---|")
for t in TUMORS:
    for p in PLATFORMS:
        for g, name in (("d9", "HPRC v1.1"), ("d46", "HPRC v2.1")):
            run, d = vcf(f"nositef_{g}", p, t)
            a, b = rep(d, "pon"), rep(d, "raw")
            c = [a["tp_baseline"] + a["fn"], a["tp_baseline"], a["fp"], a["fn"]] if a else ["-"] * 4
            print(f"| {t} | {plat(t, p)} | {name} | {best_epoch(run)} | " + " | ".join(map(str, c)) + f" | {prf(a)} | {prf(b)} |")
print("\n## 2. Against the six-tumor models of the same recipe, chr1 PASS after the population filter, P / R / F1\n")
MODELS = (("linear_nositef", "GRCh38-only, no site features"), ("nositef_d9", "HPRC v1.1, no site features"),
          ("nositef_d46", "HPRC v2.1, no site features"), ("d9", "HPRC v1.1, site features"),
          ("d46", "HPRC v2.1, site features"))
print("| tumor, chr1 | platform | " + " | ".join(f"{n}, chr1" for _, n in MODELS) + " |")
print("|---|---|" + "---|" * len(MODELS))
for t in TUMORS:
    for p in PLATFORMS:
        cells = [rep(vcf(m, p, t)[1], "pon") for m, _ in MODELS]
        same_truth(cells, (t, p))
        print(f"| {t} | {plat(t, p)} | " + " | ".join(prf(a) for a in cells) + " |")
