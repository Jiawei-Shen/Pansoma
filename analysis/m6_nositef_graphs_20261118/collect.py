#!/usr/bin/env python3
"""results.md: chr1 of HCC1395T / COLO829T / HG008T, benchmark BED, after the population filter, for the six-tumor
nositef models of this batch (eval_bed/report.json of every vcf_chr1_<SET>): PASS TP / FP / FN / P / R / F1, the best
F1 on the post-filter curve and the curve end. Second table: PASS F1 next to the six-tumor models of the figure
(../reviewer_response_20261011/supplementary/R1.6/points_six_tumor_graphs.md: v2.1 and v1.1 with the site features
as an input, GRCh38-only without), F1 = 2PR / (P + R) from the 3-decimal P and R there. Every call set of a row is
scored against the same truth (record count asserted equal across graphs).
usage: python3 collect.py   (login node, standard library)"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = Path("/storage2/fs1/epigenome/Active/jiawei.s/pansoma_net_v2_runs/m6_nositef_graphs_20261118")
POINTS = HERE.parent / "reviewer_response_20261011/supplementary/R1.6/points_six_tumor_graphs.md"
TUMORS = ("HCC1395T", "COLO829T", "HG008T")
PLATFORMS = ("Illumina", "PacBio", "ONT")
GRAPHS = (("d9", "HPRC v1.1"), ("d46", "HPRC v2.1"))


def test_set(tumor, p, g):
    cp = "fiberseq" if (tumor, p) == ("COLO829T", "PacBio") else p
    af = "_snvaf05" if p != "ONT" and tumor != "HG008T" else ""
    if tumor == "HCC1395T":
        return f"HCC1395T_{p}_{g}{af}"
    if g == "d9":
        return f"{tumor}_{cp}{af}"
    return f"{tumor}_{cp}_d46{af}"


def plat(tumor, p):
    return {"Illumina": "Illumina", "ONT": "ONT", "PacBio": "Fiber-seq" if tumor == "COLO829T" else "PacBio HiFi"}[p]


def f1(p, r):
    return 2 * p * r / (p + r) if p + r else 0.0


def points():
    """{(tumor, platform label): {column: value}} of the SNV rows of the figure's points file."""
    out, head = {}, None
    for line in POINTS.read_text().splitlines():
        if not line.startswith("|") or line.startswith("|---"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if head is None:
            head = cells
            continue
        if cells[0] == "SNV":
            out[(cells[1], cells[2])] = cells
    return head, out


def num(x):
    try:
        return float(x)
    except ValueError:
        return None


def main():
    rep, truth = {}, {}
    for tumor in TUMORS:
        for p in PLATFORMS:
            for g, _ in GRAPHS:
                f = RUNS / f"multicancer6_{p}_SNV_{g}_nositef" / f"vcf_chr1_{test_set(tumor, p, g)}" / "eval_bed" / "report.json"
                if f.exists():
                    r = json.loads(f.read_text())
                    rep[tumor, p, g] = r
                    truth.setdefault((tumor, p), set()).add(r["truth_records"])
    assert all(len(v) == 1 for v in truth.values()), truth
    lines = ["# Six-tumor SNV models without site features as a model input, HPRC v1.1 and v2.1: chr1 results", "",
             "Generated by `collect.py`. chr1, benchmark BED, after the population filter; PASS = the checkpoint's call "
             "rule (rule 2: post-filter validation recall 0.95 of the callable positives). Runs: "
             "`$PANSOMA_RUNS/m6_nositef_graphs_20261118/multicancer6_<P>_SNV_{d9,d46}_nositef`, seed 0.", "",
             "| tumor | platform | graph | test set | truth | threshold | TP | FP | FN | P | R | F1 | best F1 on curve | curve end R |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for tumor in TUMORS:
        for p in PLATFORMS:
            for g, gl in GRAPHS:
                r = rep.get((tumor, p, g))
                if r is None:
                    lines.append(f"| {tumor} | {plat(tumor, p)} | {gl} | {test_set(tumor, p, g)} | pending |" + " |" * 9)
                    continue
                a, c = r["pon"]["at_threshold"], r["pon"]
                lines.append(f"| {tumor} | {plat(tumor, p)} | {gl} | {test_set(tumor, p, g)} | {r['truth_records']} | "
                             f"{r['threshold']:.3f} | {a['tp_baseline']} | {a['fp']} | {a['fn']} | {a['precision']:.3f} | "
                             f"{a['recall']:.3f} | {a['f1']:.3f} | {c['best']['f1']:.3f} | {c['curve_roc'][-1]['recall']:.3f} |")
    head, pts = points()
    col = {"v21": (3, 4), "lin": (6, 7), "v11": (9, 10)}  # (R, P) cells of the points file
    lines += ["", "## PASS F1 next to the six-tumor models of Supplementary Fig. R1.6 (three references)", "",
              "With site features = the population site features are a model input (`multicancer6_<P>_SNV_newpipe` on "
              "v2.1, `m4m6_graphs_20261110/multicancer6_<P>_SNV_d9` on v1.1); GRCh38-only never has them "
              "(`multicancer6_<P>_SNV_linear_nositef`). Their F1 is computed from the rounded P / R of "
              f"`{POINTS.relative_to(HERE.parent)}`; \"pending\" there = model not finished when that file was made.", "",
              "| tumor | platform | GRCh38-only | v1.1 with site features | v1.1 nositef | v2.1 with site features | v2.1 nositef |",
              "|---|---|---|---|---|---|---|"]
    for tumor in TUMORS:
        for p in PLATFORMS:
            row = pts.get((tumor, plat(tumor, p)))

            def fig(k):
                if row is None:
                    return "n/a"
                r_, p_ = (num(row[i]) for i in col[k])
                return "pending" if r_ is None or p_ is None else f"{f1(p_, r_):.3f}"

            def ours(g):
                r = rep.get((tumor, p, g))
                return f"{r['pon']['at_threshold']['f1']:.3f}" if r else "pending"
            lines.append(f"| {tumor} | {plat(tumor, p)} | {fig('lin')} | {fig('v11')} | {ours('d9')} | {fig('v21')} | {ours('d46')} |")
    (HERE / "results.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
