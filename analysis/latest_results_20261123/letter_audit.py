def ds(tumor, p):
    return "COLO829T_fiberseq" if (tumor, p) == ("COLO829T", "PacBio") else f"{tumor}_{p}"


def pname(tumor, p):
    return {"Illumina": "Illumina", "ONT": "ONT", "PacBio": "Fiber-seq" if tumor == "COLO829T" else "PacBio HiFi"}[p]


def full(d):
    f = Path(d) / "eval_bed" / "report.json"
    return json.loads(f.read_text()) if f.exists() else None


def rep(d, stage="pon"):
    r = full(d)
    return r[stage]["at_threshold"] if r else None


def rule(kind, p):
    return "" if kind == "SNV" else ("pp_" if p == "ONT" else "ppr8_")


def cell_dir(n, kind, p, graph, tumor, seed=0, old_ont=False):
    """VCF directory of one multi-tumor model (n = 4 four-line, 6 six-tumor) on one test tumor, chr1."""
    r = rule(kind, p)
    if graph in ("linear_nositef", "d9"):
        return G / f"multicancer{n}_{p}_{kind}_{graph}" / f"vcf_{r}chr1_{tumor}"
    if kind == "INDEL":
        return R / f"{'release' if n == 6 else 'unseen'}_s{seed}_{p}_INDEL" / f"vcf_{r}chr1_{ds(tumor, p)}_d46"
    if p == "ONT" and old_ont:
        return R / f"multicancer{n}_ONT_SNV" / f"vcf_chr1_{ds(tumor, p)}_d46_normfix"
    if n == 6 or p == "ONT":
        return N / f"multicancer{n}_{p}_SNV_newpipe" / f"vcf_chr1_{ds(tumor, p)}_d46"
    af = "_snvaf05" if tumor == "COLO829T" else ""
    return R / f"multicancer4_{p}_SNV_sitef_af05_lnf25w1" / f"vcf_chr1_{ds(tumor, p)}_d46{af}_r095"


def colo_single(p, variant, seed=0, stage="pon"):
    """COLO829T single-tumor SNV model of the current pipeline; p in Illumina / fiberseq / ONT."""
    run = N / f"COLO829_{p}_SNV_{variant}{'' if seed == 0 else f'_s{seed}'}"
    d = sorted(run.glob(f"vcf_chr1_COLO829T_{p}*")) if run.exists() else []
    return rep(d[0], stage) if d else None


def prf(a):
    return "–" if a is None else f"{a['precision']:.3f} / {a['recall']:.3f} / {a['f1']:.3f}"


def f1s(cells):
    return " / ".join(format(c["f1"], ".3f") for c in cells if c)


def mean_prf(cells):
    cells = [c for c in cells if c]
    if not cells:
        return "–", 0
    m = {k: statistics.mean(c[k] for c in cells) for k in ("precision", "recall", "f1")}
    return prf(m), len(cells)


def comparator(caller, kind, tumor, p):
    e = json.loads((E8 / caller / ds(tumor, p) / kind / "report.json").read_text())
    return e["eval_bed"]["pass_pon"]["at_threshold"]


def table_after(path, heading):
    """The first Markdown table after the line that starts with `heading` (bold markers removed)."""
    lines = Path(path).read_text().splitlines()
    i = next(k for k, x in enumerate(lines) if x.startswith(heading))
    out = []
    for x in lines[i + 1:]:
        if x.startswith("|"):
            out.append(x.replace("**", ""))
        elif out:
            break
    return out


def letter_rows(heading):
    """Rows of a letter table as {first cell: [cells]}, highlight and bold markers removed."""
    rows = {}
    for x in table_after(LETTER, heading):
        c = [re.sub(r"</?mark>", "", y).strip() for y in x.strip().strip("|").split("|")]
        rows[c[0]] = c
    return rows


