#!/usr/bin/env python3
"""results.md: the six-tumor SNV models of the current pipeline on HPRC v2.1 with and without the haplotype-count
channel, chr1 of HCC1395T, COLO829T and HG008T on three platforms, benchmark BED, PASS at rule 2.
Without the channel (seed 0): eval_bed/report.json of this batch (after the population filter: "pon"; before: "raw").
With the channel: seeds 1 and 2 from the reports of ../m6_seeds_20261123; seed 0 (old cluster,
snv_newpipe_20261109/multicancer6_<P>_SNV_newpipe) has no report on storage2: P / R / F1 after the filter from
Supplementary Table R1.7b (r17b_latest.md) and before the filter from the ver4 letter table nofilter_snv
(ver4_20261123/tables/tables.json), both to three decimals, so the differences against seed 0 are differences of
rounded values. A cell whose job has not finished says "pending".
usage: python3 collect.py   (login node, standard library)"""
import importlib.util
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = Path("/storage2/fs1/epigenome/Active/jiawei.s/pansoma_net_v2_runs")
NOPC = RUNS / "m6_nopathcount_20261124"
SEEDS = RUNS / "m6_seeds_20261123"
NOFILTER = HERE.parent / "reviewer_response_20261011/ver4_20261123/tables/tables.json"
_spec = importlib.util.spec_from_file_location("seeds_collect", HERE.parent / "m6_seeds_20261123/collect.py")
S = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(S)
TUMORS = ("HG008T", "COLO829T", "HCC1395T")


def report(run, tumor, p):
    """{'pon': at_threshold, 'raw': at_threshold, 'epoch': best epoch} of a run on RIS, or None while pending."""
    f = run / f"vcf_chr1_{S.test_set(tumor, p)}" / "eval_bed" / "report.json"
    if not f.exists():
        return None
    r = json.loads(f.read_text())
    ep = next((ln.split()[3] for ln in (run / "train.log").read_text().splitlines() if ln.startswith("done; best epoch")), "")
    return {"pon": r["pon"]["at_threshold"], "raw": r["raw"]["at_threshold"], "epoch": ep}


def seed0_raw():
    """{'<tumor> <platform label>': (P, R, F1)} before the filter, HPRC v2.1 column of the ver4 table nofilter_snv."""
    t = json.loads(NOFILTER.read_text())["nofilter_snv"]
    col = next(i for i, h in enumerate(t["header"]) if "v2.1" in h)
    return {row[0]: tuple(float(x) for x in row[col].split(" / ")) for row in t["rows"]}


def fmt(x):
    return "" if x is None else f"{x:.3f}"


def delta(a, b):
    return "" if a is None or b is None else f"{a - b:+.3f}"


def main():
    s0, s0raw = S.seed0(), seed0_raw()
    md = ["# Six-tumor SNV models on HPRC v2.1 with and without the haplotype-count channel: chr1 results", "",
          "Generated by `collect.py`. chr1, benchmark BED; PASS = rule 2 (post-filter validation recall 0.95 of the callable "
          "positives). Without the channel: `m6_nopathcount_20261124/multicancer6_<P>_SNV_newpipe_nopc` (seed 0, "
          "`--drop-planes path_count`). With the channel: seed 0 `snv_newpipe_20261109/multicancer6_<P>_SNV_newpipe` (old "
          "cluster; P / R / F1 to three decimals from `r17b_latest.md` and the ver4 table `nofilter_snv`), seeds 1 and 2 "
          "`m6_seeds_20261123/multicancer6_<P>_SNV_newpipe_s<SEED>`.", "",
          "## Per model", "",
          "| tumor | platform | model | best epoch | truth | TP | FP | P | R | F1 | TP before the filter | FP before | F1 before |",
          "|" + "---|" * 13]
    rows = []
    for tumor in TUMORS:
        for p in S.PLATFORMS:
            key, truth = f"{tumor} {S.plat(tumor, p)}", set()
            cells = {}  # model -> (P, R, F1, F1 before)
            if key in s0:
                cells["with, seed 0"] = (*s0[key], s0raw[key][2])
                md.append(f"| {tumor} | {S.plat(tumor, p)} | with, seed 0 | | | | | {s0[key][0]:.3f} | {s0[key][1]:.3f} | "
                          f"{s0[key][2]:.3f} | | | {s0raw[key][2]:.3f} |")
            for label, run in (("with, seed 1", SEEDS / f"multicancer6_{p}_SNV_newpipe_s1"),
                               ("with, seed 2", SEEDS / f"multicancer6_{p}_SNV_newpipe_s2"),
                               ("without", NOPC / f"multicancer6_{p}_SNV_newpipe_nopc")):
                r = report(run, tumor, p)
                if r is None:
                    md.append(f"| {tumor} | {S.plat(tumor, p)} | {label} | pending |" + " |" * 9)
                    continue
                a, b = r["pon"], r["raw"]
                truth |= {a["tp_baseline"] + a["fn"], b["tp_baseline"] + b["fn"]}
                cells[label] = (a["precision"], a["recall"], a["f1"], b["f1"])
                md.append(f"| {tumor} | {S.plat(tumor, p)} | {label} | {r['epoch']} | {a['tp_baseline'] + a['fn']:,} | "
                          f"{a['tp_baseline']:,} | {a['fp']:,} | {a['precision']:.3f} | {a['recall']:.3f} | {a['f1']:.3f} | "
                          f"{b['tp_baseline']:,} | {b['fp']:,} | {b['f1']:.3f} |")
            assert len(truth) <= 1, (tumor, p, truth)
            rows.append((tumor, p, cells))
    md += ["", "## With − without the channel", "",
           "Δ = with, seed 0 − without (P, R, F1 after the filter; F1 before it). Seeds = F1 after the filter of the models "
           "with the channel.", "",
           "| tumor | platform | ΔP | ΔR | ΔF1 | ΔF1 before the filter | F1 with, seeds 0 / 1 / 2 | mean | F1 without | "
           "mean − without | seeds above the model without |", "|" + "---|" * 11]
    for tumor, p, cells in rows:
        w = cells.get("without")
        a = cells.get("with, seed 0")
        f1s = [cells[k][2] for k in ("with, seed 0", "with, seed 1", "with, seed 2") if k in cells]
        d = [delta(a[i], w[i]) if a and w else "" for i in range(4)]
        mean = statistics.mean(f1s) if f1s else None
        above = f"{sum(x > w[2] for x in f1s)} of {len(f1s)}" if w and f1s else ""
        md.append(f"| {tumor} | {S.plat(tumor, p)} | {d[0]} | {d[1]} | {d[2]} | {d[3]} | {' / '.join(fmt(x) for x in f1s)} | "
                  f"{fmt(mean)} | {fmt(w[2]) if w else 'pending'} | {delta(mean, w[2]) if w else ''} | {above} |")
    (HERE / "results.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
