"""Collect the E1.1 ch6 counterfactual outputs into results/tables.md and results/summary.json (standard library).

Reads, for every run of RUNS that has finished:
  /scratch/jshen/data/reviewer_experiments_20261013/E1.1_ch6_counterfactual/<run>/report.json  (ch6_counterfactual.py)
  .../<run>/report_assembly.json                (asm_scores.py, d46 runs, when present)
  .../linear_sampled/<run>/report.json          (ch6_counterfactual_sampled.py, GRCh38-only graph, when present)
and, for the base-mode check, the RIS GPU predict of the same checkpoint
  /scratch/jshen/data/pansoma_net_v2_runs/ris_7fc7396_20261012/<run>/test_chr1*/<set>.tensors.SNV.metrics.json
and the rtg vcfeval result after the PoN (in the BED) of analysis/benchmark_7fc7396_20261012/*/summary.json.
Runs without a report are listed as pending.

usage: python collect.py"""
import glob
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = Path("/scratch/jshen/data/reviewer_experiments_20261013/E1.1_ch6_counterfactual")
RIS = Path("/scratch/jshen/data/pansoma_net_v2_runs/ris_7fc7396_20261012")
BENCH = HERE.parents[2] / "benchmark_7fc7396_20261012"
RUNS = [  # (run, set, graph label)
    ("HG008_Illumina_SNV_7fc7396_ddp4_b1024", "HG008T_Illumina", "d9"),
    ("HG008_PacBio_SNV_7fc7396", "HG008T_PacBio", "d9"),
    ("HG008_ONT_SNV_7fc7396", "HG008T_ONT", "d9"),
    ("HG008_Illumina_SNV_d46_7fc7396", "HG008T_Illumina_d46", "d46"),
    ("HG008_PacBio_SNV_d46_7fc7396", "HG008T_PacBio_d46", "d46"),
    ("HG008_ONT_SNV_d46_7fc7396", "HG008T_ONT_d46", "d46"),
    ("COLO829_Illumina_SNV_d46_7fc7396", "COLO829T_Illumina_d46", "d46"),
    ("COLO829_fiberseq_SNV_d46_7fc7396", "COLO829T_fiberseq_d46", "d46"),
    ("COLO829_ONT_SNV_d46_7fc7396", "COLO829T_ONT_d46", "d46"),
    ("COLO829_Illumina_SNV_joint_7fc7396_gpu4", "COLO829T_Illumina", "d9 joint"),
    ("COLO829_fiberseq_SNV_joint_7fc7396_gpu4", "COLO829T_fiberseq", "d9 joint"),
    ("COLO829_ONT_SNV_joint_7fc7396_gpu4", "COLO829T_ONT", "d9 joint"),
    ("HG008_Illumina_SNV_linear_7fc7396", "HG008T_Illumina_linear", "linear"),
    ("HG008_PacBio_SNV_linear_7fc7396", "HG008T_PacBio_linear", "linear"),
    ("HG008_ONT_SNV_linear_7fc7396", "HG008T_ONT_linear", "linear"),
    ("COLO829_Illumina_SNV_linear_7fc7396", "COLO829T_Illumina_linear", "linear"),
    ("COLO829_fiberseq_SNV_linear_7fc7396", "COLO829T_fiberseq_linear", "linear"),
    ("COLO829_ONT_SNV_linear_7fc7396", "COLO829T_ONT_linear", "linear"),
]
MODES = ("base", "all_H", "train_mean", "train_median", "shuffle", "site0_low", "site0_high", "site10_low", "site10_high")


def short(run):
    return run.replace("_7fc7396", "").replace("_ddp4_b1024", "").replace("_gpu4", "").replace("_SNV", "")


def load(run):
    for f in (DATA / run / "report.json", DATA / "linear_sampled" / run / "report.json"):
        if f.exists():
            r = json.loads(f.read_text())
            a = f.parent / "report_assembly.json"
            if a.exists():
                r["assembly_report"] = json.loads(a.read_text())
            return r
    return None


def ris_metrics(run, set_name):
    files = glob.glob(str(RIS / run / "test_chr1*" / f"{set_name}.tensors.SNV.metrics.json"))
    return json.loads(Path(files[0]).read_text()) if files else None


def rtg_pon(run, set_name):
    """eval_bed PoN PASS result (rtg vcfeval in the BED after the PoN) of the run on the set in the benchmark
    summaries: HG008T d9 (`runs`), d46 / linear (lists of d9 / d46 / linear entries), COLO829T joint (`joint`, per
    purity: P100 = the set without suffix). None if absent."""
    def walk(x):
        if isinstance(x, dict):
            if x.get("run") == run:
                if "eval_bed" in x:
                    return x["eval_bed"].get("pon")
                for p in (x.get("purity") or {}).values():
                    if p.get("set") == set_name and "eval_bed" in p:
                        return p["eval_bed"].get("pon")
            for v in x.values():
                hit = walk(v)
                if hit:
                    return hit
        elif isinstance(x, list):
            for v in x:
                hit = walk(v)
                if hit:
                    return hit
        return None
    for f in sorted(BENCH.glob("*/summary.json")):
        hit = walk(json.loads(f.read_text()))
        if hit:
            return hit
    return None


def f3(x):
    return "" if x is None else f"{x:.3f}"


def main():
    reports = {run: load(run) for run, _, _ in RUNS}
    done = [(run, s, g) for run, s, g in RUNS if reports[run]]
    pending = [run for run, _, _ in RUNS if not reports[run]]
    L = ["# E1.1 ch6 counterfactual: chr1 SNV test tensors (generated by collect.py)", ""]
    if pending:
        L += ["Pending (no report yet): " + ", ".join(f"`{r}`" for r in pending), ""]

    L += ["## 1. Setup per run", "",
          "Site code = median ch6 code of the site column (50) over the rows that have one; codes are relative to the "
          "graph's haplotype count H (H -> 100). Training ch6 = valid cells of 3,000 random training tensors.", "",
          "| run | graph (H) | test tensors: somatic / germline / non on-ref / non off-ref | PASS threshold | training ch6 mean (checkpoint) / median / cells at 100 | LOW | site code median: somatic / germline / non on-ref / non off-ref |",
          "|---|---|---|---:|---|---:|---|"]
    for run, s, g in done:
        r = reports[run]
        b = r["results"]["base"]
        sc = r["params"]["site_code"]
        t = r["train_ch6"]
        sample = f" (sampled: {r['sampling']})" if r.get("sampling") else ""
        L.append(f"| `{short(run)}` | {g} ({r['haplotypes']}) | {b['somatic']['n']:,} / {b['germline']['n']:,} / "
                 f"{b['non_onref']['n']:,} / {b['non_offref']['n']:,}{sample} | {r['threshold_val_recall_0_9']:.3f} | "
                 f"{t['mean']:.1f} ({t['checkpoint_mean']:.1f}) / {t['median']} / {t['frac_100']:.2f} | {r['params']['low']} | "
                 + " / ".join("" if sc[k]["median"] is None else f"{sc[k]['median']:.0f}" for k in ("somatic", "germline", "non_onref", "non_offref")) + " |")

    L += ["", "## 2. Base mode against the RIS GPU predict of the same checkpoint and against rtg", "",
          "CPU fp32 here against the GPU bf16 `predict` of 2026-10-12 (same test tensors, same threshold); rtg = vcfeval "
          "in the BED after the PoN (PASS records; merged GRCh38 alleles, unplaced calls not scored), against this "
          "script's per-tensor PoN (on-reference tensors only).", "",
          "| run | somatic AP: CPU / GPU | calls >= t: CPU / GPU | germline >= t: CPU / GPU | truth TP / FP: CPU / GPU | after PoN TP / FP: per tensor / rtg |",
          "|---|---|---|---|---|---|"]
    for run, s, g in done:
        b = reports[run]["results"]["base"]
        m = ris_metrics(run, s)
        rt = rtg_pon(run, s)
        if m:
            v = m["rules"]["val_recall_0.9"]
            gcalls = v["confusion"][2][1]
            gpu = (f"{m['somatic_ap']:.4f}", f"{v['per_tensor']['calls']:,}", f"{gcalls:,}", f"{v['truth']['tp']} / {v['truth']['fp']:,}")
        else:
            gpu = ("", "", "", "")
        L.append(f"| `{short(run)}` | {b['somatic_ap']:.4f} / {gpu[0]} | {b['calls_ge_thr']:,} / {gpu[1]} | "
                 f"{b['germline']['ge_thr']:,} / {gpu[2]} | {b['truth']['tp']} / {b['truth']['fp']:,} / {gpu[3]} | "
                 f"{b['truth_after_pon']['tp']} / {b['truth_after_pon']['fp']:,} / "
                 + (f"{rt['tp']} / {rt['fp']}" if rt else "") + " |")

    L += ["", "## 3. Per run and mode", "",
          "p >= t: p_somatic at or above the run's validation recall-0.9 threshold (the PASS rule). Truth: every chr1 "
          "somatic truth SNV once (its best tensor). After PoN: on-reference tensors whose GRCh38 allele is not in the "
          "four PoNs (SNV rule). x base: germline tensors >= t relative to base."]
    for run, s, g in done:
        r = reports[run]
        res = r["results"]
        b = res["base"]
        L += ["", f"### `{run}` ({g}, set `{s}`, t = {r['threshold_val_recall_0_9']:.3f}, LOW = {r['params']['low']})", "",
              "| mode | somatic AP (delta) | somatic >= t / n (median p) | germline >= t (x base) | non on-ref >= t | non off-ref >= t | truth TP / FP / F1 | after PoN TP / FP / F1 |",
              "|---|---|---|---|---|---|---|---|"]
        for mode in MODES:
            x = res.get(mode)
            if not x:
                continue
            gb = b["germline"]["ge_thr"]
            ratio = f"{x['germline']['ge_thr'] / gb:.2f}" if gb else ""
            L.append(f"| {mode} | {x['somatic_ap']:.4f} ({x['somatic_ap'] - b['somatic_ap']:+.4f}) | "
                     f"{x['somatic']['ge_thr']:,} / {x['somatic']['n']:,} ({f3(x['somatic']['p_median'])}) | "
                     f"{x['germline']['ge_thr']:,} ({ratio}) | {x['non_onref']['ge_thr']:,} | {x['non_offref']['ge_thr']:,} | "
                     f"{x['truth']['tp']} / {x['truth']['fp']:,} / {x['truth']['f1']:.3f} | "
                     f"{x['truth_after_pon']['tp']} / {x['truth_after_pon']['fp']:,} / {x['truth_after_pon']['f1']:.3f} |")

    L += ["", "## 4. Across runs", ""]
    for title, fn in (("Somatic AP per tensor", lambda x: f"{x['somatic_ap']:.3f}"),
                      ("Germline tensors with p_somatic >= t", lambda x: f"{x['germline']['ge_thr']:,}"),
                      ("Truth SNVs found at t (of the chr1 truth)", lambda x: f"{x['truth']['tp']}"),
                      ("Truth-level F1 at t after the per-tensor PoN", lambda x: f"{x['truth_after_pon']['f1']:.3f}")):
        L += [f"**{title}**", "", "| run | " + " | ".join(MODES) + " |", "|---|" + "---:|" * len(MODES)]
        for run, s, g in done:
            res = reports[run]["results"]
            L.append(f"| `{short(run)}` | " + " | ".join(fn(res[m]) if m in res else "-" for m in MODES) + " |")
        L.append("")

    L += ["## 5. Assembly off-reference somatic SNVs (HG008T)", "",
          "Keys of `assembly_offref_20260929/offref_somatic.tsv` (d9) and of `asm_d46_classify.py` (d46) with a tensor in the "
          "set, all autosomes (none is a training label). Cells: p_somatic >= t / argmax somatic / n (chr1: >= t / n).", "",
          "| run | " + " | ".join(MODES) + " |", "|---|" + "---|" * len(MODES)]
    for run, s, g in done:
        r = reports[run]
        res = {m: v.get("assembly") for m, v in r["results"].items() if v.get("assembly")}
        if not res and "assembly_report" in r:
            res = r["assembly_report"]["summary"]
        if not res:
            continue
        L.append(f"| `{short(run)}` | " + " | ".join(
            f"{res[m]['ge_thr']} / {res[m]['argmax_somatic']} / {res[m]['n']} (chr1 {res[m]['chr1_ge_thr']} / {res[m]['chr1_n']})"
            if m in res else "-" for m in MODES) + " |")
    out = HERE / "results"
    out.mkdir(exist_ok=True)
    pa = out / "profile_auc.json"
    if pa.exists():
        prof = json.loads(pa.read_text())
        L += ["", "## 6. ch6 alone: somatic against germline test tensors (profile_auc.py, no model)", "",
              "AUC of a single ch6 summary of the base tensors (higher site code, fewer cells below 100, fewer distinct codes "
              "in columns 40-60 = more somatic); medians somatic / germline.", "",
              "| run | somatic / germline tensors | site code: AUC (medians) | cells below 100: AUC (medians) | distinct codes +-10: AUC (medians) |",
              "|---|---|---|---|---|"]
        for run, s, g in RUNS:
            if run in prof:
                p = prof[run]
                L.append(f"| `{short(run)}` | {p['somatic']:,} / {p['germline']:,} | {p['auc_site']:.3f} ({p['median_site_somatic']:.0f} / "
                         f"{p['median_site_germline']:.0f}) | {p['auc_below']:.3f} ({p['median_below_somatic']:.3f} / "
                         f"{p['median_below_germline']:.3f}) | {p['auc_distinct']:.3f} ({p['median_distinct_somatic']:.0f} / "
                         f"{p['median_distinct_germline']:.0f}) |")
    (out / "tables.md").write_text("\n".join(L) + "\n")
    slim = {}
    for run, s, g in done:
        r = dict(reports[run])
        r["train_ch6"] = {k: v for k, v in r["train_ch6"].items() if k != "hist"}
        r.pop("assembly_report", None)
        slim[run] = {**r, "set": s, "graph": g}
    (out / "summary.json").write_text(json.dumps(dict(done=[r for r, _, _ in done], pending=pending, runs=slim), indent=1) + "\n")
    asm = {}
    for run, s, g in done:
        r = reports[run]
        keys = r.get("assembly_keys") or (r.get("assembly_report") or {}).get("assembly_keys")
        if keys:
            asm[run] = keys
    (out / "assembly_keys.json").write_text(json.dumps(asm, indent=1) + "\n")
    print(f"{len(done)} runs done, {len(pending)} pending -> {out}/tables.md")


if __name__ == "__main__":
    main()
