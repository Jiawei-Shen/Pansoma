"""E3b collect: tables.md + summary.json from the re-calls of variant_calls.sh.

1. SNV, off-reference rescue on (the run's vcf_chr1) vs off (<run>__norescue/vcf_chr1): PoN TP / FP / FN of the placed
   calls (rtg), graph-coordinate (unplaced) PASS calls, and the complete-output F1 = 2TP / (2TP + FP + FN + U), every
   graph-coordinate PASS call counted as a false positive (they have no GRCh38 position, so the BED cannot be applied
   to them); in the BED and without it.
2. INDEL, PASS at the validation recall-0.9 threshold (vcf_chr1) vs at the validation-chosen best truth-level F1
   threshold (vcf_chr1_valbest, chosen on chr2-22 validation blocks): PoN P / R / F1, and the chr1 curve's best F1
   (test-tuned upper bound) for reference.
Standard library only."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
S = Path("/scratch/jshen/data/pansoma_net_v2_runs/reviewer_cpu_20261013")


def rep(d, ev):
    f = d / ev / "report.json"
    return json.loads(f.read_text()) if f.exists() else None


def f(v, spec=".3f"):
    return "-" if v is None else format(v, spec)


def arm(run):
    return "linear" if "_linear_" in run else "d46" if "_d46_" in run else "d9 joint" if "_joint_" in run else "d9"


def complete_f1(r):
    p = r["pon"]["at_threshold"]; u = r["unplaced_pass"]
    tp, fp, fn = p["tp_baseline"], p["fp"], p["fn"]
    return tp, fp, fn, u, 2 * tp / (2 * tp + fp + fn + u)


def main():
    L = ["# E3b: SNV without the off-reference rescue; INDEL at a validation-chosen threshold (generated by collect.py)", ""]
    snv, indel = [], []
    for d in sorted(S.iterdir()):
        r = d.name
        if r.startswith("xs__") or r.endswith("__norescue"):
            continue
        if "_SNV_" in r and (S / f"{r}__norescue").exists():
            for ev in ("eval_bed", "eval_nobed"):
                on, off = rep(d / "vcf_chr1", ev), rep(S / f"{r}__norescue" / "vcf_chr1", ev)
                if on and off:
                    a, b = complete_f1(on), complete_f1(off)
                    snv.append(dict(run=r, arm=arm(r), eval=ev, placed_f1=on["pon"]["at_threshold"]["f1"],
                                    on=dict(zip(("tp", "fp", "fn", "unplaced", "complete_f1"), a)),
                                    off=dict(zip(("tp", "fp", "fn", "unplaced", "complete_f1"), b))))
        if "_INDEL_" in r and (d / "vcf_chr1_valbest").exists():
            thr = (d / "valbest_threshold.txt").read_text().strip() if (d / "valbest_threshold.txt").exists() else ""
            for ev in ("eval_bed", "eval_nobed"):
                a, b = rep(d / "vcf_chr1", ev), rep(d / "vcf_chr1_valbest", ev)
                if a and b:
                    pa, pb = a["pon"]["at_threshold"], b["pon"]["at_threshold"]
                    indel.append(dict(run=r, arm=arm(r), eval=ev, thr_r09=a["threshold"] if a["threshold"] is not None else float("nan"),
                                      thr_valbest=float(thr) if thr else (b["threshold"] if b["threshold"] is not None else float("nan")),
                                      r09=dict(tp=pa["tp_baseline"], fp=pa["fp"], p=pa["precision"], r=pa["recall"], f1=pa["f1"]),
                                      valbest=dict(tp=pb["tp_baseline"], fp=pb["fp"], p=pb["precision"], r=pb["recall"], f1=pb["f1"]),
                                      best_f1=a["pon"].get("best", {}).get("f1")))
    L += ["## 1. SNV: off-reference rescue on vs off (chr1, after the PoN)", "",
          "| run | arm | eval | placed F1 (rtg; same on / off) | rescue ON: graph-coordinate PASS / complete-output F1 | rescue OFF: graph-coordinate PASS / complete-output F1 |",
          "|---|---|---|---:|---|---|"]
    for x in snv:
        L.append(f"| `{x['run']}` | {x['arm']} | {x['eval']} | {x['placed_f1']:.4f} | {x['on']['unplaced']:,} / {x['on']['complete_f1']:.4f} | "
                 f"{x['off']['unplaced']:,} / {x['off']['complete_f1']:.4f} |")
    L += ["", "## 2. INDEL: PASS at the validation recall-0.9 threshold vs at the validation-chosen best-F1 threshold (chr1, after the PoN)", "",
          "| run | arm | eval | threshold r0.9 / valbest | r0.9: TP / FP, P / R / F1 | valbest: TP / FP, P / R / F1 | chr1 best F1 (test-tuned) |",
          "|---|---|---|---|---|---|---:|"]
    for x in indel:
        a, b = x["r09"], x["valbest"]
        L.append(f"| `{x['run']}` | {x['arm']} | {x['eval']} | {f(x['thr_r09'], '.4g')} / {f(x['thr_valbest'], '.4g')} | "
                 f"{a['tp']} / {a['fp']}, {f(a['p'])} / {f(a['r'])} / **{f(a['f1'])}** | {b['tp']} / {b['fp']}, {f(b['p'])} / "
                 f"{f(b['r'])} / **{f(b['f1'])}** | {f(x['best_f1'])} |")
    (HERE / "tables.md").write_text("\n".join(L) + "\n")
    (HERE / "summary.json").write_text(json.dumps(dict(snv=snv, indel=indel), indent=1) + "\n")
    print(f"{len(snv)} SNV rows, {len(indel)} INDEL rows")


if __name__ == "__main__":
    main()
