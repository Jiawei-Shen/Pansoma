"""E8 add-on (R2.3, 2026-10-21; the user: "用最新的数据"): the comparators of E8 against Pansoma's latest models, chr1, in the
benchmark BED, PASS after our population filter (PoN), same scoring as collect.py.

Pansoma's latest models (RIS, `analysis/benchmark_7fc7396_20261012/reviewer_gpu_7fc7396_20261016/tables.md`):
  SNV    `--norm dataset` (BQ per dataset, f344bca), three seeds per arm: <S>_<P>_SNV_{d46,d9}_normbq{,_s1,_s2};
         COLO829T Illumina d9 at epochs 6 / 5 / 6 (the user, 2026-10-20): COLO829_Illumina_SNV_d9_normbq{_sweep_e06,
         _s1_sweep_e05,_s2_sweep_e06}.
  INDEL  Illumina: <S>_Illumina_INDEL_{d46,d9}_normbq (one seed); PacBio-fiberseq / ONT have no `--norm dataset` run (the
         recipe is unchanged there): the matched-recipe runs <S>_<P>_INDEL_{d46_,}7fc7396 re-scored with the current INDEL
         rule (vcf_chr1_pon71cb51a).
Every Pansoma report is <run>/vcf_chr1*/eval_bed/report.json (jobs/vcf.sh; pon at_threshold = PASS at the validation
recall-0.9 threshold, after the PoN); INDEL reports are checked to carry the current rule (HG008T 418 / COLO829T 81 truth
INDELs tagged). Comparators: the E8 score reports (`pass_pon` = the tool's PASS + our PoN).

Also: COLO829T Illumina SNV recall split at the 0.08 candidate floor by the truth's Illumina VAF (INFO VAF_Ill), from
rtg's tp-baseline / fn of each call set.
Writes latest_models.md and latest_models.json next to this script.
usage: /wanglab/jshen/anaconda3/bin/python latest_models.py
"""
import gzip
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RIS = Path("/scratch/jshen/data/pansoma_net_v2_runs/ris_7fc7396_20261012")
E8 = Path("/scratch/jshen/data/reviewer_experiments_20261013/E8_comparators/score")
CALLERS = (("clairs_to", "ClairS-TO"), ("deepsomatic", "DeepSomatic-TO"))
SETS = [("HG008T", "HG008", p) for p in ("Illumina", "PacBio", "ONT")] + \
       [("COLO829T", "COLO829", p) for p in ("Illumina", "fiberseq", "ONT")]
PON_TAGGED = {"HG008T": 418, "COLO829T": 81}  # truth INDELs tagged by the current INDEL rule (chr1, BED)
FLOOR = 0.08


def snv_runs(s, p, arm):
    if (s, p, arm) == ("COLO829", "Illumina", "d9"):
        return [f"{s}_{p}_SNV_d9_normbq_sweep_e06", f"{s}_{p}_SNV_d9_normbq_s1_sweep_e05", f"{s}_{p}_SNV_d9_normbq_s2_sweep_e06"]
    return [f"{s}_{p}_SNV_{arm}_normbq{x}" for x in ("", "_s1", "_s2")]


def indel_runs(s, p, arm):
    if p == "Illumina":
        return [f"{s}_{p}_INDEL_{arm}_normbq"]
    return [f"{s}_{p}_INDEL_{'d46_' if arm == 'd46' else ''}7fc7396"]


def report(run, kind):
    order = ("vcf_chr1_pon71cb51a", "vcf_chr1") if kind == "INDEL" else ("vcf_chr1",)
    for v in order:
        f = RIS / run / v / "eval_bed" / "report.json"
        if f.exists():
            return json.loads(f.read_text()), f
    raise FileNotFoundError(f"{run}: no eval_bed report")


def at(block):
    a = block["at_threshold"]
    return dict(p=a["precision"], r=a["recall"], f1=a["f1"], tp=a["tp_baseline"], fp=a["fp"], fn=a["fn"])


def vaf_split(vcfeval_dir):
    """(recall below FLOOR, n below, recall at/above FLOOR, n above) from tp-baseline / fn by INFO VAF_Ill."""
    hit = {True: [0, 0], False: [0, 0]}
    for name, is_tp in (("tp-baseline.vcf.gz", 1), ("fn.vcf.gz", 0)):
        with gzip.open(vcfeval_dir / name, "rt") as fh:
            for line in fh:
                if line.startswith("#"):
                    continue
                info = dict(kv.split("=", 1) for kv in line.split("\t")[7].split(";") if "=" in kv)
                low = float(info["VAF_Ill"]) < FLOOR
                hit[low][0] += is_tp
                hit[low][1] += 1
    return hit[True][0] / hit[True][1], hit[True][1], hit[False][0] / hit[False][1], hit[False][1]


def main():
    out = dict(rows=[], vaf_split=[])
    L = ["# E8 comparators against Pansoma's latest models (chr1, benchmark BED, PASS after our PoN)", "",
         "Generated by `latest_models.py`. Pansoma: `--norm dataset` SNV models, three seeds per arm (COLO829T Illumina "
         "v1.1 at epochs 6 / 5 / 6); INDEL: Illumina `--norm dataset` (one seed), long reads the matched-recipe runs under "
         "the current INDEL rule. Cells: P / R / F1; Pansoma seeds as min-max.", ""]
    for kind in ("SNV", "INDEL"):
        L += [f"## {kind}", "", "| dataset | ClairS-TO | DeepSomatic-TO | Pansoma v2.1 (d46) | Pansoma v1.1 (d9) | Pansoma runs |",
              "|---|---|---|---|---|---|"]
        for sample, s, p in SETS:
            ds = f"{sample}_{p}"
            cells, row = [], dict(dataset=ds, kind=kind)
            for c, label in CALLERS:
                r = json.loads((E8 / c / ds / kind / "report.json").read_text())["eval_bed"]["pass_pon"]["at_threshold"]
                v = dict(p=r["precision"], r=r["recall"], f1=r["f1"])
                row[c] = v
                cells.append(f"{v['p']:.3f} / {v['r']:.3f} / {v['f1']:.3f}")
            names = []
            for arm in ("d46", "d9"):
                runs = snv_runs(s, p, arm) if kind == "SNV" else indel_runs(s, p, arm)
                vals = []
                for run in runs:
                    rep, f = report(run, kind)
                    if kind == "INDEL":
                        assert rep["truth_pon_tags"]["tagged"] == PON_TAGGED[sample], (run, rep["truth_pon_tags"])
                    vals.append(dict(run=run, report=str(f), **at(rep["pon"])))
                row[arm] = vals
                rng = lambda k: (f"{min(v[k] for v in vals):.3f}" if len(vals) == 1 else  # noqa: E731
                                 f"{min(v[k] for v in vals):.3f}-{max(v[k] for v in vals):.3f}")
                cells.append(f"{rng('p')} / {rng('r')} / {rng('f1')}")
                names.append(", ".join(f"`{v['run']}`" for v in vals))
            out["rows"].append(row)
            L.append(f"| {ds} | " + " | ".join(cells) + f" | {'; '.join(names)} |")
        L.append("")
    # VAF split, COLO829T Illumina SNV
    L += [f"## COLO829T Illumina SNV: recall below / at or above the {FLOOR} candidate floor (truth VAF_Ill)", "",
          "| call set | recall VAF < 0.08 (n) | recall VAF >= 0.08 (n) |", "|---|---|---|"]
    sets = [(label, E8 / c / "COLO829T_Illumina" / "SNV" / "eval_bed" / "pass_pon") for c, label in CALLERS]
    for arm in ("d46", "d9"):
        for run in snv_runs("COLO829", "Illumina", arm):
            sets.append((f"Pansoma {arm} `{run}`", RIS / run / "vcf_chr1" / "eval_bed" / "vcfeval" / "pon_calls"))
    for label, d in sets:
        lo, nlo, hi, nhi = vaf_split(d)
        out["vaf_split"].append(dict(call_set=label, dir=str(d), recall_low=lo, n_low=nlo, recall_high=hi, n_high=nhi))
        L.append(f"| {label} | {lo:.3f} ({nlo}) | {hi:.3f} ({nhi}) |")
    # funnel with the latest models: E1.6's per-run n and no-tensor counts (model-independent: the tensor set) and each
    # run's rtg TPs before / after the PoN: below threshold = n - no tensor - raw TP, PoN = raw TP - PoN TP, called = PoN TP
    e16 = json.loads((HERE.parent / "E1.6_recall_funnel" / "summary.json").read_text())["runs"]
    L += ["", "## HG008T SNV funnel with the latest models (chr1, BED; % of E1.6's truth n)", "",
          "no tensor from E1.6 (the 7fc7396 run on the same tensor set); the other stages from each run's report.", "",
          "| run | n | no tensor | tensor, below threshold | PASS, PoN-tagged | called |", "|---|---:|---:|---:|---:|---:|"]
    out["funnel"] = []
    for p in ("Illumina", "PacBio", "ONT"):
        for arm, ref in (("d9", f"HG008_{p}_SNV_7fc7396{'_ddp4_b1024' if p == 'Illumina' else ''}"), ("d46", f"HG008_{p}_SNV_d46_7fc7396")):
            f = e16[f"{ref}__vcf_chr1"]["funnel"]
            for run in snv_runs("HG008", p, arm):
                rep, _ = report(run, "SNV")
                raw, pon = rep["raw"]["at_threshold"]["tp_baseline"], rep["pon"]["at_threshold"]["tp_baseline"]
                st = dict(run=run, arm=arm, n=f["n"], no_tensor=f["no_tensor"], below=f["n"] - f["no_tensor"] - raw,
                          pon=raw - pon, called=pon)
                out["funnel"].append(st)
                pc = lambda k: f"{100 * st[k] / st['n']:.1f} %"  # noqa: E731
                L.append(f"| `{run}` | {st['n']} | {pc('no_tensor')} | {pc('below')} | {pc('pon')} | {pc('called')} |")
    # R1.6: per-arm recall before the PoN (raw PASS), after it (PASS), the post-filter curve maximum, and the recall on
    # Pansoma's post-filter curve at each comparator's PASS + PoN precision (seed min-max and mean)
    L += ["", "## R1.6: recall per arm (seeds min-max; mean)", "",
          "raw PASS = PASS before the PoN; PASS = after it; ceiling = highest recall on the post-filter curve; at ClairS-TO / "
          "DeepSomatic P = Pansoma's recall on its post-filter curve at precision >= that comparator's PASS + PoN precision.", "",
          "| dataset | kind | arm | truth with a tensor | raw PASS R | PASS R | ceiling | R at ClairS-TO P | R at DeepSomatic P |",
          "|---|---|---|---|---|---|---|---|---|"]
    out["r16"] = []
    mm = lambda xs: (f"{min(xs):.3f}-{max(xs):.3f}; {sum(xs) / len(xs):.3f}" if len(xs) > 1 else f"{xs[0]:.3f}")  # noqa: E731
    for kind in ("SNV", "INDEL"):
        for sample, s, p in SETS:
            ds = f"{sample}_{p}"
            comp_p = {c: json.loads((E8 / c / ds / kind / "report.json").read_text())["eval_bed"]["pass_pon"]["at_threshold"]["precision"]
                      for c, _ in CALLERS}
            for arm in ("d46", "d9"):
                runs = snv_runs(s, p, arm) if kind == "SNV" else indel_runs(s, p, arm)
                vals = dict(raw=[], r=[], ceil=[], clairs_to=[], deepsomatic=[])
                for run in runs:
                    rep, _ = report(run, kind)
                    vals["raw"].append(rep["raw"]["at_threshold"]["recall"])
                    vals["r"].append(rep["pon"]["at_threshold"]["recall"])
                    vals["ceil"].append(rep["pon"]["ceiling"])
                    roc = rep["pon"]["curve_roc"]
                    for c in comp_p:
                        hits = [x["recall"] for x in roc if x["precision"] >= comp_p[c] - 1e-9]
                        vals[c].append(max(hits) if hits else float("nan"))
                # truth alleles with a tensor (the predict truth report of the tensor set; model-independent, partial
                # matches included as in the R1.6 v1.1 table)
                m = json.loads(next((RIS / runs[0] / "test_chr1").glob("*.metrics.json")).read_text())["truth"]
                reach = m["with_tensor"] / m["truth_alleles"]
                out["r16"].append(dict(dataset=ds, kind=kind, arm=arm, runs=runs, comparator_precision=comp_p,
                                       reach_candidate=reach, **vals))
                L.append(f"| {ds} | {kind} | {arm} | {reach:.3f} | {mm(vals['raw'])} | {mm(vals['r'])} | {mm(vals['ceil'])} | "
                         f"{mm(vals['clairs_to'])} | {mm(vals['deepsomatic'])} |")
    # INDEL: the final models of the INDEL pipeline (9919d4a; PASS = post-PoN validation recall 0.8 of the callable
    # positives, "ppr8"; tmp/indel_gap_20261020/final_20261023): release = trained with chr2-22 of every tumor (HG008T and
    # COLO829T included), unseen = without HG008T / COLO829T; Illumina 3 seeds, long reads 2
    L += ["", "## INDEL, final models (ppr8), chr1: recall / precision per seed against the comparators' PASS + PoN", "",
          "| dataset | model | seeds | recall (mean) | precision (mean) | ClairS-TO R / P | DeepSomatic-TO R / P |", "|---|---|---|---|---|---|---|"]
    out["indel_final"] = []
    for sample, s, p in SETS:
        ds = f"{sample}_{p}"
        comp = {c: json.loads((E8 / c / ds / "INDEL" / "report.json").read_text())["eval_bed"]["pass_pon"]["at_threshold"]
                for c, _ in CALLERS}
        tset = f"{sample}_{p}_d46"
        plat = "PacBio" if p == "fiberseq" else p
        for model in ("release", "unseen"):
            vals = []
            for seed in ("s0", "s1", "s2"):
                f = RIS.parent / f"{model}_{seed}_{plat}_INDEL" / f"vcf_ppr8_chr1_{tset}" / "eval_bed" / "report.json"
                if f.exists():
                    a = json.loads(f.read_text())["pon"]["at_threshold"]
                    vals.append(dict(seed=seed, report=str(f), p=a["precision"], r=a["recall"], f1=a["f1"]))
            if not vals:
                continue
            out["indel_final"].append(dict(dataset=ds, model=model, seeds=vals,
                                           comparators={c: dict(r=v["recall"], p=v["precision"]) for c, v in comp.items()}))
            L.append(f"| {ds} | {model} | {len(vals)} | {mm([v['r'] for v in vals])} | {mm([v['p'] for v in vals])} | "
                     f"{comp['clairs_to']['recall']:.3f} / {comp['clairs_to']['precision']:.3f} | "
                     f"{comp['deepsomatic']['recall']:.3f} / {comp['deepsomatic']['precision']:.3f} |")
    (HERE / "latest_models.md").write_text("\n".join(L) + "\n")
    (HERE / "latest_models.json").write_text(json.dumps(out, indent=1) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
