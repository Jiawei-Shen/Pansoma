"""E8 add-on (2026-10-29): ClairS-TO and DeepSomatic-TO on the COLO829T purity mixtures (P75 / P50 / P25) under the same
chr1 protocol as P100 (score_comparator.py: benchmark BED, PASS after our PoN), next to their P100 rows.

The VCFs are the user's existing tumor-only runs of the original manuscript (/scratch/jshen/Pansoma_testing_results_V2/
COLO829T_{WGS,Pacbio,ONT}/{clairs-to,deepsomatic-to}_INDEL_COLO829_*_chr1_P*/; despite the "INDEL" in the directory
names, each holds the run's full output) on the in-silico mixture BAMs
/scratch/jshen/data/COLO829T/Tumor_Normal_inSilico_Mix/COLO829_{WGS,Pacbio,ONT}/MIX_p*_*.mixed.sorted.bam. Scored by
tmp/E8_purity_20261029/score.sh (array 461262) into score/<caller>/COLO829T_<platform>_P<q>/<KIND>/. The original
manuscript's evaluation of the same VCFs (rtg --region chr1, no BED, the tools' own filters only) is in the same
directories (*_SNV_rtg_chr1_*_p*.somatic); its F1 is listed for comparison.
Writes purity_comparators.md and purity_comparators.json next to this script.
usage: /wanglab/jshen/anaconda3/bin/python purity_comparators.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCORE = Path("/scratch/jshen/data/reviewer_experiments_20261013/E8_comparators/score")
V2 = Path("/scratch/jshen/Pansoma_testing_results_V2")
CALLERS = (("clairs_to", "ClairS-TO", "clairs-to"), ("deepsomatic", "DeepSomatic-TO", "deepsomatic-to"))
PLATFORMS = (("Illumina", "WGS", "wgs"), ("fiberseq", "Pacbio", "pacbio"), ("ONT", "ONT", "ont"))
PURITIES = ("P100", "P75", "P50", "P25")


def scored(caller, platform, purity, kind):
    ds = f"COLO829T_{platform}" + ("" if purity == "P100" else f"_{purity}")
    f = SCORE / caller / ds / kind / "report.json"
    if not f.exists():
        return None
    rep = json.loads(f.read_text())
    out = {"report": str(f)}
    for cs in ("pass", "pass_pon"):
        a = rep["eval_bed"][cs]["at_threshold"]
        out[cs] = dict(p=a["precision"], r=a["recall"], f1=a["f1"], tp=a["tp_baseline"], fp=a["fp"], fn=a["fn"])
    out["truth_tagged"] = (rep.get("truth_pon_tags") or {}).get("tagged")
    return out


def old_snv_f1(tool, v2dir, short, purity):
    """F1 of the original manuscript's rtg run (no BED, tools' own filters), from summary.txt's 'None' row."""
    f = V2 / f"COLO829T_{v2dir}" / f"{tool}_SNV_rtg_chr1_{short}_{purity.lower()}.somatic" / "summary.txt"
    if not f.exists():
        return None
    for line in f.read_text().splitlines():
        c = line.split()
        if c and c[0] == "None":
            return float(c[-1])
    return None


def main():
    out, L = [], ["# ClairS-TO / DeepSomatic-TO on the COLO829T purity mixtures (chr1, benchmark BED)", "",
                  "Generated by `purity_comparators.py`. Cells: P / R / F1 of the tool's PASS after our PoN "
                  "(score_comparator.py `eval_bed.pass_pon`; P100 = the E8 re-score of section 9). 'orig F1' = the "
                  "original manuscript's evaluation of the same SNV VCFs (rtg --region chr1, no BED, tools' own "
                  "filters only).", ""]
    for kind in ("SNV", "INDEL"):
        L += [f"## {kind}", "", "| platform | caller | " + " | ".join(PURITIES) +
              (" | orig F1 P100 / P75 / P50 / P25 |" if kind == "SNV" else " |"),
              "|---|---|" + "---|" * len(PURITIES) + ("---|" if kind == "SNV" else "")]
        for platform, v2dir, short in PLATFORMS:
            for caller, label, tool in CALLERS:
                cells, row = [], dict(kind=kind, platform=platform, caller=label, purities={})
                for q in PURITIES:
                    s = scored(caller, platform, q, kind)
                    row["purities"][q] = s
                    cells.append("-" if s is None else
                                 f"{s['pass_pon']['p']:.3f} / {s['pass_pon']['r']:.3f} / {s['pass_pon']['f1']:.3f}")
                line = f"| {platform} | {label} | " + " | ".join(cells)
                if kind == "SNV":
                    olds = [old_snv_f1(tool, v2dir, short, q) for q in PURITIES]
                    row["orig_snv_f1"] = olds
                    line += " | " + " / ".join("-" if x is None else f"{x:.3f}" for x in olds)
                L.append(line + " |")
                out.append(row)
        L.append("")
    tags = sorted({(r["kind"], s["truth_tagged"]) for r in out for s in r["purities"].values() if s})
    L += ["Truth records tagged by our PoN (chr1, per kind; the same truth at every purity): " +
          ", ".join(f"{k} {t}" for k, t in tags) + "."]
    (HERE / "purity_comparators.md").write_text("\n".join(L) + "\n")
    (HERE / "purity_comparators.json").write_text(json.dumps(out, indent=1) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
