"""E21 step 4: markdown tables (tables.md) from the TSVs of collect_runs.py and summarize.py. Standard library only.

    python make_tables.py
"""
import csv
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent


def read(name):
    p = HERE / name
    if not p.exists():
        return []
    with open(p) as f:
        return list(csv.DictReader(f, delimiter="\t"))


def n(x):
    return "-" if x in (None, "") else f"{int(float(x)):,}"


def f3(x):
    return "-" if x in (None, "") else f"{float(x):.3f}"


def f2(x):
    return "-" if x in (None, "") else f"{float(x):.2f}"


def pct(x):
    return "-" if x in (None, "") else f"{100 * float(x):.1f} %"


def main():
    L = ["# E21 tables (generated by make_tables.py from the TSVs in this folder)", ""]
    runs = read("runs_training.tsv")
    check = {r["run"]: r for r in read("runs_replay_check.tsv")}
    L += ["## T1. Every trained model: training / validation tensors, epochs, validation metrics",
          "",
          "train / val = tensors per class (non / somatic / germline) as train.log reports them; left out = tensors with "
          "a partial somatic match (--ignore-reasons) in the training / validation blocks; replay = the split re-derived "
          "from the index caches (summarize.py) gives exactly these counts (yes / no / - not checked); val loss min (ep) = "
          "lowest validation loss and its epoch, last = at the final epoch; AP = validation somatic average precision at "
          "the best epoch (the checkpoint); PASS thr = the checkpoint's validation recall-0.9 threshold.",
          "",
          "| run | arm | params (M) | train non / somatic / germline | val non / somatic / germline | left out train / val | "
          "replay | epochs (best) | train loss best / last | val loss best / min (ep) / last | val somatic AP | PASS thr |",
          "|---|---|---:|---|---|---|---|---|---|---|---:|---:|"]
    for r in runs:
        c = check.get(r["run"])
        ok = "-" if c is None or c["match"] == "" else ("yes" if c["match"] == "True" else "no")
        L.append(f"| `{r['run']}` | {r['arm']} | {r['params_M']} | {n(r['train_non'])} / {n(r['train_somatic'])} / "
                 f"{n(r['train_germline'])} | {n(r['val_non'])} / {n(r['val_somatic'])} / {n(r['val_germline'])} | "
                 f"{n(r['ignored_train'])} / {n(r['ignored_val'])} | {ok} | {r['epochs_run']}/{r['epochs']} ({r['best_epoch']}) | "
                 f"{f3(r['train_loss_best_epoch'])} / {f3(r['train_loss_last'])} | {f3(r['val_loss_best_epoch'])} / "
                 f"{f3(r['val_loss_min'])} ({r['val_loss_min_epoch']}) / {f3(r['val_loss_last'])} | {f3(r['val_somatic_ap'])} | "
                 f"{f3(r['threshold_r09'])} |")

    sp = read("set_split_counts.tsv")
    L += ["", "## T2. Per tensor set (chr2-22, the recipes' split): training tensors and what is ignored",
          "",
          "train = label >= 0 in the training blocks minus the partial somatic matches; ignored = label -1 in the training "
          "blocks, by label reason (outside = outside_confident_region, off-ref = off_reference_no_truth_match, no pos = "
          "not_on_unique_grch38_node, repeat = repeat_indel_without_truth, rule (a)); partial = left out by --ignore-reasons.",
          "",
          "| set | kind | labels | chr2-22 tensors | train non / somatic / germline | partial left out | ignored (-1) | "
          "outside | off-ref | no pos | repeat | val non / somatic / germline |",
          "|---|---|---|---:|---|---:|---:|---:|---:|---:|---:|---|"]
    for r in sp:
        neg = json.loads(r["ignored_train_blocks_by_reason"])
        L.append(f"| {r['set']} | {r['kind']} | {r['rules_sha256']}{' rule (a)' if r['ignore_repeat_indels'] == 'True' else ''} | "
                 f"{n(r['chr2_22_tensors'])} | {n(r['train_non'])} / {n(r['train_somatic'])} / {n(r['train_germline'])} | "
                 f"{n(r['partial_left_out_train'])} | {n(r['ignored_train_blocks'])} | "
                 f"{n(neg.get('outside_confident_region', 0))} | {n(neg.get('off_reference_no_truth_match', 0))} | "
                 f"{n(neg.get('not_on_unique_grch38_node', 0))} | {n(neg.get('repeat_indel_without_truth', 0))} | "
                 f"{n(r['val_non'])} / {n(r['val_somatic'])} / {n(r['val_germline'])} |")

    st = read("somatic_truth_alleles.tsv")
    L += ["", "## T3. Distinct somatic truth alleles behind the training tensors (chr2-22, validation blocks excluded)",
          "",
          "truth = PASS somatic truth alleles of the kind on chr2-22 inside the BED (the labels' somatic BED ∩ germline "
          "BED test of data.somatic_truth); training region = those outside the validation blocks; behind training = "
          "distinct truth alleles that a training tensor (label 1, representative match) stands for; the status columns "
          "count the training-region truth alleles by the set's somatic.recall.tsv (rep = representative allele of a "
          "tensor; other = another allele of a site; filtered = candidate removed by the build's AF 0.08 / min 3 ALT "
          "reads filters; none = no candidate).",
          "",
          "| set | kind | truth in BED | in validation region | training region | behind training tensors | "
          "% of training region | rep | other | filtered | none |",
          "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in st:
        s = json.loads(r["training_region_truth_status"])
        filt = sum(v for k, v in s.items() if k.startswith("filtered"))
        L.append(f"| {r['set']} | {r['kind']} | {n(r['truth_pass_in_bed_chr2_22'])} | {n(r['truth_in_validation_region'])} | "
                 f"{n(r['truth_training_region'])} | {n(r['truth_behind_train_tensors'])} | "
                 f"{pct(r['frac_training_region_truth_with_train_tensor'])} | {n(s.get('tensor_representative', 0))} | "
                 f"{n(s.get('tensor_non_representative_allele', 0))} | {n(filt)} | {n(s.get('no_candidate', 0))} |")

    un = read("somatic_truth_unions.tsv")
    L += ["", "## T4. Distinct somatic truth alleles behind training tensors, unions (allele = VCF chrom, pos, REF, ALT)", "",
          "| sample | kind | group | distinct truth alleles |", "|---|---|---|---:|"]
    for r in un:
        L.append(f"| {r['sample']} | {r['kind']} | {r['group']} | {n(r['distinct_truth_alleles_behind_train_tensors'])} |")

    q = read("vaf_quantiles.tsv")
    L += ["", "## T5. AF (A1 allele fraction of the tensor) of the training tensors, per set and class", "",
          "| set | kind | class | n | mean | 5 % | 10 % | 25 % | median | 75 % | 90 % | 95 % | AF < 0.10 | AF < 0.20 | AF >= 0.40 |",
          "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in q:
        L.append(f"| {r['set']} | {r['kind']} | {r['cls']} | {n(r['n'])} | {f3(r['mean'])} | {f3(r['q05'])} | {f3(r['q10'])} | "
                 f"{f3(r['q25'])} | {f3(r['q50'])} | {f3(r['q75'])} | {f3(r['q90'])} | {f3(r['q95'])} | "
                 f"{pct(r['frac_af_lt_0_10'])} | {pct(r['frac_af_lt_0_20'])} | {pct(r['frac_af_ge_0_40'])} |")

    h = read("vaf_hist.tsv")
    coarse = [(0.0, 0.10), (0.10, 0.20), (0.20, 0.30), (0.30, 0.40), (0.40, 0.60), (0.60, 0.80), (0.80, 1.00)]
    L += ["", "## T6. AF histogram of the somatic training tensors (fraction per bin; bins of 0.02 in vaf_hist.tsv)", "",
          "| set | kind | n | " + " | ".join(f"{a:.2f}-{b:.2f}" for a, b in coarse) + " |",
          "|---|---|---:|" + "---:|" * len(coarse)]
    for r in h:
        if r["cls"] != "somatic":
            continue
        tot = int(r["n"]) or 1
        cells = []
        for a, b in coarse:
            s = sum(int(v) for k, v in r.items() if "-" in k and a - 1e-9 <= float(k.split("-")[0]) < b - 1e-9)
            cells.append(f"{100 * s / tot:.1f} %")
        L.append(f"| {r['set']} | {r['kind']} | {n(r['n'])} | " + " | ".join(cells) + " |")
    sp = read("somatic_spectrum.tsv")
    L += ["", "## T7. Mutation spectrum of the SNV truth alleles behind the training tensors (SBS6, pyrimidine reference)",
          "",
          "UV-type = C>T with a pyrimidine 5' of the C (CC / TC); APOBEC-type = C>T or C>G at TCW (W = A / T; overlaps "
          "UV-type at TCA / TCT); TCW C>G = the APOBEC part UV does not make; CpG C>T = C>T followed by G; all as a "
          "fraction of all SNV alleles. Context from the labels' GRCh38 FASTA.",
          "",
          "| set | SNV alleles | C>A | C>G | C>T | T>A | T>C | T>G | UV-type C>T | APOBEC-type TCW | TCW C>G | CpG C>T |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in sp:
        L.append(f"| {r['set']} | {n(r['snv_alleles'])} | " + " | ".join(pct(r[c]) for c in ("C>A", "C>G", "C>T", "T>A", "T>C", "T>G"))
                 + f" | {pct(r['uv_CT_at_dipyrimidine'])} | {pct(r['apobec_TCW'])} | {pct(r['apobec_TCW_CG'])} | "
                 f"{pct(r['CpG_CT'])} |")
    (HERE / "tables.md").write_text("\n".join(L) + "\n")
    print(f"tables.md: {len(L)} lines")


if __name__ == "__main__":
    main()
