"""E20b step 5: tables of classify.py's per-locus read labels, HG008-N normal against HG008-T tumor (PacBio HiFi), HPRC
v2.1 (d46), at E5d's 1,607 HG008T absorbed truth alleles. Same definitions as E20's report.py (imported):
  ALT path = path label alt or alt_like (the walked graph sequence is the ALT hap, or closer to it than to GRCh38);
  REF read / ALT read = the read's own bases are ref_exact or ref_like / alt_exact or alt_like.
Grouping per locus by E5d's assembly class of the allele (present / absent / ambiguous in the HG008-N v6.2 haplotypes).
Check: the realigned tumor reads against the counts taken earlier from Pansoma's own HG008T PacBio HiFi d46 GAM
(E5c per_locus.tsv.gz, HG008T_PacBio_d46 alt_reads / spanning; E5c has the loci lost on PacBio).
Writes tables.md and summary.json (this folder) and $D/per_locus.tsv.
usage: /wanglab/jshen/anaconda3/bin/python report.py
"""
import csv
import gzip
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "E20_normal_reads_colo829bl"))
from report import locus_fracs, pct, pooled  # noqa: E402  (E20's definitions)

D = Path("/scratch/jshen/data/reviewer_experiments_20261013/E20b_normal_reads_hg008n")
E5D_ALLELES = Path("/scratch/jshen/data/reviewer_experiments_20261013/E5d_absorbed_normal_d46/per_allele.tsv")
E5C = Path("/scratch/jshen/data/reviewer_experiments_20261013/E5c_d46_loss_reads/per_locus.tsv.gz")
SAMPLES = ("normal", "tumor")
NAME = {"normal": "HG008-N normal (PacBio HiFi, realigned)", "tumor": "HG008-T tumor (PacBio HiFi, realigned)"}
MIN_SPAN = 5


def load(sample):
    f = D / "classify" / f"{sample}_d46.jsonl"
    if not f.exists():
        return None
    with f.open() as fh:
        return {r["truth_id"]: r for r in (json.loads(x) for x in fh if x.strip())}


def gam_counts():
    out = {}
    with gzip.open(E5C, "rt") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            if r["set"] == "HG008T_PacBio_d46" and r["spanning"] not in ("", "None"):
                out[r["truth_id"]] = dict(alt=int(r["alt_reads"] or 0), spanning=int(r["spanning"]))
    return out


def main():
    with open(D / "loci_d46.tsv") as fh:
        loci = list(csv.DictReader(fh, delimiter="\t"))
    with open(E5D_ALLELES) as fh:
        cat = {r["truth_id"]: r["category"] for r in csv.DictReader(fh, delimiter="\t")
               if r["sample"] == "HG008T" and r["arm"] == "d46"}
    assert all(m["truth_id"] in cat for m in loci), "E5d per_allele lacks loci"
    data = {s: load(s) for s in SAMPLES}
    L = ["# E20b tables (generated by report.py)", "",
         "HG008T absorbed truth alleles on HPRC v2.1 (d46), E5d set. Normal = HG008-N-D PacBio HiFi (GIAB BCM Revio 68x), "
         "tumor = HG008-T PacBio HiFi (116x, the reads of Pansoma's HG008T PacBio GAMs), both realigned to d46 with the "
         "GAMs' giraffe settings (vg 1.77, -b hifi). ALT path = the walked graph sequence between the read's GRCh38 "
         "anchors is the ALT hap or closer to it than to GRCh38 (path label alt / alt_like); REF read / ALT read = the "
         "read's own bases are closer to GRCh38 / to GRCh38 + truth. Spanning reads with MAPQ > 10.", "",
         f"## d46: {len(loci)} absorbed loci", "",
         "| reads | loci (>= 1 spanning) | spanning reads per locus, median | reads | on the ALT path | REF reads on the ALT path | ALT reads | ALT reads on the ALT path | ALT reads on GRCh38 |",
         "|---|---:|---:|---:|---|---|---|---|---|"]
    summary = {}
    for s in SAMPLES:
        recs = data[s]
        if not recs:
            continue
        for label, ids in (("all", [m["truth_id"] for m in loci]),
                           ("SNV", [m["truth_id"] for m in loci if m["kind2"] == "SNV"]),
                           ("INDEL", [m["truth_id"] for m in loci if m["kind2"] == "INDEL"])):
            p = pooled(recs, ids)
            spans = [recs[i]["spanning"] for i in ids if i in recs]
            covered = sum(x > 0 for x in spans)
            p.update(loci=len(ids), loci_in_output=len(spans), loci_covered=covered,
                     median_spanning=statistics.median(spans) if spans else None)
            summary[f"{s}_{label}"] = p
            L.append(f"| {NAME[s]}, {label} | {covered} / {len(ids)} | {p['median_spanning']} | {p['reads']:,} | "
                     f"{p['alt_path']:,} ({pct(p['alt_path'], p['reads'])}) | "
                     f"{p['ref_on_alt_path']:,} / {p['ref_reads']:,} ({pct(p['ref_on_alt_path'], p['ref_reads'])}) | "
                     f"{p['alt_reads']:,} ({pct(p['alt_reads'], p['reads'])}) | "
                     f"{p['alt_on_alt_path']:,} ({pct(p['alt_on_alt_path'], p['alt_reads'])}) | "
                     f"{p['alt_on_grch38']:,} ({pct(p['alt_on_grch38'], p['alt_reads'])}) |")
    norm, tum = data["normal"], data["tumor"]
    per = []
    for m in loci:
        n = locus_fracs(norm[m["truth_id"]]) if norm and m["truth_id"] in norm else dict(span=0)
        t = locus_fracs(tum[m["truth_id"]]) if tum and m["truth_id"] in tum else dict(span=0)
        per.append(dict(truth_id=m["truth_id"], kind2=m["kind2"], chrom=m["chrom"], vcf_pos=m["vcf_pos"],
                        e5d_normal_class=cat[m["truth_id"]],
                        normal_span=n.get("span"), normal_alt_path=n.get("alt_path"), normal_alt_seq=n.get("alt_seq"),
                        normal_ref_on_alt=n.get("ref_on_alt"),
                        tumor_span=t.get("span"), tumor_alt_path=t.get("alt_path"), tumor_alt_seq=t.get("alt_seq")))
    if norm:
        ok = [r for r in per if (r["normal_span"] or 0) >= MIN_SPAN]
        zero = [r for r in ok if r["normal_alt_path"] == 0]
        L += ["", f"Per locus, normal (loci with >= {MIN_SPAN} spanning normal reads: {len(ok)} of {len(per)}): "
              f"no normal read on the ALT path at {len(zero)} ({pct(len(zero), len(ok))}); "
              f"normal ALT-path fraction >= 0.2 at {sum(r['normal_alt_path'] >= 0.2 for r in ok)}; "
              f"normal reads carrying the ALT (own bases) >= 0.2 at {sum(r['normal_alt_seq'] >= 0.2 for r in ok)}.", ""]
        summary["per_locus"] = dict(loci_min_span=len(ok), zero_normal_alt_path=len(zero),
                                    normal_alt_path_ge_0p2=sum(r["normal_alt_path"] >= 0.2 for r in ok),
                                    normal_alt_seq_ge_0p2=sum(r["normal_alt_seq"] >= 0.2 for r in ok))
        groups = defaultdict(list)
        for r in ok:
            groups[(r["e5d_normal_class"], r["kind2"])].append(r)
        L += ["| E5d normal class (HG008-N assembly), kind | loci | normal ALT-path fraction, median (max) | loci with no normal read on the ALT path | "
              "normal ALT-carrying fraction, median | REF normal reads on the ALT path | tumor ALT-carrying fraction, median |",
              "|---|---:|---|---:|---|---|---|"]
        summary["by_e5d_class"] = {}
        for key, rs in sorted(groups.items()):
            n_ref = sum(locus_fracs(norm[r["truth_id"]]).get("n_ref", 0) for r in rs)
            n_ref_alt = sum(locus_fracs(norm[r["truth_id"]]).get("n_ref_on_alt", 0) for r in rs)
            tv = [r["tumor_alt_seq"] for r in rs if r["tumor_alt_seq"] is not None]
            entry = dict(loci=len(rs), normal_alt_path_median=statistics.median(r["normal_alt_path"] for r in rs),
                         normal_alt_path_max=max(r["normal_alt_path"] for r in rs),
                         zero=sum(r["normal_alt_path"] == 0 for r in rs),
                         normal_alt_seq_median=statistics.median(r["normal_alt_seq"] for r in rs),
                         ref_on_alt=n_ref_alt, ref=n_ref, tumor_alt_seq_median=statistics.median(tv) if tv else None)
            summary["by_e5d_class"][f"{key[0]}_{key[1]}"] = entry
            tm = f"{entry['tumor_alt_seq_median']:.3f}" if tv else "-"
            L.append(f"| {key[0]}, {key[1]} | {len(rs)} | {entry['normal_alt_path_median']:.3f} ({entry['normal_alt_path_max']:.3f}) | "
                     f"{entry['zero']} | {entry['normal_alt_seq_median']:.3f} | {n_ref_alt:,} / {n_ref:,} ({pct(n_ref_alt, n_ref)}) | {tm} |")
        # the normal's SNV ALT reads by E5d class: expected ~0 where the assembly has no ALT, ~0.5 / 1 where it has
        L += ["", "Normal reads carrying the ALT at SNV loci, by E5d class (pooled):", ""]
        for c in sorted({r["e5d_normal_class"] for r in per}):
            ids = [r["truth_id"] for r in per if r["e5d_normal_class"] == c and r["kind2"] == "SNV"]
            p = pooled(norm, ids)
            summary[f"normal_SNV_{c}"] = p
            L.append(f"- {c}: {len(ids)} loci, {p['alt_reads']:,} / {p['reads']:,} ({pct(p['alt_reads'], p['reads'])}) normal reads ALT-like")
    if tum:
        ref_counts = gam_counts()
        pairs = []
        for r in per:
            g = ref_counts.get(r["truth_id"])
            tr = tum.get(r["truth_id"])
            if not g or not tr or g["spanning"] < MIN_SPAN or tr["spanning"] < MIN_SPAN:
                continue
            pairs.append((g["alt"] / g["spanning"], locus_fracs(tr)["alt_seq"], g["spanning"], tr["spanning"]))
        if pairs:
            d = [abs(a - b) for a, b, _, _ in pairs]
            summary["realigned_vs_pansoma_gam"] = dict(
                source="E5c per_locus.tsv.gz, HG008T_PacBio_d46 alt_reads / spanning", loci=len(pairs),
                median_abs_diff_alt_read_fraction=statistics.median(d), within_0p1=sum(x <= 0.1 for x in d),
                median_spanning_gam=statistics.median(x[2] for x in pairs),
                median_spanning_realigned=statistics.median(x[3] for x in pairs))
            L += ["", f"Check against Pansoma's own HG008T PacBio HiFi d46 GAM (E5c per_locus.tsv.gz, HG008T_PacBio_d46 "
                  f"alt_reads / spanning): tumor ALT-read fraction per locus, realigned reads against the GAM, {len(pairs)} "
                  f"loci: median |difference| {statistics.median(d):.3f}, within 0.1 at {sum(x <= 0.1 for x in d)}; median "
                  f"spanning reads {statistics.median(x[2] for x in pairs)} (GAM) and {statistics.median(x[3] for x in pairs)} "
                  "(realigned).", ""]
    with open(D / "per_locus.tsv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(per[0]), delimiter="\t", lineterminator="\n")
        w.writeheader()
        w.writerows(per)
    (HERE / "tables.md").write_text("\n".join(L) + "\n")
    (HERE / "summary.json").write_text(json.dumps(summary, indent=1, default=float) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
