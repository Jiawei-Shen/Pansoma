"""E20b: why HG008-N reads carry the ALT at many HG008T absorbed SNVs (24.7% of the reads at the normal-absent ones,
COLO829BL 2.0%).

The HG008T truth is called on the HG008-N assembly (truth INFO HG008Nv62SOMATICVARIANT = the event in the normal frame) and
projected to GRCh38. Where the normal's own haplotypes differ from GRCh38 in a homopolymer or STR, a normal-frame length
change can appear on GRCh38 as an SNV, and the normal's reads then show the 'ALT' base on GRCh38 although the normal does
not carry the tumor allele (whole-array comparison, E5d). Split of the 140 d46 SNVs by E5d class and by the kind of the
normal-frame event (SNV / INDEL / no INFO event), with two read measures: E20b's ALT-like normal / tumor reads (own bases,
realigned to d46) and a GRCh38 pileup of the ALT base (control_snv.py, MAPQ >= 20, linear BAMs).
Writes snv_event_frame.md (this folder).
usage: /wanglab/jshen/anaconda3/bin/python snv_event_frame.py
"""
import collections
import csv
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
D = '/scratch/jshen/data/reviewer_experiments_20261013/E20b_normal_reads_hg008n'
E5D = '/scratch/jshen/data/reviewer_experiments_20261013/E5d_absorbed_normal_d46'
OLD = '/scratch/jshen/data/pansoma_net_v2_runs/graph_absorbed_somatic_20261001'
rd = lambda f: list(csv.DictReader(open(f), delimiter='\t'))  # noqa: E731


def ev_kind(e):
    if not e:
        return 'no INFO event'
    m = re.match(r'.*:(\d+)-([ACGTN]*)-([ACGTN]*)$', e.upper())
    r, a = m.group(2), m.group(3)
    return 'SNV' if len(r) == len(a) == 1 else 'INDEL' if len(r) != len(a) else 'MNV'


def main():
    loci = {}
    for d in (OLD, f'{E5D}/hg008t'):
        for r in rd(f'{d}/loci.tsv'):
            loci[r['truth_id']] = r
    cat = {r['truth_id']: r['category'] for r in rd(f'{E5D}/per_allele.tsv') if r['sample'] == 'HG008T' and r['arm'] == 'd46'}
    pu = {r['truth_id']: r for r in rd(f'{D}/control/snv_pileup.tsv') if r['group'] == 'absorbed'}
    e20 = {r['truth_id']: r for r in rd(f'{D}/per_locus.tsv') if r['kind2'] == 'SNV'}
    G = collections.defaultdict(list)
    for t in e20:
        G[(cat[t], ev_kind(loci[t]['asm_event']))].append(t)
    pct = lambda a, b: f'{a:,} / {b:,} ({100 * a / b:.1f}%)' if b else '-'  # noqa: E731
    L = ['# HG008T absorbed SNVs (d46) by E5d class and normal-frame event kind (generated by snv_event_frame.py)', '',
         '| E5d class | normal-frame event | loci | normal reads ALT-like (E20b) | tumor reads ALT-like (E20b) | normal ALT base, GRCh38 pileup | tumor ALT base, GRCh38 pileup | loci with normal pileup < 0.1 / >= 0.3 (>= 5 reads) |',
         '|---|---|---:|---|---|---|---|---|']
    for k in sorted(G, key=lambda k: (['present', 'ambiguous', 'absent'].index(k[0]), k[1])):
        ids = G[k]
        ea = sum(round(float(e20[t]['normal_alt_seq'] or 0) * int(e20[t]['normal_span'] or 0)) for t in ids)
        es = sum(int(e20[t]['normal_span'] or 0) for t in ids)
        ta = sum(round(float(e20[t]['tumor_alt_seq'] or 0) * int(e20[t]['tumor_span'] or 0)) for t in ids)
        ts = sum(int(e20[t]['tumor_span'] or 0) for t in ids)
        na, nd = sum(int(pu[t]['normal_alt']) for t in ids), sum(int(pu[t]['normal_depth']) for t in ids)
        pa, pd = sum(int(pu[t]['tumor_alt']) for t in ids), sum(int(pu[t]['tumor_depth']) for t in ids)
        fr = [int(pu[t]['normal_alt']) / int(pu[t]['normal_depth']) for t in ids if int(pu[t]['normal_depth']) >= 5]
        L.append(f'| {k[0]} | {k[1]} | {len(ids)} | {pct(ea, es)} | {pct(ta, ts)} | {pct(na, nd)} | {pct(pa, pd)} | '
                 f'{sum(f < 0.1 for f in fr)} / {sum(f >= 0.3 for f in fr)} of {len(fr)} |')
    ctl = [r for r in rd(f'{D}/control/snv_pileup.tsv') if r['group'] == 'control']
    L += ['', f"Random non-absorbed truth SNVs (300, control_snv.py): normal ALT base {pct(sum(int(r['normal_alt']) for r in ctl), sum(int(r['normal_depth']) for r in ctl))}, "
          f"tumor {pct(sum(int(r['tumor_alt']) for r in ctl), sum(int(r['tumor_depth']) for r in ctl))}.", '',
          'Absent SNVs with a high normal ALT fraction lie at homopolymer / dinucleotide-repeat boundaries where the HG008-N',
          'haplotypes differ from GRCh38 in repeat length or composition (inspected: all 12 absent loci with a normal-frame SNV',
          'event and normal pileup >= 0.1). There the GRCh38 records of one normal-frame event include bases the normal already',
          'has (e.g. five GRCh38 G>T SNVs at chr13:84,388,899-907 for one normal-frame T>G, truth ids 11888-11892), so normal',
          'reads show them; the whole-array comparison of E5d still finds the tumor sequence in neither normal haplotype.']
    (HERE / 'snv_event_frame.md').write_text('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
