"""E26: the RIS GPU reruns synced on 2026-10-17 (ris_7fc7396_20261012), compared with the runs they pair with.

Groups (chr1, in the benchmark BED, PASS = validation recall-0.9 threshold; F1 after the PoN unless 'raw'):
  nopc     retrained without the path-count plane (train --drop-planes path_count; E1.1 gpu_nopc_commands.sh) vs with
  matched  the d9 SNV recipe of the d46 / GRCh38-only arms (4 GPUs, batch 1024: *_7fc7396_ddp4_b1024) vs the d9 runs of
           E3 (HG008T PacBio / ONT on 1 GPU, COLO829T *_SNV_h90), and the three arms with the matched d9
  seeds    a second training seed (*_s1) vs the first, per arm
  normds   BQ / MAPQ statistics per dataset (*_d46_normds) vs the training-set statistics (*_d46_7fc7396)
  readnorm COLO829T Illumina joint INDEL with per-read base-quality centring (joint_readnorm) vs the joint model
  repro    HG008T Illumina INDEL retrained with the same command (_repro) vs the original
Sources: a run synced today -> its own vcf_chr1[_<set>][_pon71cb51a]/eval_bed/report.json (INDEL: the _pon71cb51a one,
the current INDEL PoN rule); a run not synced today (SNV baselines) -> the 7fc7396 benchmark summaries (RIS, same
vcf.sh). SNV is unaffected by the INDEL PoN rule change.
usage: /wanglab/jshen/anaconda3/bin/python collect.py   (writes tables.md and summary.json next to this script)
"""
import glob
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RIS = Path("/scratch/jshen/data/pansoma_net_v2_runs/ris_7fc7396_20261012")
BENCH = Path("/scratch/jshen/Github/Pansoma/analysis/benchmark_7fc7396_20261012")
SETS = {"HG008": ("Illumina", "PacBio", "ONT"), "COLO829": ("Illumina", "fiberseq", "ONT")}


def load(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def bench_index():
    idx = {}

    def walk(o):
        if isinstance(o, dict):
            if isinstance(o.get("run"), str) and "eval_bed" in o:
                idx.setdefault(o["run"], o)
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    for f in sorted(glob.glob(str(BENCH / "*" / "summary.json"))):
        walk(load(f))
    return idx


BIDX = bench_index()


def from_report(rep, source):
    at, best = rep["pon"]["at_threshold"], rep["pon"]["best"]
    return dict(p=at["precision"], r=at["recall"], f1=at["f1"], tp=at["tp_baseline"], fp=at["fp"], fn=at["fn"],
                best=best["f1"], raw_f1=rep["raw"]["at_threshold"]["f1"], ceiling=rep["pon"]["ceiling"], source=source)


def metrics(run, kind, set_suffix=""):
    """PASS + PoN metrics of a run (in the BED); INDEL only under the current PoN rule (_pon71cb51a)."""
    names = [f"vcf_chr1{set_suffix}_pon71cb51a"] + ([] if kind == "INDEL" else [f"vcf_chr1{set_suffix}"])
    for n in names:
        rep = load(RIS / run / n / "eval_bed" / "report.json")
        if rep:
            return from_report(rep, f"RIS {run}/{n}")
    if kind == "SNV" and not set_suffix and run in BIDX:
        e = BIDX[run]["eval_bed"]
        pon, raw = e["pon"], e["raw"]
        return dict(p=pon["p"], r=pon["r"], f1=pon["f1"], tp=pon["tp"], fp=pon["fp"], fn=pon["fn"],
                    best=(pon.get("best") or {}).get("f1"), raw_f1=raw["f1"], ceiling=pon.get("ceiling"),
                    source=f"benchmark {run}")
    return None


def ap(run):
    """chr1 somatic average precision (per tensor, before the PoN) from test_chr1/*.metrics.json, or None."""
    for f in sorted((RIS / run / "test_chr1").glob("*.metrics.json")) if (RIS / run / "test_chr1").exists() else ():
        d = load(f)
        v = d.get("somatic_ap") or (d.get("somatic") or {}).get("ap") or d.get("ap")
        if v is not None:
            return v
    return None


def fmt(x, d=3):
    return "-" if x is None else f"{x:.{d}f}"


def cell(m):
    return "-" if m is None else f"{fmt(m['p'])} / {fmt(m['r'])} / **{fmt(m['f1'])}** (best {fmt(m['best'])})"


def diff(a, b, key="f1"):
    return "-" if a is None or b is None or a.get(key) is None or b.get(key) is None else f"{a[key] - b[key]:+.3f}"


def d9_base(s, p, kind):
    if kind == "INDEL":
        return f"{s}_{p}_INDEL_7fc7396"
    if s == "HG008":
        return "HG008_Illumina_SNV_7fc7396_ddp4_b1024" if p == "Illumina" else f"HG008_{p}_SNV_7fc7396"
    return f"COLO829_{p}_SNV_h90"


def main():
    out, L = {}, ["# E26 tables (generated by collect.py)", "",
                  "chr1, benchmark BED, PASS (validation recall-0.9 threshold) after the PoN: P / R / **F1** (best = test-tuned "
                  "best F1 on the chr1 curve, an upper bound). INDEL under the current INDEL PoN rule (`_pon71cb51a`).", ""]

    # ---- nopc
    L += ["## 1. Retrained without channel 6 (nopc) vs with", "",
          "| set | kind | graph | with ch6 | without ch6 | dF1 (PASS) | d best F1 | chr1 AP with / without |", "|---|---|---|---|---|---:|---:|---|"]
    out["nopc"] = []
    for kind in ("SNV", "INDEL"):
        for s, plats in SETS.items():
            for p in plats:
                for g, base, nopc in (
                        ("v1.1 d9", d9_base(s, p, kind),
                         f"HG008_Illumina_SNV_nopc_7fc7396_ddp4_b1024" if (s, p, kind) == ("HG008", "Illumina", "SNV")
                         else f"{s}_{p}_{kind}_nopc_7fc7396"),
                        ("v2.1 d46", f"{s}_{p}_{kind}_d46_7fc7396", f"{s}_{p}_{kind}_nopc_d46_7fc7396")):
                    a, b = metrics(base, kind), metrics(nopc, kind)
                    out["nopc"].append(dict(set=f"{s}T_{p}", kind=kind, graph=g, base=base, nopc=nopc, with_ch6=a, without=b,
                                            ap_with=ap(base), ap_without=ap(nopc)))
                    L.append(f"| {s}T {p} | {kind} | {g} | {cell(a)} | {cell(b)} | {diff(b, a)} | {diff(b, a, 'best')} | "
                             f"{fmt(ap(base))} / {fmt(ap(nopc))} |")
    L.append("")

    # ---- matched d9 recipe and the three arms
    L += ["## 2. Matched d9 SNV recipe (4 GPUs, batch 1024) vs the E3 d9 run, and the three arms", "",
          "| set | E3 d9 run | matched d9 | d46 | GRCh38-only | matched d9 - E3 d9 | d46 - matched d9 | matched d9 - GRCh38-only |",
          "|---|---|---|---|---|---:|---:|---:|"]
    out["matched"] = []
    for s, plats in SETS.items():
        for p in plats:
            old = d9_base(s, p, "SNV")
            new = f"{s}_{p}_SNV_7fc7396_ddp4_b1024"
            a, b = metrics(old, "SNV"), metrics(new, "SNV")
            d46, lin = metrics(f"{s}_{p}_SNV_d46_7fc7396", "SNV"), metrics(f"{s}_{p}_SNV_linear_7fc7396", "SNV")
            out["matched"].append(dict(set=f"{s}T_{p}", old=old, new=new, e3_d9=a, matched_d9=b, d46=d46, linear=lin))
            L.append(f"| {s}T {p} | {cell(a)} | {cell(b)} | {cell(d46)} | {cell(lin)} | {diff(b, a)} | {diff(d46, b)} | "
                     f"{diff(b, lin)} |")
    L.append("")

    # ---- seeds
    L += ["## 3. Second seed (s1) vs first (s0), SNV", "",
          "| set | arm | s0 run | s0 | s1 | s1 - s0 F1 | chr1 AP s0 / s1 |", "|---|---|---|---|---|---:|---|"]
    out["seeds"] = []
    for s, plats in SETS.items():
        for p in plats:
            for arm, s0 in (("d9 (matched recipe)", f"{s}_{p}_SNV_7fc7396_ddp4_b1024"), ("d46", f"{s}_{p}_SNV_d46_7fc7396"),
                            ("GRCh38-only", f"{s}_{p}_SNV_linear_7fc7396")):
                s1 = s0 + "_s1"
                a, b = metrics(s0, "SNV"), metrics(s1, "SNV")
                if b is None:
                    continue
                out["seeds"].append(dict(set=f"{s}T_{p}", arm=arm, s0=s0, s1=s1, m0=a, m1=b, ap0=ap(s0), ap1=ap(s1)))
                L.append(f"| {s}T {p} | {arm} | `{s0}` | {cell(a)} | {cell(b)} | {diff(b, a)} | {fmt(ap(s0))} / {fmt(ap(s1))} |")
    L.append("")

    # ---- seed-matched arm comparisons (HPRC minus GRCh38-only, same seed), and two-seed means
    L += ["## 3b. HPRC minus GRCh38-only, SNV PASS F1 after the PoN, per seed and two-seed mean", "",
          "| set | d9 (matched) - GRCh38-only s0 / s1 / mean | d46 - GRCh38-only s0 / s1 / mean | d46 - d9 (matched) mean |",
          "|---|---|---|---|"]
    out["arms_by_seed"] = []
    for s, plats in SETS.items():
        for p in plats:
            runs = {"d9": f"{s}_{p}_SNV_7fc7396_ddp4_b1024", "d46": f"{s}_{p}_SNV_d46_7fc7396", "lin": f"{s}_{p}_SNV_linear_7fc7396"}
            f1 = {(k, sd): (metrics(r + ("_s1" if sd else ""), "SNV") or {}).get("f1") for k, r in runs.items() for sd in (0, 1)}
            mean = {k: (f1[(k, 0)] + f1[(k, 1)]) / 2 if None not in (f1[(k, 0)], f1[(k, 1)]) else None for k in runs}
            def d(a, b, sd):
                return None if f1[(a, sd)] is None or f1[(b, sd)] is None else f1[(a, sd)] - f1[(b, sd)]
            def dm(a, b):
                return None if mean[a] is None or mean[b] is None else mean[a] - mean[b]
            row = dict(set=f"{s}T_{p}", f1={f"{k}_s{sd}": v for (k, sd), v in f1.items()},
                       d9_lin=[d("d9", "lin", 0), d("d9", "lin", 1), dm("d9", "lin")],
                       d46_lin=[d("d46", "lin", 0), d("d46", "lin", 1), dm("d46", "lin")], d46_d9=dm("d46", "d9"))
            out["arms_by_seed"].append(row)
            sg = lambda x: "-" if x is None else f"{x:+.3f}"
            L.append(f"| {s}T {p} | {' / '.join(sg(x) for x in row['d9_lin'])} | {' / '.join(sg(x) for x in row['d46_lin'])} | "
                     f"{sg(row['d46_d9'])} |")
    L.append("")

    # ---- normds
    L += ["## 4. Per-dataset normalisation (normds) vs training statistics, d46", "",
          "| set | kind | training statistics | per dataset | dF1 | d best | chr1 AP train stats / per dataset |", "|---|---|---|---|---:|---:|---|"]
    out["normds"] = []
    for kind in ("SNV", "INDEL"):
        for s, plats in SETS.items():
            for p in plats:
                b = metrics(f"{s}_{p}_{kind}_d46_normds", kind)
                if b is None:
                    continue
                a = metrics(f"{s}_{p}_{kind}_d46_7fc7396", kind)
                out["normds"].append(dict(set=f"{s}T_{p}", kind=kind, base=a, normds=b,
                                          ap_base=ap(f"{s}_{p}_{kind}_d46_7fc7396"), ap_normds=ap(f"{s}_{p}_{kind}_d46_normds")))
                L.append(f"| {s}T {p} | {kind} | {cell(a)} | {cell(b)} | {diff(b, a)} | {diff(b, a, 'best')} | "
                         f"{fmt(ap(f'{s}_{p}_{kind}_d46_7fc7396'))} / {fmt(ap(f'{s}_{p}_{kind}_d46_normds'))} |")
    L.append("")

    # ---- readnorm
    L += ["## 5. COLO829T Illumina joint INDEL: per-read BQ centring (readnorm) vs the joint model, per purity", "",
          "| purity | joint | joint_readnorm | dF1 | d best |", "|---|---|---|---:|---:|"]
    out["readnorm"] = []
    for pur, suf in (("P100", "_COLO829T_Illumina"), ("P75", "_COLO829T_Illumina_P75"), ("P50", "_COLO829T_Illumina_P50"),
                     ("P25", "_COLO829T_Illumina_P25")):
        a = metrics("COLO829_Illumina_INDEL_joint_7fc7396", "INDEL", suf)
        b = metrics("COLO829_Illumina_INDEL_joint_readnorm", "INDEL", suf)
        out["readnorm"].append(dict(purity=pur, joint=a, readnorm=b))
        L.append(f"| {pur} | {cell(a)} | {cell(b)} | {diff(b, a)} | {diff(b, a, 'best')} |")
    L.append("")

    # ---- repro
    a, b = metrics("HG008_Illumina_INDEL_7fc7396", "INDEL"), metrics("HG008_Illumina_INDEL_7fc7396_repro", "INDEL")
    out["repro"] = dict(original=a, repro=b)
    L += ["## 6. Reproduction: HG008T Illumina INDEL retrained with the same command", "",
          f"original {cell(a)}; repro {cell(b)}; dF1 {diff(b, a)}, d best {diff(b, a, 'best')}", ""]

    (HERE / "summary.json").write_text(json.dumps(out, indent=1) + "\n")
    (HERE / "tables.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
