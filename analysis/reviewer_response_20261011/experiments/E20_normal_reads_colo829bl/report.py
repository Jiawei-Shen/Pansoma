"""E20 step 5: tables of classify.py's per-locus read labels, normal (COLO829BL) against tumor (COLO829T), per graph.

Reads $D/classify/{normal,tumor,tumorgam}_{d9,d46}.jsonl and $D/loci_{d9,d46}.tsv; writes tables.md, summary.json
(this folder) and $D/per_locus.tsv.
  ALT path = path label alt or alt_like (the walked graph sequence is the ALT hap, or closer to it than to GRCh38).
  REF read / ALT read = the read's own bases are ref_exact or ref_like / alt_exact or alt_like.
usage: /wanglab/jshen/anaconda3/bin/python report.py
"""
import csv
import json
import statistics
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
D = Path("/scratch/jshen/data/reviewer_experiments_20261013/E20_normal_reads_colo829bl")
SAMPLES = ("normal", "tumor", "tumorgam")
NAME = {"normal": "COLO829BL normal (realigned)", "tumor": "COLO829T tumor (realigned)",
        "tumorgam": "COLO829T tumor (Pansoma's GAM)"}
MIN_SPAN = 5  # per-locus fractions need >= 5 spanning reads


GAM_COUNT_SOURCE = {
    "d9": "graph_absorbed_somatic_colo829t_20261005 variant_set.tsv ONT_alt_reads / ONT_spanning (miss analysis on the d9 GAM)",
    "d46": "E5c per_locus.tsv.gz, COLO829T_ONT_d46 alt_reads / spanning",
}


def gam_counts(graph):
    """{truth_id: dict(alt, spanning)} counted earlier on Pansoma's own COLO829T ONT GAM of the graph."""
    import gzip
    out = {}
    if graph == "d9":
        path = Path("/scratch/jshen/data/pansoma_net_v2_runs/graph_absorbed_somatic_colo829t_20261005/variant_set.tsv")
        with open(path) as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                if r["ONT_spanning"] not in ("", "None"):
                    out[r["truth_id"]] = dict(alt=int(float(r["ONT_alt_reads"] or 0)), spanning=int(float(r["ONT_spanning"])))
    else:
        path = Path("/scratch/jshen/data/reviewer_experiments_20261013/E5c_d46_loss_reads/per_locus.tsv.gz")
        with gzip.open(path, "rt") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                if r["set"] == "COLO829T_ONT_d46" and r["spanning"] not in ("", "None"):
                    out[r["truth_id"]] = dict(alt=int(r["alt_reads"] or 0), spanning=int(r["spanning"]))
    return out


def load(sample, graph):
    f = D / "classify" / f"{sample}_{graph}.jsonl"
    if not f.exists():
        return None
    with f.open() as fh:
        return {r["truth_id"]: r for r in (json.loads(x) for x in fh if x.strip())}


def split(table):
    """Counter of (path, seq) from 'path|seq' keys."""
    return Counter({tuple(k.split("|")): v for k, v in table.items()})


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "-"


def pooled(records, ids):
    t = Counter()
    for i in ids:
        if i in records:
            t.update(split(records[i]["table"]))
    total = sum(t.values())
    alt_path = sum(v for (p, _), v in t.items() if p in ("alt", "alt_like"))
    ref_reads = sum(v for (_, s), v in t.items() if s.startswith("ref"))
    ref_on_alt = sum(v for (p, s), v in t.items() if s.startswith("ref") and p in ("alt", "alt_like"))
    alt_reads = sum(v for (_, s), v in t.items() if s.startswith("alt"))
    alt_on_alt = sum(v for (p, s), v in t.items() if s.startswith("alt") and p in ("alt", "alt_like"))
    alt_on_grch38 = sum(v for (p, s), v in t.items() if s.startswith("alt") and p == "grch38")
    by_path = Counter()
    for (p, _), v in t.items():
        by_path[p] += v
    return dict(reads=total, alt_path=alt_path, alt_path_frac=alt_path / total if total else None,
                path=dict(by_path), ref_reads=ref_reads, ref_on_alt_path=ref_on_alt,
                ref_on_alt_frac=ref_on_alt / ref_reads if ref_reads else None,
                alt_reads=alt_reads, alt_reads_frac=alt_reads / total if total else None,
                alt_on_alt_path=alt_on_alt, alt_on_grch38=alt_on_grch38,
                alt_on_alt_frac=alt_on_alt / alt_reads if alt_reads else None)


def locus_fracs(r):
    t = split(r["table"])
    n = sum(t.values())
    if n == 0:
        return dict(span=0, alt_path=None, alt_seq=None, ref_on_alt=None)
    alt_path = sum(v for (p, _), v in t.items() if p in ("alt", "alt_like"))
    alt_seq = sum(v for (_, s), v in t.items() if s.startswith("alt"))
    ref = sum(v for (_, s), v in t.items() if s.startswith("ref"))
    ref_on_alt = sum(v for (p, s), v in t.items() if s.startswith("ref") and p in ("alt", "alt_like"))
    return dict(span=n, alt_path=alt_path / n, alt_seq=alt_seq / n, ref_on_alt=ref_on_alt / ref if ref else None,
                n_alt_path=alt_path, n_ref=ref, n_ref_on_alt=ref_on_alt)


def main():
    L = ["# E20 tables (generated by report.py)", "",
         "ALT path = the walked graph sequence between the read's GRCh38 anchors is the ALT hap or closer to it than to "
         "GRCh38 (path label alt / alt_like); REF read / ALT read = the read's own bases are closer to GRCh38 / to "
         "GRCh38 + truth. Spanning reads with MAPQ > 10.", ""]
    summary, rows = {}, []
    with open(D / "loci_d9.tsv") as fh:
        d9_category = {r["truth_id"]: (r["category"], r["pf_label"]) for r in csv.DictReader(fh, delimiter="\t")}
    for graph in ("d9", "d46"):
        with open(D / f"loci_{graph}.tsv") as fh:
            loci = list(csv.DictReader(fh, delimiter="\t"))
        for m in loci:  # d46 loci: the assembly category of the same allele on d9 (E5d's d46 set has no own one)
            m.setdefault("category", d9_category.get(m["truth_id"], ("not in the d9 set", ""))[0])
            m.setdefault("pf_label", d9_category.get(m["truth_id"], ("", ""))[1])
        data = {s: load(s, graph) for s in SAMPLES}
        if not data["normal"]:
            continue
        L += [f"## {graph}: {len(loci)} absorbed loci", "",
              "| reads | loci (>= 1 spanning) | spanning reads per locus, median | reads | on the ALT path | REF reads on the ALT path | ALT reads | ALT reads on the ALT path | ALT reads on GRCh38 |",
              "|---|---:|---:|---:|---|---|---|---|---|"]
        summary[graph] = {}
        for s in SAMPLES:
            recs = data[s]
            if not recs:
                continue
            for label, ids in (("all", [m["truth_id"] for m in loci]),
                               ("SNV", [m["truth_id"] for m in loci if m["kind2"] == "SNV"]),
                               ("INDEL", [m["truth_id"] for m in loci if m["kind2"] == "INDEL"])):
                p = pooled(recs, ids)
                spans = [recs[i]["spanning"] for i in ids if i in recs]
                covered = sum(x > 0 for x in spans)
                p.update(loci=len(ids), loci_covered=covered,
                         median_spanning=statistics.median(spans) if spans else None)
                summary[graph][f"{s}_{label}"] = p
                L.append(f"| {NAME[s]}, {label} | {covered} / {len(ids)} | {p['median_spanning']} | {p['reads']:,} | "
                         f"{p['alt_path']:,} ({pct(p['alt_path'], p['reads'])}) | "
                         f"{p['ref_on_alt_path']:,} / {p['ref_reads']:,} ({pct(p['ref_on_alt_path'], p['ref_reads'])}) | "
                         f"{p['alt_reads']:,} ({pct(p['alt_reads'], p['reads'])}) | "
                         f"{p['alt_on_alt_path']:,} ({pct(p['alt_on_alt_path'], p['alt_reads'])}) | "
                         f"{p['alt_on_grch38']:,} ({pct(p['alt_on_grch38'], p['alt_reads'])}) |")
        # per-locus normal
        norm, tum = data["normal"], data["tumor"] or data["tumorgam"]
        per = []
        for m in loci:
            n = locus_fracs(norm[m["truth_id"]]) if m["truth_id"] in norm else dict(span=0)
            t = locus_fracs(tum[m["truth_id"]]) if tum and m["truth_id"] in tum else dict(span=0)
            g = locus_fracs(data["tumorgam"][m["truth_id"]]) if data["tumorgam"] and m["truth_id"] in data["tumorgam"] else dict(span=0)
            per.append(dict(graph=graph, truth_id=m["truth_id"], kind2=m["kind2"], chrom=m["chrom"], vcf_pos=m["vcf_pos"],
                            category=m.get("category", ""), pf_label=m.get("pf_label", ""),
                            in_d9_set=m.get("in_d9_set", ""),
                            normal_span=n.get("span"), normal_alt_path=n.get("alt_path"), normal_alt_seq=n.get("alt_seq"),
                            normal_ref_on_alt=n.get("ref_on_alt"),
                            tumor_span=t.get("span"), tumor_alt_path=t.get("alt_path"), tumor_alt_seq=t.get("alt_seq"),
                            tumorgam_span=g.get("span"), tumorgam_alt_path=g.get("alt_path"), tumorgam_alt_seq=g.get("alt_seq")))
        rows += per
        ok = [r for r in per if (r["normal_span"] or 0) >= MIN_SPAN]
        zero = [r for r in ok if r["normal_alt_path"] == 0]
        L += ["", f"Per locus, normal (loci with >= {MIN_SPAN} spanning normal reads: {len(ok)} of {len(per)}): "
              f"no normal read on the ALT path at {len(zero)} ({pct(len(zero), len(ok))}); "
              f"normal ALT-path fraction >= 0.2 at {sum(r['normal_alt_path'] >= 0.2 for r in ok)}; "
              f"normal reads carrying the ALT (own bases) >= 0.2 at {sum(r['normal_alt_seq'] >= 0.2 for r in ok)}.", ""]
        summary[graph]["per_locus"] = dict(loci_min_span=len(ok), zero_normal_alt_path=len(zero),
                                           normal_alt_path_ge_0p2=sum(r["normal_alt_path"] >= 0.2 for r in ok),
                                           normal_alt_seq_ge_0p2=sum(r["normal_alt_seq"] >= 0.2 for r in ok))
        group_key = "category"
        groups = defaultdict(list)
        for r in ok:
            groups[r[group_key] or "-"].append(r)
        L += [f"| {group_key} | loci | normal ALT-path fraction, median (max) | loci with no normal read on the ALT path | "
              f"normal ALT-carrying fraction, median | REF normal reads on the ALT path | tumor ALT-path fraction, median |",
              "|---|---:|---|---:|---|---|---|"]
        summary[graph]["by_" + group_key] = {}
        for key, rs in sorted(groups.items()):
            n_ref = sum(locus_fracs(norm[r["truth_id"]]).get("n_ref", 0) for r in rs)
            n_ref_alt = sum(locus_fracs(norm[r["truth_id"]]).get("n_ref_on_alt", 0) for r in rs)
            tv = [r["tumor_alt_path"] for r in rs if r["tumor_alt_path"] is not None]
            entry = dict(loci=len(rs), normal_alt_path_median=statistics.median(r["normal_alt_path"] for r in rs),
                         normal_alt_path_max=max(r["normal_alt_path"] for r in rs),
                         zero=sum(r["normal_alt_path"] == 0 for r in rs),
                         normal_alt_seq_median=statistics.median(r["normal_alt_seq"] for r in rs),
                         ref_on_alt=n_ref_alt, ref=n_ref, tumor_alt_path_median=statistics.median(tv) if tv else None)
            summary[graph]["by_" + group_key][key] = entry
            L.append(f"| {key} | {len(rs)} | {entry['normal_alt_path_median']:.3f} ({entry['normal_alt_path_max']:.3f}) | "
                     f"{entry['zero']} | {entry['normal_alt_seq_median']:.3f} | {n_ref_alt:,} / {n_ref:,} ({pct(n_ref_alt, n_ref)}) | "
                     f"{entry['tumor_alt_path_median']:.3f} |" if entry["tumor_alt_path_median"] is not None else
                     f"| {key} | {len(rs)} | {entry['normal_alt_path_median']:.3f} | {entry['zero']} | - | - | - |")
        # realigned tumor against the tumor counts taken earlier from Pansoma's own ONT GAMs (same read selection rule)
        ref_counts = gam_counts(graph)
        pairs = []
        for r in per:
            g = ref_counts.get(r["truth_id"])
            tr = data["tumor"].get(r["truth_id"]) if data["tumor"] else None
            if not g or not tr or g["spanning"] < MIN_SPAN or tr["spanning"] < MIN_SPAN:
                continue
            f = locus_fracs(tr)
            pairs.append((g["alt"] / g["spanning"], f["alt_seq"], g["spanning"], tr["spanning"]))
        if pairs:
            d = [abs(a - b) for a, b, _, _ in pairs]
            summary[graph]["realigned_vs_pansoma_gam"] = dict(
                source=GAM_COUNT_SOURCE[graph], loci=len(pairs), median_abs_diff_alt_read_fraction=statistics.median(d),
                within_0p1=sum(x <= 0.1 for x in d),
                median_spanning_gam=statistics.median(x[2] for x in pairs), median_spanning_realigned=statistics.median(x[3] for x in pairs))
            L += ["", f"Check against Pansoma's own COLO829T ONT GAM ({GAM_COUNT_SOURCE[graph]}): tumor ALT-read fraction per locus, "
                  f"realigned reads against the GAM, {len(pairs)} loci: median |difference| {statistics.median(d):.3f}, within 0.1 at "
                  f"{sum(x <= 0.1 for x in d)}; median spanning reads {statistics.median(x[2] for x in pairs)} (GAM) and "
                  f"{statistics.median(x[3] for x in pairs)} (realigned).", ""]
        # realigned tumor against Pansoma's tumor GAM classified here (tumorgam), when run
        both = [r for r in per if (r["tumor_span"] or 0) >= MIN_SPAN and (r["tumorgam_span"] or 0) >= MIN_SPAN]
        if both:
            diffs = [abs(r["tumor_alt_path"] - r["tumorgam_alt_path"]) for r in both]
            summary[graph]["realigned_vs_gam"] = dict(loci=len(both), median_abs_diff=statistics.median(diffs),
                                                     within_0p1=sum(d <= 0.1 for d in diffs))
            L += ["", f"Check: tumor ALT-path fraction, realigned reads against Pansoma's GAM, {len(both)} loci: median "
                  f"|difference| {statistics.median(diffs):.3f}, within 0.1 at {sum(d <= 0.1 for d in diffs)}.", ""]
        L.append("")
    if rows:
        with open(D / "per_locus.tsv", "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0]), delimiter="\t", lineterminator="\n")
            w.writeheader()
            w.writerows(rows)
    (HERE / "tables.md").write_text("\n".join(L) + "\n")
    (HERE / "summary.json").write_text(json.dumps(summary, indent=1, default=float) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
