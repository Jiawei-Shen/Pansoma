#!/usr/bin/env python3
"""HG008T chr1 (benchmark BED) with / without population filtering (R2.6 point 3 fact sheet, 2026-10-30).
Reads every run's <run>/vcf_chr1*/eval_bed/report.json: `raw` = PASS before the PoN, `pon` = PASS after it (tagged
records not called), both rtg vcfeval in the BED; `pon.ceiling` = highest post-filter recall on the curve, `raw.best` /
`pon.best` = test-tuned best F1 (upper bound). Writes r26_filter_table.md / .json next to this script.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RIS = Path("/scratch/jshen/data/pansoma_net_v2_runs/ris_7fc7396_20261012")
RUNS = RIS.parent
PLATS = ("Illumina", "PacBio", "ONT")


BENCH = Path("/scratch/jshen/Github/Pansoma/analysis/benchmark_7fc7396_20261012/linear_grch38_7fc7396_20261012/runs")


def txt_report(run_dir):
    """Fallback for seed-0 7fc7396 runs whose report.json is only on RIS: the benchmark's copied eval text
    (vcf_chr1.eval_bed.txt: lines raw / pon with records TP FP FN P R F1 | best F1 ... | ... | ceiling)."""
    f = BENCH / run_dir.name / "vcf_chr1.eval_bed.txt"
    if not f.exists():
        return None, None
    r = {}
    for line in f.read_text().splitlines():
        x = line.split()
        if x and x[0] in ("raw", "pon"):
            r[x[0]] = dict(at_threshold=dict(precision=float(x[5]), recall=float(x[6]), f1=float(x[7])),
                           best=dict(f1=float(x[9])), ceiling=float(x[-1]))
    return (r, str(f)) if len(r) == 2 else (None, None)


def rep(run_dir, kind):
    for v in (("vcf_chr1_pon71cb51a", "vcf_chr1") if kind == "INDEL" else ("vcf_chr1",)):
        f = run_dir / v / "eval_bed" / "report.json"
        if f.exists():
            return json.loads(f.read_text()), str(f)
    return txt_report(run_dir) if kind == "SNV" else (None, None)


def groups(p):
    s = "HG008"
    return [
        ("SNV", "v2.1 d46", "final (--norm dataset, 3 seeds)", [RIS / f"{s}_{p}_SNV_d46_normbq{x}" for x in ("", "_s1", "_s2")]),
        ("SNV", "v1.1 d9", "final (--norm dataset, 3 seeds)", [RIS / f"{s}_{p}_SNV_d9_normbq{x}" for x in ("", "_s1", "_s2")]),
        ("SNV", "GRCh38-only", "7fc7396 recipe (--norm train, 3 seeds; no --norm dataset run exists)",
         [RIS / f"{s}_{p}_SNV_linear_7fc7396{x}" for x in ("", "_s1", "_s2")]),
        ("SNV", "v2.1 d46", "7fc7396 recipe (matched to GRCh38-only)", [RIS / f"{s}_{p}_SNV_d46_7fc7396{x}" for x in ("", "_s1", "_s2")]),
        ("SNV", "v1.1 d9", "7fc7396 recipe (matched to GRCh38-only)",
         [RIS / f"{s}_{p}_SNV_7fc7396{'_ddp4_b1024' if p == 'Illumina' else '_ddp4_b1024'}{x}" for x in ("", "_s1", "_s2")]),
        ("INDEL", "v2.1 d46", "final release model, ppr8 (3 seeds)",
         [RUNS / f"release_{sd}_{p}_INDEL" / f"vcf_ppr8_chr1_HG008T_{p}_d46" for sd in ("s0", "s1", "s2")]),
        ("INDEL", "v2.1 d46", "7fc7396 / normbq single-set, recall-0.9 threshold (1 seed)",
         [RIS / (f"{s}_{p}_INDEL_d46_normbq" if p == "Illumina" else f"{s}_{p}_INDEL_d46_7fc7396")]),
        ("INDEL", "v1.1 d9", "7fc7396 / normbq single-set, recall-0.9 threshold (1 seed)",
         [RIS / (f"{s}_{p}_INDEL_d9_normbq" if p == "Illumina" else f"{s}_{p}_INDEL_7fc7396")]),
        ("INDEL", "GRCh38-only", "7fc7396 single-set, recall-0.9 threshold (1 seed)", [RIS / f"{s}_{p}_INDEL_linear_7fc7396"]),
    ]


def mm(xs, nd=3):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "-"
    if len(xs) == 1:
        return f"{xs[0]:.{nd}f}"
    return f"{min(xs):.{nd}f}-{max(xs):.{nd}f} ({sum(xs) / len(xs):.{nd}f})"


out, L = [], ["# HG008T chr1, benchmark BED: PASS without / with population filtering (generated by r26_filter_table.py)", "",
              "Cells: min-max (mean) over seeds; P / R / F1 at the run's PASS threshold; 'best F1' = test-tuned upper bound.", "",
              "| kind | platform | graph | model | n | without filter P / R / F1 | with filter P / R / F1 | best F1 without / with | post-filter ceiling |",
              "|---|---|---|---|---|---|---|---|---|"]
for p in PLATS:
    for kind, graph, model, dirs in groups(p):
        vals = []
        for d in dirs:
            if d.name.startswith("vcf_ppr8"):
                f = d / "eval_bed" / "report.json"
                r, path = (json.loads(f.read_text()), str(f)) if f.exists() else (None, None)
            else:
                r, path = rep(d, kind)
            if r is None:
                vals.append(dict(run=str(d), missing=True))
                continue
            a, b = r["raw"]["at_threshold"], r["pon"]["at_threshold"]
            vals.append(dict(run=str(d), report=path, raw=a, pon=b, raw_best=r["raw"].get("best", {}).get("f1"),
                             pon_best=r["pon"].get("best", {}).get("f1"), ceiling=r["pon"].get("ceiling"),
                             threshold=r.get("threshold"), truth_pon_tagged=(r.get("truth_pon_tags") or {}).get("tagged")))
        ok = [v for v in vals if not v.get("missing")]
        out.append(dict(kind=kind, platform=p, graph=graph, model=model, runs=vals))
        if not ok:
            L.append(f"| {kind} | {p} | {graph} | {model} | 0 | MISSING | MISSING | - | - |")
            continue
        g = lambda blk, k: [v[blk][k] for v in ok]  # noqa: E731
        L.append(f"| {kind} | {p} | {graph} | {model} | {len(ok)} | {mm(g('raw', 'precision'))} / {mm(g('raw', 'recall'))} / "
                 f"{mm(g('raw', 'f1'))} | {mm(g('pon', 'precision'))} / {mm(g('pon', 'recall'))} / {mm(g('pon', 'f1'))} | "
                 f"{mm([v['raw_best'] for v in ok])} / {mm([v['pon_best'] for v in ok])} | {mm([v['ceiling'] for v in ok])} |")
(HERE / "r26_filter_table.md").write_text("\n".join(L) + "\n")
(HERE / "r26_filter_table.json").write_text(json.dumps(out, indent=1) + "\n")
print("\n".join(L))
