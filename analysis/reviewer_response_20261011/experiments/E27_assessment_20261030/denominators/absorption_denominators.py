#!/usr/bin/env python3
"""Absorption with full-truth denominators (R1.4 fact sheet, 2026-10-30). Read-only on E5b / E5c outputs.

Inputs
  E5b per-truth table  /scratch/jshen/data/reviewer_experiments_20261013/E5b_absorbed_d46/per_truth.tsv.gz
      (one row per somatic truth allele, chr1-22, all records; per platform x arm status T/A/F/N; pon = current
      PoN tags (INDEL rule HP>=8: 0.01, else 1e-4), d9_spelled / d46_spelled = ALT spelled by a graph path)
  E5c per-locus table  /scratch/jshen/data/reviewer_experiments_20261013/E5c_d46_loss_reads/per_locus.tsv.gz
      (class I1 = entire ALT reads on graph alt nodes without edit, I2 = alt nodes plus a residual edit; d46 only)
Definitions (per platform p, arm g in d46 / d9)
  strict   = E5b section 2/3: tensor_representative on GRCh38-only (linear T), no candidate on g (N), ALT spelled by g
  arm-only = E8c / E5b section 7: no candidate on g (N) and ALT spelled by g (no GRCh38-only condition)
  spelled  = E5b section 5: ALT spelled by g (independent of reads)
  broad    = E5c: a tensor allele equals the truth on GRCh38-only (T or A) and none on g (not T/A); net = broad lost
             untagged minus gained untagged (tensor allele on g, none on GRCh38-only)
Scopes: chr1-22 all truth records (E5b denominators); chr1-22 in the truth BED; chr1 in the truth BED (vcfeval scope).
Writes absorption_denominators.md / .json next to this script.
"""
import csv
import gzip
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
PT = "/scratch/jshen/data/reviewer_experiments_20261013/E5b_absorbed_d46/per_truth.tsv.gz"
E5C = "/scratch/jshen/data/reviewer_experiments_20261013/E5c_d46_loss_reads/per_locus.tsv.gz"
PLATS = {"HG008T": ["Illumina", "PacBio", "ONT"], "COLO829T": ["Illumina", "fiberseq", "ONT"]}
HAS = ("T", "A")

rows = [r for r in csv.DictReader(gzip.open(PT, "rt"), delimiter="\t") if r["sample"] in PLATS]
for r in rows:
    r["kind2"] = "SNV" if r["kind"] == "SNP" else "INDEL"
    r["tagged"] = bool(r["pon"])
e5c = {}
for r in csv.DictReader(gzip.open(E5C, "rt"), delimiter="\t"):
    if r["locus_set"] == "lost":
        e5c[(r["set"], r["truth_id"])] = r["cls"]

SCOPES = {"chr1-22 all records": lambda r: True,
          "chr1-22 in BED": lambda r: r["in_bed"] == "True",
          "chr1 in BED": lambda r: r["chrom"] == "chr1" and r["in_bed"] == "True"}


def strict(r, p, g):
    return r[f"{p}_linear"] == "T" and r[f"{p}_{g}"] == "N" and r[f"{g}_spelled"] == "1"


def armonly(r, p, g):
    return r[f"{p}_{g}"] == "N" and r[f"{g}_spelled"] == "1"


def cnt(sub):
    n = len(sub)
    t = sum(r["tagged"] for r in sub)
    return dict(n=n, tagged=t, untagged=n - t)


out = {}
L = ["# Absorption with full-truth denominators (generated by absorption_denominators.py)", ""]
for scope, keep in SCOPES.items():
    L += [f"## {scope}", ""]
    for s, plats in PLATS.items():
        for kind in ("SNV", "INDEL"):
            sub = [r for r in rows if r["sample"] == s and r["kind2"] == kind and keep(r)]
            N = len(sub)
            tot = cnt(sub)
            key = f"{scope}|{s}|{kind}"
            res = dict(n=N, tagged=tot["tagged"], untagged=tot["untagged"])
            pc = lambda x: f"{100 * x / N:.2f}%" if N else "-"  # noqa: E731
            L.append(f"### {s} {kind}: truth n = {N:,}; population-tagged {tot['tagged']:,} ({pc(tot['tagged'])}); "
                     f"not tagged {tot['untagged']:,} ({pc(tot['untagged'])})")
            L += ["", "| arm | definition | platform | absorbed | tagged | NOT tagged | NOT tagged, % of truth | absorbed, % of truth |",
                  "|---|---|---|---:|---:|---:|---:|---:|"]
            for g in ("d46", "d9"):
                for dname, fn in (("strict", strict), ("arm-only", armonly)):
                    per = {}
                    for p in plats:
                        a = cnt([r for r in sub if fn(r, p, g)])
                        per[p] = a
                        L.append(f"| {g} | {dname} | {p} | {a['n']:,} | {a['tagged']:,} | {a['untagged']:,} | "
                                 f"{pc(a['untagged'])} | {pc(a['n'])} |")
                    u = cnt([r for r in sub if any(fn(r, p, g) for p in plats)])
                    al = cnt([r for r in sub if all(fn(r, p, g) for p in plats)])
                    per["union"], per["all3"] = u, al
                    L.append(f"| {g} | {dname} | >= 1 platform | {u['n']:,} | {u['tagged']:,} | {u['untagged']:,} | "
                             f"{pc(u['untagged'])} | {pc(u['n'])} |")
                    L.append(f"| {g} | {dname} | all 3 platforms | {al['n']:,} | {al['tagged']:,} | {al['untagged']:,} | "
                             f"{pc(al['untagged'])} | {pc(al['n'])} |")
                    res[f"{g}|{dname}"] = per
                sp = cnt([r for r in sub if r[f"{g}_spelled"] == "1"])
                res[f"{g}|spelled"] = sp
                L.append(f"| {g} | ALT spelled by graph (any reads) | - | {sp['n']:,} | {sp['tagged']:,} | {sp['untagged']:,} | "
                         f"{pc(sp['untagged'])} | {pc(sp['n'])} |")
            # broad E5c loss and net, d46 and d9, per platform; I1 / I2 split from E5c (d46 only)
            L += ["", "| arm | platform | broad lost (any reason) | % of truth | lost tagged | lost NOT tagged (% truth) | "
                  "gained NOT tagged | net NOT tagged loss (% truth) | of lost NOT tagged: strict absorbed | E5c I1 entire | E5c I2 partial |",
                  "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
            for g in ("d46", "d9"):
                for p in plats:
                    lost = [r for r in sub if r[f"{p}_linear"] in HAS and r[f"{p}_{g}"] not in HAS]
                    gained = [r for r in sub if r[f"{p}_{g}"] in HAS and r[f"{p}_linear"] not in HAS]
                    lu = [r for r in lost if not r["tagged"]]
                    gu = [r for r in gained if not r["tagged"]]
                    sa = sum(strict(r, p, g) for r in lu)
                    if g == "d46":
                        setname = f"{s}_{p}_d46"
                        cl = [e5c.get((setname, r["truth_id"]), "?") for r in lu]
                        i1 = sum(c.startswith("I1") for c in cl)
                        i2 = sum(c.startswith("I2") for c in cl)
                        miss = sum(c == "?" for c in cl)
                    else:
                        i1 = i2 = miss = None
                    lt = len(lost) - len(lu)
                    res[f"{g}|broad|{p}"] = dict(lost=len(lost), lost_tagged=lt, lost_untagged=len(lu), gained=len(gained),
                                                 gained_untagged=len(gu), net_untagged=len(lu) - len(gu),
                                                 strict_absorbed_in_lost_untagged=sa, I1=i1, I2=i2, e5c_missing=miss)
                    L.append(f"| {g} | {p} | {len(lost):,} | {pc(len(lost))} | {lt:,} | {len(lu):,} ({pc(len(lu))}) | "
                             f"{len(gu):,} | {len(lu) - len(gu):,} ({pc(len(lu) - len(gu))}) | {sa:,} | "
                             f"{'-' if i1 is None else i1} | {'-' if i2 is None else i2}"
                             f"{'' if not miss else f' ({miss} not in E5c)'} |")
            L.append("")
            out[key] = res
(HERE / "absorption_denominators.md").write_text("\n".join(L) + "\n")
(HERE / "absorption_denominators.json").write_text(json.dumps(out, indent=1) + "\n")
print("\n".join(L))
