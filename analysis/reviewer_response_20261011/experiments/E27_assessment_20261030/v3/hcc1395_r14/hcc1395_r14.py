#!/usr/bin/env python3
"""HCC1395T column of the letter's Supplementary Table R1.4 (candidate loss on HPRC v2.1 vs GRCh38-only, and its overlap
with population filtering), chr1-22, all truth records, on the definitions of ../../denominators/absorption_denominators.py.

Inputs (read-only)
  E5b per-truth table /scratch/jshen/data/reviewer_experiments_20261013/E5b_absorbed_d46/per_truth.tsv.gz: one row per
      somatic truth allele; per platform x arm status T / A / F / N; pon = population-filter tags of the current rule
      (allele-exact; INDEL HP >= 8: AF >= 0.01, else AF >= 1e-4). Its HCC1395T rows carry d46 statuses only, because
      the HCC1395T GRCh38-only and HPRC v1.1 sets were built later (tmp/hcc1395_linear_d9_20261104, finalized 11-07).
  HCC1395T_<p>_linear and HCC1395T_<p>_d9 tensors/somatic.recall.tsv (/scratch/jshen/data/pansoma_v2_tensors): the
      missing statuses, coded as in E5b s1_status_matrix.py; truth_id / chrom / vcf_pos / kind are checked row by row
      against per_truth, and the d46 statuses against the current HCC1395T_<p>_d46 sets.
Definitions (per platform p, arm g; as absorption_denominators.py)
  broad lost = a tensor allele equals the truth on GRCh38-only (T or A) and none does on g (not T / A)
  net NOT-tagged loss = broad lost and not tagged, minus gained and not tagged (tensor allele on g, none on GRCh38-only)
The HG008T / COLO829T cells are recomputed from per_truth unchanged, as a check against the published table.
Writes hcc1395_r14.md / .json next to this script.
"""
import csv
import gzip
import json
from pathlib import Path

csv.field_size_limit(1 << 30)
HERE = Path(__file__).resolve().parent
PT = "/scratch/jshen/data/reviewer_experiments_20261013/E5b_absorbed_d46/per_truth.tsv.gz"
T = Path("/scratch/jshen/data/pansoma_v2_tensors")
PLATS = {"HG008T": ["Illumina", "PacBio", "ONT"], "COLO829T": ["Illumina", "fiberseq", "ONT"],
         "HCC1395T": ["Illumina", "PacBio", "ONT"]}
LABEL = {"Illumina": "Illumina", "PacBio": "PacBio HiFi", "fiberseq": "Fiber-seq", "ONT": "ONT"}
CODE = {"tensor_representative": "T", "tensor_non_representative_allele": "A", "filtered": "F", "no_candidate": "N",
        "complex_allele": "C", "no_unique_grch38_node_key": "K"}
HAS = ("T", "A")

rows = [r for r in csv.DictReader(gzip.open(PT, "rt"), delimiter="\t")]
for r in rows:
    r["kind2"] = "SNV" if r["kind"] == "SNP" else "INDEL"
    r["tagged"] = bool(r["pon"])

# HCC1395T: fill linear / d9 from the current sets; check d46 against the current sets
hcc = [r for r in rows if r["sample"] == "HCC1395T"]
for p in PLATS["HCC1395T"]:
    for arm, suf in (("linear", "_linear"), ("d9", "_d9"), ("d46", "_d46")):
        rec = list(csv.DictReader(open(T / f"HCC1395T_{p}{suf}" / "tensors" / "somatic.recall.tsv"), delimiter="\t"))
        assert len(rec) == len(hcc), (p, arm, len(rec), len(hcc))
        for r, b in zip(hcc, rec):
            assert (r["truth_id"], r["chrom"], r["vcf_pos"], r["kind"]) == (b["truth_id"], b["chrom"], b["vcf_pos"], b["kind"]), (p, arm, r["truth_id"])
            code = CODE.get(b["status"], b["status"][:2])
            if arm == "d46":
                assert r[f"{p}_d46"] == code, (p, r["truth_id"], r[f"{p}_d46"], code)
            else:
                assert r[f"{p}_{arm}"] == "", (p, arm, r["truth_id"])
                r[f"{p}_{arm}"] = code

out = {}
for s, plats in PLATS.items():
    for kind in ("INDEL", "SNV"):
        sub = [r for r in rows if r["sample"] == s and r["kind2"] == kind]
        n = len(sub)
        res = dict(n=n, tagged=sum(r["tagged"] for r in sub))
        for g in ("d46", "d9"):
            for p in plats:
                lost = [r for r in sub if r[f"{p}_linear"] in HAS and r[f"{p}_{g}"] not in HAS]
                gained = [r for r in sub if r[f"{p}_{g}"] in HAS and r[f"{p}_linear"] not in HAS]
                lu = sum(not r["tagged"] for r in lost)
                gu = sum(not r["tagged"] for r in gained)
                res[f"{g}|{p}"] = dict(lost=len(lost), lost_tagged=len(lost) - lu, lost_untagged=lu, gained=len(gained),
                                       gained_untagged=gu, net_untagged=lu - gu)
        out[f"{s}|{kind}"] = res
(HERE / "hcc1395_r14.json").write_text(json.dumps(out, indent=1) + "\n")


def pct(x, n, d=1):
    return f"{100 * x / n:.{d}f}%"


def rng(vals, d=1):
    lo, hi = f"{100 * min(vals):.{d}f}", f"{100 * max(vals):.{d}f}"
    return f"{lo}%" if lo == hi else f"{lo}–{hi}%"


COLS = [(s, k) for k in ("INDEL", "SNV") for s in PLATS]
L = ["# Supplementary Table R1.4 with HCC1395T (generated by hcc1395_r14.py)", "",
     "## Letter rows (HPRC v2.1 and v1.1; % of all chr1–22 truth alleles, last row % of the lost alleles; ranges over three platforms)", "",
     "| HPRC graphs | " + " | ".join(f"{s} {k}s" for s, k in COLS) + " |", "|---|" + "---|" * len(COLS)]
L.append("| truth alleles, chr1–22 | " + " | ".join(f"{out[f'{s}|{k}']['n']:,}" for s, k in COLS) + " |")
L.append("| somatic truth alleles tagged by population filtering | "
         + " | ".join(pct(out[f"{s}|{k}"]["tagged"], out[f"{s}|{k}"]["n"]) for s, k in COLS) + " |")
for g, gname in (("d46", "v2.1"), ("d9", "v1.1")):
    L.append(f"| candidate on the GRCh38-only graph but not on {gname} | " + " | ".join(
        rng([out[f"{s}|{k}"][f"{g}|{p}"]["lost"] / out[f"{s}|{k}"]["n"] for p in PLATS[s]]) for s, k in COLS) + " |")
    L.append(f"| graph-specific loss left after filtering ({gname}) | " + " | ".join(
        rng([out[f"{s}|{k}"][f"{g}|{p}"]["net_untagged"] / out[f"{s}|{k}"]["n"] for p in PLATS[s]]) for s, k in COLS) + " |")
    L.append(f"| of the lost alleles, tagged ({gname}) | " + " | ".join(
        rng([out[f"{s}|{k}"][f"{g}|{p}"]["lost_tagged"] / out[f"{s}|{k}"][f"{g}|{p}"]["lost"] for p in PLATS[s]]) for s, k in COLS) + " |")
L += ["", "## Per platform (counts; % of truth)", "",
      "| tumor | kind | graph | platform | lost vs GRCh38-only | of which tagged | lost, not tagged | gained, not tagged | net not-tagged loss |",
      "|---|---|---|---|---:|---:|---:|---:|---:|"]
for s, k in COLS:
    x = out[f"{s}|{k}"]
    for g, gname in (("d46", "v2.1"), ("d9", "v1.1")):
        for p in PLATS[s]:
            y = x[f"{g}|{p}"]
            L.append(f"| {s} | {k} | {gname} | {LABEL[p]} | {y['lost']:,} ({pct(y['lost'], x['n'])}) | "
                     f"{y['lost_tagged']:,} ({pct(y['lost_tagged'], y['lost']) if y['lost'] else '-'} of lost) | "
                     f"{y['lost_untagged']:,} | {y['gained_untagged']:,} | {y['net_untagged']:,} ({pct(y['net_untagged'], x['n'], 2)}) |")
L += ["", "v1.1 (d9): HG008T / COLO829T from per_truth, HCC1395T from the HCC1395T_<p>_d9 sets."]
(HERE / "hcc1395_r14.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
