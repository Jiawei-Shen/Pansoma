#!/usr/bin/env python3
"""Supplementary Table R1.3a before population filtering on the LATEST SNV models (user 2026-11-12: "the v2.1 6 tumor
model is updated. Make sure the results corresponding to the latest results").

Which rows have newer models than region_nopon.py's table (the old single-tumor 7fc7396 models, PASS at validation
recall 0.9):
- COLO829T Illumina / Fiber-seq: the current SNV pipeline (AF 0.05 sets, site features, rule 2 PASS), single-tumor,
  seed 0, on all three references (snv_newpipe_20261109/COLO829_<P>_SNV_{linear,d9,d46}_newpipe): recomputed here, same
  strata, 1-Mb blocks, 2,000 resamples and seed as region_nopon.py (rtg raw_calls, complete truth).
- HG008T (not rebuilt / retrained, user 11-09), every ONT row (original recipe) and the INDEL column: unchanged, copied
  from cells.json (region_nopon.py).
- Six-tumor models: only HPRC v2.1 is trained (multicancer6_<P>_SNV_newpipe, final 2026-11-12; ONT multicancer6_ONT_SNV
  normfix). Their GRCh38-only / v1.1 counterparts (tmp/m4m6_graphs_20261110) are still training, so there is no pair
  and no dF1 yet; section 2 lists the v2.1 six-tumor model alone per stratum (before -> after the filter), with HCC1395T.
Check: the chr1 totals of every raw_calls / pon_calls directory equal the run's report.json.
Writes tables_latest.md / cells_latest.json. usage: /wanglab/jshen/anaconda3/bin/python region_nopon_latest.py
"""
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
EXP = Path("/scratch/jshen/Github/Pansoma/analysis/reviewer_response_20261011/experiments")
sys.path.insert(0, str(EXP / "E16_bootstrap"))
sys.path.insert(0, str(EXP / "E10b_giab_strata"))
import callsets as C  # noqa: E402
import e16_bootstrap as E  # noqa: E402
import giab_strata as G  # noqa: E402
from region_nopon import GIAB_ST, GNAME, SETS, SMAHT_EXTREME, bed_chr1  # noqa: E402  (also reruns its checks)

RUNS = Path("/scratch/jshen/data/pansoma_net_v2_runs")
NEW = RUNS / "snv_newpipe_20261109"
PARTS = ("tp-baseline", "fn", "tp", "fp")
SUF = {"linear": "_linear", "d9": "", "d46": "_d46"}
single = {(f"COLO829T_{p}", arm): NEW / f"COLO829_{p}_SNV_{arm}_newpipe/vcf_chr1_COLO829T_{p}{SUF[arm]}"
          for p in ("Illumina", "fiberseq") for arm in SUF}
six = {}
for t, plats in (("HG008T", ("Illumina", "PacBio", "ONT")), ("COLO829T", ("Illumina", "fiberseq", "ONT")),
                 ("HCC1395T", ("Illumina", "PacBio", "ONT"))):
    for p in plats:
        m = "PacBio" if p == "fiberseq" else p
        six[f"{t}_{p}"] = (RUNS / f"multicancer6_ONT_SNV/vcf_chr1_{t}_ONT_d46_normfix" if p == "ONT" else
                           NEW / f"multicancer6_{m}_SNV_newpipe/vcf_chr1_{t}_{p}_d46")

ivs = {"extreme": bed_chr1(SMAHT_EXTREME)}
ivs.update({name: G.chr1_intervals(G.GIAB / rel) for name, rel, _ in G.STRATA if name in dict(GIAB_ST)})
bs = E.BlockSets(C.fasta_path(), 2000, 20261015)


def score(vcf_dir, which):
    rep = json.loads((vcf_dir / "eval_bed/report.json").read_text())
    w = vcf_dir / "eval_bed/vcfeval" / which
    assert C._rtg_complete(w), w
    rec = {p: np.array([r[1] for r in C.read_records(w / f"{p}.vcf.gz") if r[0] == "chr1"], dtype=np.int64) for p in PARTS}
    a = rep["raw" if which == "raw_calls" else "pon"]["at_threshold"]
    assert (len(rec["tp-baseline"]), len(rec["fn"]), len(rec["fp"])) == (a["tp_baseline"], a["fn"], a["fp"]), (w, a)
    blocks = bs.get("bed", rep["bed"], G.WIDTH)
    out = {}
    for name, iv in ivs.items():
        m = E.block_counts({p: rec[p][G.inside(rec[p], iv)].tolist() for p in PARTS}, blocks)
        out[name] = (m.sum(axis=0), blocks.mult @ m, blocks.key)
    return out


def paired(a, b):
    assert a[2] == b[2]
    lo, hi, _, _ = E.ci(E.metrics(a[1])[2] - E.metrics(b[1])[2])
    return float(E.metrics(a[0])[2] - E.metrics(b[0])[2]), lo, hi


f3 = lambda x: "-" if np.isnan(x) else f"{x:.3f}"  # noqa: E731
ci = lambda t: f"{t[0]:+.3f} [{t[1]:+.3f}, {t[2]:+.3f}]"  # noqa: E731
prf = lambda t: " / ".join(f3(float(v)) for v in E.metrics(t)[:3])  # noqa: E731
old = json.loads((HERE / "cells.json").read_text())["cells"]
X = {k: score(d, "raw_calls") for k, d in single.items()}
R = {k: score(d, "pon_calls") for k, d in single.items()}
cells, changed = {}, []
L = ["# Supplementary Table R1.3a before population filtering, latest SNV models (generated by region_nopon_latest.py)", "",
     "chr1, benchmark regions, no population filter (rtg raw_calls; complete truth), 1-Mb blocks, 2,000 resamples, seed "
     "20261015. **Bold rows changed**: COLO829T Illumina / Fiber-seq now use the current SNV pipeline on all three "
     "references (AF 0.05 sets, site features, PASS = rule 2; single-tumor, seed 0). HG008T, ONT and the INDEL column "
     "are unchanged (old recipe, PASS at validation recall 0.9; region_nopon.py).", "",
     "| chr1 | graph | SMaHT extreme: PASS calls (precision), GRCh38-only → HPRC | SMaHT extreme ΔF1 | "
     + " | ".join(f"GIAB {n} ΔF1" for _, n in GIAB_ST) + " | INDEL F1, homopolymers ≥ 7 bp: GRCh38-only → HPRC |",
     "|---" * (4 + len(GIAB_ST) + 1) + "|"]
for s, lab in SETS:
    for arm in ("d9", "d46"):
        row = old[f"{s}|{arm}"]
        if (s, arm) in single:
            lin, a = X[(s, "linear")], X[(s, arm)]
            t0, t1 = lin["extreme"][0], a["extreme"][0]
            row = [f"{int(t0[2] + t0[3]):,} ({f3(E.metrics(t0)[0])}) → {int(t1[2] + t1[3]):,} ({f3(E.metrics(t1)[0])})",
                   ci(paired(a["extreme"], lin["extreme"]))] + [ci(paired(a[st], lin[st])) for st, _ in GIAB_ST] + [row[-1]]
            changed.append(f"{s}|{arm}")
            L.append(f"| **{lab}** | **{GNAME[arm]}** | " + " | ".join(row) + " |")
        else:
            L.append(f"| {lab} | {GNAME[arm]} | " + " | ".join(row) + " |")
        cells[f"{s}|{arm}"] = row
L += ["", "## Per call set (changed rows): SNV P / R / F1 before → after population filtering", "",
      "| set | graph | SMaHT extreme | GIAB all difficult | GIAB not difficult |", "|---|---|---|---|---|"]
for s, lab in SETS:
    for arm in ("linear", "d9", "d46"):
        if (s, arm) in single:
            L.append(f"| {lab} | {'GRCh38-only' if arm == 'linear' else GNAME[arm]} | " + " | ".join(
                prf(X[(s, arm)][st][0]) + " → " + prf(R[(s, arm)][st][0])
                for st in ("extreme", "alldifficultregions", "notinalldifficultregions")) + " |")
# ---- six-tumor model, HPRC v2.1 only (no GRCh38-only / v1.1 six-tumor model yet)
S6 = {k: (score(d, "raw_calls"), score(d, "pon_calls")) for k, d in six.items()}
L += ["", "## 2. Six-tumor SNV model on HPRC v2.1, per stratum (no pair yet)", "",
      "multicancer6_<P>_SNV_newpipe (PacBio HiFi / Illumina, final 2026-11-12, PASS = rule 2; HCC1395T on its AF 0.05 "
      "sets) and multicancer6_ONT_SNV normfix (ONT). The six-tumor models on GRCh38-only / HPRC v1.1 "
      "(tmp/m4m6_graphs_20261110) are still training, so no ΔF1. SNV P / R / F1 before → after population filtering.", "",
      "| chr1 | SMaHT extreme: PASS calls before | SMaHT extreme | GIAB all difficult | GIAB low mappability or segdup | "
      "GIAB tandem repeats and homopolymers | GIAB not difficult |", "|---|---|---|---|---|---|---|"]
six_cells = {}
for k, (b, a) in S6.items():
    t = b["extreme"][0]
    row = [f"{int(t[2] + t[3]):,}"] + [prf(b[st][0]) + " → " + prf(a[st][0]) for st in ["extreme"] + [x for x, _ in GIAB_ST]]
    six_cells[k] = row
    L.append(f"| {k.replace('_', ' ').replace('fiberseq', 'Fiber-seq').replace('PacBio', 'PacBio HiFi')} | " + " | ".join(row) + " |")
(HERE / "tables_latest.md").write_text("\n".join(L) + "\n")
(HERE / "cells_latest.json").write_text(json.dumps(dict(
    changed=changed, cells=cells, six_tumor_v21=six_cells, runs={"|".join(k): str(v) for k, v in single.items()},
    six_runs={k: str(v) for k, v in six.items()}), indent=1) + "\n")
print("\n".join(L))
