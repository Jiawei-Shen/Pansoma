#!/usr/bin/env python3
"""Suppl. Table R1.6a extra comparator rows "no PoN -> native PoN filter" (user 2026-11-10), HCC1395T columns added (11-10).

Reads E8 score_comparator.py reports (eval_bed = chr1 inside the benchmark BED, complete truth):
  native  /scratch/jshen/data/reviewer_experiments_20261013/E8_comparators/score/<caller>/<set>/<KIND>/report.json
          (the published comparator rows: the caller's own PASS, its built-in population filter on)
  no PoN  .../E8_comparators/score_nopon{,_rerun}/<caller>/<set>/<KIND>/report.json
          DeepSomatic: FILTER PON -> PASS (postprocess_variants only turns PASS into PON);
          ClairS-TO: run_clairs_to --disable_nonsomatic_tagging (score_nopon_rerun/, E27 v3/nopon_comparators, 11-02).
Prints the letter rows (ranges over the three platforms) and a per-run table; writes r16a_rows.md / .json next to it.
"""
import json
import sys
from pathlib import Path

D = Path("/scratch/jshen/data/reviewer_experiments_20261013/E8_comparators")
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent
SETS = {"HG008T": ["HG008T_Illumina", "HG008T_PacBio", "HG008T_ONT"],
        "COLO829T": ["COLO829T_Illumina", "COLO829T_fiberseq", "COLO829T_ONT"],
        "HCC1395T": ["HCC1395T_Illumina", "HCC1395T_PacBio", "HCC1395T_ONT"]}
COLS = [("HG008T", "SNV"), ("COLO829T", "SNV"), ("HCC1395T", "SNV"), ("HG008T", "INDEL"), ("COLO829T", "INDEL"), ("HCC1395T", "INDEL")]
CALLERS = [("deepsomatic", "DeepSomatic-TO"), ("clairs_to", "ClairS-TO")]
NOPON = {"deepsomatic": "score_nopon", "clairs_to": "score_nopon_rerun"}


def at(root, caller, s, kind, which):
    r = json.load(open(D / root / caller / s / kind / "report.json"))
    a = r["eval_bed"][which]["at_threshold"]
    return dict(recall=a["recall"], precision=a["precision"], tp=a["tp_baseline"], baseline=a["tp_baseline"] + a["fn"],
                calls=a["tp_call"] + a["fp"])


res = {}
for c, _ in CALLERS:
    for (t, k) in COLS:
        for s in SETS[t]:
            res[f"{c}|{s}|{k}"] = dict(nopon=at(NOPON[c], c, s, k, "pass"), native=at("score", c, s, k, "pass"),
                                       native_ours=at("score", c, s, k, "pass_pon"))
            assert res[f"{c}|{s}|{k}"]["nopon"]["baseline"] == res[f"{c}|{s}|{k}"]["native"]["baseline"]
(OUT / "r16a_rows.json").write_text(json.dumps(res, indent=1) + "\n")


def rng(vals):
    lo, hi = f"{min(vals):.3f}", f"{max(vals):.3f}"
    return lo if lo == hi else f"{lo}–{hi}"


L = ["# Suppl. Table R1.6a: comparators without their built-in population filter (generated by r16a_rows.py)", "",
     "| recall (chr1, benchmark regions, complete truth) | " + " | ".join(f"{t} {k}" for t, k in COLS) + " |",
     "|---|" + "---|" * len(COLS)]
for c, name in CALLERS:
    cells_a, cells_b = [], []
    for t, k in COLS:
        x = [res[f"{c}|{s}|{k}"] for s in SETS[t]]
        a, b, o = (rng([y[w]["tp"] / y[w]["baseline"] for y in x]) for w in ("nopon", "native", "native_ours"))  # from counts: no double rounding
        cells_a.append(f"{a} → {b}" if a != b else f"{a} (unchanged)")
        cells_b.append(f"{b} → {o}" if b != o else f"{b} (unchanged)")
    L.append(f"| {name} PASS: no PoN → native PoN filter | " + " | ".join(cells_a) + " |")
    L.append(f"| {name} PASS: native → after the same filter | " + " | ".join(cells_b) + " |")
L += ["", "## Per run (recall, precision, PASS calls in the BED)", "",
      "| caller | set | kind | no PoN: R / P / calls | native PoN: R / P / calls | native + our filter: R / P / calls |",
      "|---|---|---|---|---|---|"]
for c, name in CALLERS:
    for t, k in COLS:
        for s in SETS[t]:
            y = res[f"{c}|{s}|{k}"]
            L.append(f"| {name} | {s} | {k} | " + " | ".join(
                f"{y[w]['recall']:.3f} / {y[w]['precision']:.3f} / {y[w]['calls']:,}" for w in ("nopon", "native", "native_ours")) + " |")
(OUT / "r16a_rows.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
