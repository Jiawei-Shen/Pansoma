"""E3: the three reference arms (GRCh38-only linear / HPRC v1.1 d9 / HPRC v2.1 d46) from the 2026-10-12 RIS runs.

Reads analysis/benchmark_7fc7396_20261012/linear_grch38_7fc7396_20261012/summary.json (it holds all three arms per set)
and writes tables.md: after-PoN PASS F1 in the BED, raw, test-tuned best, unplaced PASS calls, and the complete-output
bound that counts every unplaced PASS call as a false positive (no BED: unplaced calls have no GRCh38 position, so the
BED cannot be applied to them). Standard library only.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[2] / "benchmark_7fc7396_20261012" / "linear_grch38_7fc7396_20261012" / "summary.json"
ARMS = ("linear", "d9", "d46")


def f1(tp, fp, fn):
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    return 2 * p * r / (p + r) if p + r else 0.0


def main():
    rows = json.loads(SRC.read_text())
    out = ["# E3 reference arms: chr1 numbers of the 2026-10-12 RIS runs (generated by arms_table.py)", ""]
    out.append(f"Source: `{SRC.relative_to(HERE.parents[2].parent)}`. PASS = each model's validation recall-0.9 "
               "threshold; PoN = the 7fc7396 rule of each kind; 'best' = chr1 curve best F1 (test-tuned, reference only).")
    out.append("")
    out += ["## 1. After the PoN, in the BED: PASS F1 (best F1)", "",
            "| sample | platform | kind | linear | d9 | d46 | d9 - linear | d46 - linear | d46 - d9 |",
            "|---|---|---|---:|---:|---:|---:|---:|---:|"]
    for e in rows:
        v = {a: e[a]["eval_bed"]["pon"] for a in ARMS}
        out.append(f"| {e['sample']} | {e['platform']} | {e['kind']} | " + " | ".join(
            f"{v[a]['f1']:.3f} ({v[a]['best']['f1']:.3f})" for a in ARMS) +
            f" | {v['d9']['f1'] - v['linear']['f1']:+.3f} | {v['d46']['f1'] - v['linear']['f1']:+.3f} | "
            f"{v['d46']['f1'] - v['d9']['f1']:+.3f} |")
    out += ["", "## 2. Complete-output bound (no BED, after the PoN): every unplaced PASS call counted as a false positive", "",
            "Unplaced = PASS calls on off-reference nodes without a GRCh38 position (not scored by rtg). The bound is a "
            "worst case: some unplaced calls are population alleles a graph-native PoN would remove, some may be true "
            "somatic events (E9a / E9c resolve them).", "",
            "| sample | platform | kind | arm | PoN TP / FP / FN | unplaced PASS | F1 placed only | F1 unplaced = FP |",
            "|---|---|---|---|---|---:|---:|---:|"]
    for e in rows:
        for a in ARMS:
            ev = e[a]["eval_nobed"]; p = ev["pon"]; u = ev["unplaced_pass"]
            out.append(f"| {e['sample']} | {e['platform']} | {e['kind']} | {a} | {p['tp']} / {p['fp']} / {p['fn']} | "
                       f"{u:,} | {p['f1']:.3f} | {f1(p['tp'], p['fp'] + u, p['fn']):.3f} |")
    out += ["", "## 3. Candidates and ranking (chr1 tensors; predict)", "",
            "| sample | platform | kind | arm | test tensors | somatic tensors | truth with a tensor (ceiling) | somatic AP | raw PASS calls | raw F1 | PoN ceiling |",
            "|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for e in rows:
        for a in ARMS:
            t = e[a]["test"]; ev = e[a]["eval_bed"]
            out.append(f"| {e['sample']} | {e['platform']} | {e['kind']} | {a} | {t['tensors']:,} | {t['somatic_tensors']:,} | "
                       f"{t['with_tensor']} / {t['truth_alleles']} ({t['ceiling']:.3f}) | {t['somatic_ap']:.3f} | "
                       f"{ev['raw']['evaluated']:,} | {ev['raw']['f1']:.3f} | {ev['pon']['ceiling']:.3f} |")
    out += ["", "## 4. Comparability of the d9 runs", ""]
    for e in rows:
        out.append(f"- {e['sample']} {e['platform']} {e['kind']}: d9 `{e['d9']['run']}` ({e.get('d9_note', '')}); "
                   f"d46 `{e['d46']['run']}`; linear `{e['linear']['run']}`")
    (HERE / "tables.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
