"""E11a full data: table of per-read counts on chr1-22 per dataset and reference, from full_scan.py outputs.

Reads (records; mates counted separately) whose alignment is placed on chr1-chr22: BAM = the primary record's contig;
GAM = the contig holding most of the read's GRCh38-path bases (reads only on off-reference nodes are not placed).
Writes full/results.tsv, full/results.md and full/summary.json.
usage: /wanglab/jshen/anaconda3/bin/python collect_full.py
"""
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = Path('/scratch/jshen/data/reviewer_experiments_20261013/E11a_alignment_stats/full')
SETS = [('HG008T_Illumina', 'HG008T', 'Illumina'), ('COLO829T_Illumina', 'COLO829T', 'Illumina'),
        ('HG008T_PacBio', 'HG008T', 'PacBio HiFi'), ('COLO829T_fiberseq', 'COLO829T', 'PacBio Fiber-seq'),
        ('HG008T_ONT', 'HG008T', 'ONT'), ('COLO829T_ONT', 'COLO829T', 'ONT')]
ARMS = [('grch38_bam', 'GRCh38 (linear, BAM)'), ('linear', 'GRCh38 graph'), ('d9', 'HPRC v1.1 graph'),
        ('d46', 'HPRC v2.1 graph')]
COLS = [('perfect', 'perfectly aligned'), ('sub', 'with substitution'), ('indel', 'with indel'),
        ('clip', 'with soft clipping')]


def main():
    rows, summary, missing = [], {}, []
    for s, tumor, plat in SETS:
        for a, alabel in ARMS:
            p = DATA / f'{s}.{a}.json'
            if not p.exists():
                missing.append(f'{s}.{a}')
                continue
            d = json.loads(p.read_text())
            t = d['chr1_22']
            n = t['records']
            r = dict(dataset=s, tumor=tumor, platform=plat, arm=a, reference=alabel, mapped=n)
            for k, _ in COLS:
                r[k] = t[k]
                r[k + '_pct'] = 100 * t[k] / n if n else None
            r['sub_per_kb'] = 1000 * t['sub_bases'] / t['aligned_bases']
            r['indel_events_per_kb'] = 1000 * t['indel_events'] / t['aligned_bases']
            r['clip_bases_pct'] = 100 * t['clip_bases'] / t['read_bases'] if t['read_bases'] else None
            r['other'] = d['other']
            if d['kind'] == 'gam':
                r['unmapped_file'] = d['per_contig'].get('unmapped', {}).get('records', 0)
                r['unplaced_file'] = d['per_contig'].get('unplaced', {}).get('records', 0)
            rows.append(r)
            summary[f'{s}.{a}'] = r
    with open(HERE / 'results.tsv', 'w', newline='') as f:
        w = csv.writer(f, delimiter='\t')
        w.writerow(['tumor', 'platform', 'reference', 'mapped reads (chr1-22)'] +
                   [x for k, lab in COLS for x in (f'{lab} N', f'{lab} %')] +
                   ['substituted bases per aligned kb', 'indel events per aligned kb', 'soft-clipped bases % of read bases'])
        for r in rows:
            w.writerow([r['tumor'], r['platform'], r['reference'], r['mapped']] +
                       [x for k, _ in COLS for x in (r[k], f'{r[k + "_pct"]:.2f}')] +
                       [f'{r["sub_per_kb"]:.3f}', f'{r["indel_events_per_kb"]:.3f}', f'{r["clip_bases_pct"]:.3f}'])
    L = ['# E11a full data, chr1-22 (generated by collect_full.py)', '',
         'Mapped reads placed on chr1-22 (mates counted separately); N (% of mapped reads).', '',
         '| tumor | platform | reference | mapped reads | perfectly aligned | with substitution | with indel | '
         'with soft clipping |', '|---|---|---|---:|---:|---:|---:|---:|']
    for r in rows:
        L.append(f"| {r['tumor']} | {r['platform']} | {r['reference']} | {r['mapped']:,} | " +
                 ' | '.join(f"{r[k]:,} ({r[k + '_pct']:.2f}%)" for k, _ in COLS) + ' |')
    if missing:
        L += ['', 'Not yet scanned: ' + ', '.join(missing)]
    (HERE / 'results.md').write_text('\n'.join(L) + '\n')
    (HERE / 'summary.json').write_text(json.dumps(summary, indent=1) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
