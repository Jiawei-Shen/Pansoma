#!/usr/bin/env python3
"""E22 check 1: tables.md + summary_tables.json from the per-allele tables (W/<set>.alleles.tsv.gz) and summary.json.

Autosomes only for the regional rows (chrX is hemizygous or LOH in several normals). "Common" = gnomAD AF >= 1 %
(exact allele). Normal-LOH segments = runs of 1-Mb bins where the normal's germline het fraction < 0.2 (summary.json,
truth_germline_check.py); only segments >= 3 Mb outside chr17:23-26 Mb (centromere, low in every normal) are listed.
"""
import csv
import gzip
import json
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
W = Path("/scratch/jshen/data/reviewer_experiments_20261013/E22_truth_and_version_checks")
AUTO = {f"chr{i}" for i in range(1, 23)}


def load(name):
    with gzip.open(W / f"{name}.alleles.tsv.gz", "rt") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    for r in rows:
        r["pos"] = int(r["pos"])
        r["gnomad"] = float(r["gnomad_af"]) if r["gnomad_af"] else None
        r["common"] = r["gnomad"] is not None and r["gnomad"] >= 0.01
        r["vaf"] = float(r["tumor_vaf"]) if r["tumor_vaf"] else None
        for k in ("in_bed", "normal_exact", "normal_exact_q10", "label_germ", "normal_pos_other", "merged_germline"):
            r[k] = int(r[k])
    return rows


def pct(a, b):
    return f"{100 * a / b:.2f} %" if b else "NA"


def med(v):
    v = sorted(v)
    return round(v[len(v) // 2], 3) if v else None


def main():
    s = json.loads((HERE / "summary.json").read_text())
    sets = list(csv.DictReader(open(HERE / "sets.tsv"), delimiter="\t"))
    out = {}
    lines_md = ["# E22 check 1 tables (generated by make_tables.py; do not edit)", ""]
    t1 = ["| truth set | used by Pansoma | SNV alleles (all / in BED) | normal carries the same allele (any QUAL / QUAL >= 10) "
          "| normal germline call at the same POS, other allele | site is a FILTER GERMLINE record in the full VCF (merge) "
          "| gnomAD AF >= 1 % (all / in BED) | CoLoRSdb AF >= 1 % (all) |",
          "|---|---|---|---|---|---|---|---|"]
    t2 = ["| truth set | common SNVs (autosomes) | in normal-LOH bins (het fraction < 0.1) | autosomal bins with het < 0.1 "
          "| rare SNVs in those bins | normal-LOH segments >= 3 Mb (het fraction < 0.2) | common SNVs in the segments "
          "| all truth SNVs in the segments | tumor VAF median: common / rare |",
          "|---|---|---|---|---|---|---|---|---|"]
    t3 = ["| truth set | chr1 SNVs | chr1 common | chr1 common in normal-LOH bins |", "|---|---|---|---|"]
    t4 = ["| truth set | normal chr20 germline SNVs in BED (QUAL >= 10) | gnomAD AF >= 1 % | observed common share of truth "
          "SNVs (all) | SEQC2 HCC1395 share (somatic reference) | implied germline-like share of truth SNVs | implied count |",
          "|---|---|---|---|---|---|---|"]
    t5 = ["| truth set | INDEL alleles | normal same allele | gnomAD AF >= 1 % | CoLoRSdb AF >= 1 % |", "|---|---|---|---|---|"]
    ref = [r for r in load("HCC1395_SEQC2") if r["kind"] == "SNV"]
    p_som = sum(r["common"] for r in ref) / len(ref)  # somatic reference: SEQC2 HCC1395 truth
    for row in sets:
        name = row["name"]
        rows = load(name)
        snv = [r for r in rows if r["kind"] == "SNV"]
        ind = [r for r in rows if r["kind"] == "INDEL"]
        sm = s["sets"][name]
        a = sm["SNV_all"]
        n, nb = len(snv), sum(r["in_bed"] for r in snv)
        com = [r for r in snv if r["common"]]
        com_b = sum(r["in_bed"] for r in com)
        t1.append(f"| {name} | {row['used_by_pansoma']} | {n:,} / {nb:,} | {a['normal_exact']:,} / {a['normal_exact_q10']:,} "
                  f"| {a['normal_pos_other']:,} | {a['merged_germline']:,} | {len(com):,} ({pct(len(com), n)}) / "
                  f"{com_b:,} ({pct(com_b, nb)}) | {a['colorsdb_ge1pct']:,} ({pct(a['colorsdb_ge1pct'], n)}) |")
        # regional, autosomes
        line = sm["normal_line"]
        segs = [g for g in s["normals"][line]["lowhet_segments_lt0.2"]
                if g["mb"] >= 3 and not (g["chrom"] == "chr17" and g["start_mb"] == 23)]
        def in_seg(r):
            return any(r["chrom"] == g["chrom"] and g["start_mb"] * 1_000_000 <= r["pos"] < g["end_mb"] * 1_000_000
                       for g in segs)
        com_a = [r for r in com if r["chrom"] in AUTO]
        rare_a = [r for r in snv if r["chrom"] in AUTO and not r["common"] and not r["normal_exact"]]
        low = [r for r in com_a if r["normal_bin_class"] == "het0.0-0.1"]
        rare_low = [r for r in rare_a if r["normal_bin_class"] == "het0.0-0.1"]
        in_segs = [r for r in com_a if in_seg(r)]
        all_segs = [r for r in snv if r["chrom"] in AUTO and in_seg(r)]
        gcls = s["normals"][line]["genome_bin_classes"]
        seg_txt = ", ".join(f"{g['chrom']}:{g['start_mb']}-{g['end_mb']} Mb" for g in segs) or "none"
        t2.append(f"| {name} | {len(com_a):,} | {len(low):,} ({pct(len(low), len(com_a))}) | {gcls.get('het0.0-0.1', 0)} of "
                  f"{sum(gcls.values())} | {len(rare_low):,} | {seg_txt} | {len(in_segs):,} ({pct(len(in_segs), len(com_a))}) "
                  f"| {len(all_segs):,} ({pct(len(all_segs), n)}) | {med([r['vaf'] for r in com if r['vaf'] is not None])} / "
                  f"{med([r['vaf'] for r in snv if r['vaf'] is not None and not r['common']])} |")
        c1 = [r for r in snv if r["chrom"] == "chr1"]
        c1c = [r for r in c1 if r["common"]]
        t3.append(f"| {name} | {len(c1):,} | {len(c1c):,} ({pct(len(c1c), len(c1))}) | "
                  f"{sum(r['normal_bin_class'] == 'het0.0-0.1' for r in c1c):,} |")
        base = sm["germline_baseline_chr20_in_bed"]
        p_germ = base["gnomad_ge1pct"] / base["n"]
        p_obs = len(com) / n
        est = (p_obs - p_som) / (p_germ - p_som) if p_som is not None else None
        t4.append(f"| {name} | {base['n']:,} | {base['gnomad_ge1pct']:,} ({pct(base['gnomad_ge1pct'], base['n'])}) | "
                  f"{pct(len(com), n)} | {pct(p_som, 1) if p_som is not None else 'NA'} | "
                  f"{(f'{100 * est:.1f} %') if est is not None else 'NA'} | {(f'~{est * n:,.0f}') if est is not None else 'NA'} |")
        ai = sm["INDEL_all"]
        t5.append(f"| {name} | {ai['n']:,} | {ai['normal_exact']:,} | {ai['gnomad_ge1pct']:,} ({pct(ai['gnomad_ge1pct'], ai['n'])}) "
                  f"| {ai['colorsdb_ge1pct']:,} ({pct(ai['colorsdb_ge1pct'], ai['n'])}) |")
        top = Counter((r["chrom"], r["pos"] // 1_000_000) for r in com_a).most_common(8)
        out[name] = dict(snv=n, snv_in_bed=nb, common=len(com), common_in_bed=com_b, common_autosomal=len(com_a),
                         common_in_lowhet_bins=len(low), rare_in_lowhet_bins=len(rare_low), common_in_segments=len(in_segs), all_in_segments=len(all_segs),
                         segments=segs, chr1_snv=len(c1), chr1_common=len(c1c),
                         germline_baseline_common=p_germ, implied_germline_like_share=est,
                         top_common_bins=[f"{c}:{b}-{b + 1} Mb n={m}" for (c, b), m in top])
    lines_md += ["## T1. Somatic truth SNV alleles vs the normal's germline calls and gnomAD", ""] + t1 + [""]
    lines_md += ["## T2. Where the common (gnomAD AF >= 1 %) truth SNVs lie: the normal's het fraction per 1-Mb bin", ""] + t2 + [""]
    lines_md += ["## T3. chr1 (Pansoma's test chromosome)", ""] + t3 + [""]
    lines_md += ["## T4. Germline-like share implied by the common-allele rate (rough mixture estimate)", "",
                 "share = (observed - somatic reference) / (germline baseline - somatic reference); the somatic reference is "
                 "the SEQC2 HCC1395 truth (its 0.54 % includes IG/TCR-locus alleles, so the estimate is approximate).", ""] + t4 + [""]
    lines_md += ["## T5. INDEL alleles (secondary)", ""] + t5 + [""]
    lines_md += ["## Top 1-Mb bins of common truth SNVs (autosomes)", ""]
    for name, d in out.items():
        lines_md.append(f"- {name}: " + "; ".join(d["top_common_bins"]))
    (HERE / "tables.md").write_text("\n".join(lines_md) + "\n")
    (HERE / "summary_tables.json").write_text(json.dumps(out, indent=1) + "\n")
    print((HERE / "tables.md").read_text())


if __name__ == "__main__":
    main()
