"""E12a: cross-sample application of the 2026-10-12 RIS d46 models (preliminary).

Each model trained on chr2-22 of one tumor (HG008T or COLO829T, HPRC v2.1 d46 graph) predicts chr1 of ANOTHER tumor's
d46 tensor set (HG008T <-> COLO829T, and both -> HCC1395T), on tequila's GPUs (bf16, as on RIS; job arrays 387379 and
387323_0), then jobs/vcf.sh: graph_vcf at the model's own validation recall-0.9 threshold -> linear_vcf -> PoN -> rtg
vcfeval inside the target's benchmark BED. In-sample references: the RIS runs of the target (benchmark summary.json).
Old checkpoints: BQ / MAPQ z-scored with the TRAINING tumor's statistics (before cbc94a7 / f2a0e4e).
Writes tables.md and summary.json. Standard library only.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = Path("/scratch/jshen/data/pansoma_net_v2_runs/reviewer_cpu_20261013")
BENCH = HERE.parents[2] / "benchmark_7fc7396_20261012" / "hprc_v21_d46_7fc7396_20261012" / "summary.json"


def report(d):
    out = {}
    for ev in ("eval_bed", "eval_nobed"):
        f = d / ev / "report.json"
        if not f.exists():
            return None
        r = json.loads(f.read_text())
        a, p = r["raw"]["at_threshold"], r["pon"]["at_threshold"]
        out[ev] = dict(threshold=r["threshold"], unplaced=r["unplaced_pass"], truth=r["truth_records"],
                       raw=dict(p=a["precision"], r=a["recall"], f1=a["f1"]),
                       pon=dict(tp=p["tp_baseline"], fp=p["fp"], fn=p["fn"], p=p["precision"], r=p["recall"], f1=p["f1"]),
                       pon_best=r["pon"].get("best", {}), pon_ceiling=r["pon"].get("ceiling"))
    return out


def insample():
    """target set -> (run, PoN F1 in the BED, best F1) of the RIS d46 runs."""
    res = {}
    for e in json.loads(BENCH.read_text()):
        a = e["d46"]
        plat = {"PacBio": "PacBio", "fiberseq": "fiberseq"}.get(e["platform"], e["platform"])
        s = f"{e['sample']}_{plat}_d46"
        res[(s, e["kind"])] = (a["run"], a["eval_bed"]["pon"]["f1"], a["eval_bed"]["pon"]["best"]["f1"])
    return res


def main():
    ins = insample()
    rows = []
    for d in sorted(RUNS.glob("xs__*")):
        _, model, target = d.name.split("__")
        kind = "SNV" if "_SNV_" in model else "INDEL"
        r = report(d / "vcf_chr1")
        if r is None:
            rows.append(dict(model=model, target=target, kind=kind, status="pending"))
            continue
        ref = ins.get((target, kind))
        rows.append(dict(model=model, target=target, kind=kind, status="done", **r,
                         insample=dict(run=ref[0], pon_f1=ref[1], pon_best_f1=ref[2]) if ref else None))
    L = ["# E12a cross-sample (preliminary): d46 models applied to another tumor's chr1 (generated by collect.py)", "",
         "PASS = the model's own validation recall-0.9 threshold (chosen on its training tumor). In the target's BED, "
         "after the PoN. `best` = the chr1 curve's best F1 after the PoN (test-tuned, reference only). In-sample = the "
         "RIS model trained on the target itself (chr2-22), same test. Old checkpoints: BQ / MAPQ z-scored with the "
         "training tumor's statistics.", "",
         "| kind | model (trained on) | target chr1 | PASS thr | PoN TP / FP / FN | PoN P / R / F1 | best F1 | ceiling | unplaced PASS | in-sample PoN F1 (best) |",
         "|---|---|---|---:|---|---|---:|---:|---:|---|"]
    for x in rows:
        if x["status"] != "done":
            L.append(f"| {x['kind']} | `{x['model']}` | {x['target']} | pending | | | | | | |")
            continue
        b = x["eval_bed"]; p = b["pon"]
        ins_txt = f"{x['insample']['pon_f1']:.3f} ({x['insample']['pon_best_f1']:.3f})" if x["insample"] else "-"
        L.append(f"| {x['kind']} | `{x['model']}` | {x['target']} | {b['threshold']:.3f} | {p['tp']} / {p['fp']} / {p['fn']} | "
                 f"{p['p']:.3f} / {p['r']:.3f} / **{p['f1']:.3f}** | {b['pon_best'].get('f1', float('nan')):.3f} | "
                 f"{b['pon_ceiling'] if b['pon_ceiling'] is not None else float('nan'):.3f} | {b['unplaced']:,} | {ins_txt} |")
    (HERE / "tables.md").write_text("\n".join(L) + "\n")
    (HERE / "summary.json").write_text(json.dumps(rows, indent=1) + "\n")
    print(f"{sum(x['status'] == 'done' for x in rows)} done, {sum(x['status'] != 'done' for x in rows)} pending")


if __name__ == "__main__":
    main()
