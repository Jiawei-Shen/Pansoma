#!/usr/bin/env python
"""Response Figure 1.3 (ver4): the numbers a caption or a sentence about the figure needs, written by code from
values.json (-> facts.md), and a pixel check of the PNG (marker positions read back from the image against the values).

Run after pathcount_data.py and pathcount_fig.py:
  /wanglab/jshen/anaconda3/envs/sambcfenv/bin/python pathcount_facts.py
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
v = json.load(open(HERE / "values.json"))
meta = json.load(open(HERE / "fig_R1.3_pathcount.meta.json"))
rows, METRICS = v["rows"], v["metrics"]


def d3(x):
    return f"{x:+.3f}".replace("-", "−")


def f3(x):
    return f"{x:.3f}"


L = []
P = L.append
truth = rows[0]["models"]["with_s0"]["pon"]["truth"]
P("# Response Figure 1.3 (ver4): facts for the caption and the text (generated by pathcount_facts.py)")
P("")
P(f"- Figure file `fig_R1.3_pathcount.png`: {meta['width_px']} x {meta['height_px']} px at {meta['dpi']} dpi "
  f"(ver3 image: 4251 x 1322 px, six rows). x-range of all four panels of a: {meta['xlim_all_panels'][0]}–{meta['xlim_all_panels'][1]}. "
  f"Colour scale of b: symmetric, {d3(meta['colour_scale'][0])} to {d3(meta['colour_scale'][1])} (ver3: ±0.5).")
P(f"- Truth: {truth:,} chr1 somatic SNVs of COLO829T in the benchmark regions, identical in all 16 call sets.")
P("")
P("## Deltas, with (seed 0) − without")
P("")
for key, stage, short in METRICS:
    P(f"- Δ{short}: " + "; ".join(f"{r['platform_name']} {r['graph_name'].replace('HPRC ', '')} {d3(r['delta'][short])}" for r in rows)
      + f". Positive in {sum(r['delta'][short] > 0 for r in rows)} of 4.")
P("")
P("## Without the channel against the three seeds with it")
P("")
n_all, k_all = 0, 0
for r in rows:
    wo = r["models"]["without_s0"]["pon"]
    seeds = [r["models"][f"with_s{s}"]["pon"] for s in range(3)]
    k = sum(s["f1"] > wo["f1"] for s in seeds)
    kp = sum(s["precision"] > wo["precision"] for s in seeds)
    kr = sum(s["recall"] > wo["recall"] for s in seeds)
    n_all, k_all = n_all + 3, k_all + k
    lo, hi = r["seed_range"]["F1"]
    P(f"- {r['platform_name']} {r['graph_name']}: F1 with the channel {' / '.join(f3(s['f1']) for s in seeds)} (seeds 0 / 1 / 2; "
      f"range {f3(hi - lo)}, mean {f3(r['seed_mean']['F1'])}), without {f3(wo['f1'])}: {r['without_vs_range']['F1']} the seed range"
      + (f" (lowest seed − without = {d3(lo - wo['f1'])})" if r["without_vs_range"]["F1"] != "inside" else "")
      + f"; seeds with higher F1 than the model without: {k} of 3 (precision {kp} of 3, recall {kr} of 3); "
      f"mean of 3 seeds − without = {d3(r['delta_mean']['F1'])}.")
P(f"- Over the four datasets, {k_all} of {n_all} with-channel seeds have a higher F1 after the filter than the model without the channel.")
P("")
P("## Where the difference comes from (PASS calls after the filter, seed 0 with / without)")
P("")
for r in rows:
    a, b = r["models"]["with_s0"]["pon"], r["models"]["without_s0"]["pon"]
    P(f"- {r['platform_name']} {r['graph_name']}: TP {a['tp_baseline']:,} / {b['tp_baseline']:,}, FP {a['fp']:,} / {b['fp']:,} "
      f"(without / with = {b['fp'] / a['fp']:.2f}x), precision {f3(a['precision'])} / {f3(b['precision'])}, recall {f3(a['recall'])} / {f3(b['recall'])}.")
P("")
P("## Before against after the population filter")
P("")
gap = [(abs(m["raw"]["f1"] - m["pon"]["f1"]), r["label"], k) for r in rows for k, m in r["models"].items()]
P(f"- |F1 before − F1 after| over the 16 models: largest {max(gap)[0]:.4f} ({max(gap)[1]}, {max(gap)[2]}), so the "
  "\"F1 (pre-filter)\" panel repeats the F1 panel: these models take the population site features as an input.")
fpgap = [(m["raw"]["fp"] - m["pon"]["fp"], m["raw"]["tp_baseline"] - m["pon"]["tp_baseline"]) for r in rows for m in r["models"].values()]
P(f"- The filter removes {min(x for x, _ in fpgap)}–{max(x for x, _ in fpgap)} FP and {min(y for _, y in fpgap)}–{max(y for _, y in fpgap)} TP per call set.")
P("")

# pixel check of the PNG: the orange diamond (drawn last, never covered) of every row and panel
a = np.asarray(Image.open(HERE / "fig_R1.3_pathcount.png").convert("RGB")).astype(int)
assert a.shape[1] == meta["width_px"] and a.shape[0] == meta["height_px"]
g = meta["geometry_px"]
lo, hi = meta["xlim_all_panels"]
orange = np.abs(a - np.array([0xd5, 0x5e, 0x00])).max(axis=2) == 0
worst = 0.0
for i, (r, y) in enumerate(zip(rows, g["rows_y"])):
    for j, (key, stage, short) in enumerate(METRICS):
        px0 = g["panel_x0"] + j * (g["panel_width"] + 73)
        band = orange[int(y) - 18:int(y) + 19, int(px0) - 30:int(px0 + g["panel_width"]) + 30]
        xs = np.flatnonzero(band.any(axis=0))
        assert len(xs), (r["label"], short)
        cx = int(px0) - 30 + (xs[0] + xs[-1]) / 2.0 + 0.5
        val = lo + (cx - px0) / g["panel_width"] * (hi - lo)
        worst = max(worst, abs(val - r["models"]["without_s0"][stage][key]))
P("## Pixel check of the PNG")
P("")
P(f"- The centre of the orange diamond of each of the 16 row x panel cells, read back from the PNG and converted to the "
  f"axis scale, equals the tabulated value of the model without the channel within {worst:.4f} (one pixel = "
  f"{(hi - lo) / g['panel_width']:.4f}).")
assert worst < 0.002, worst
(HERE / "facts.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
