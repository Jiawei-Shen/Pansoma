#!/usr/bin/env python3
"""chr1 INDEL truth and false calls by repeat context for HG008T, COLO829T and HCC1395T (2026-11-27).

    PYTHONDONTWRITEBYTECODE=1 /wanglab/jshen/anaconda3/bin/python -B indel_context_three_tumors.py

The counting of ver4_20261123/recount/b_hp_fp.py (E17a strata() and Classifier, unchanged) on the three tumors:
six-tumor release INDEL models release_s{0,1,2}_<P>_INDEL on HPRC v2.1, chr1 (held out), benchmark regions, PASS calls
after the population filter (eval_bed/vcfeval/pon_calls); PASS rule ppr8 on Illumina / PacBio HiFi (Fiber-seq), pp on ONT.
Truth by context and its population tags come from the same strata() (tp-baseline + fn records; tag from
truth.INDEL.pon.vcf.gz). HG008T must reproduce b_hp_fp.json (asserted).
Writes indel_context_three_tumors.md / .json next to this script.
"""
import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = Path('/scratch/jshen/Github/Pansoma')
RECOUNT = REPO / 'analysis/reviewer_response_20261011/ver4_20261123/recount'
E17A = REPO / 'analysis/reviewer_response_20261011/experiments/E17a_indel_strata'
sys.path.insert(0, str(E17A))
import e17a_indel_strata as E  # noqa: E402
from e17a_indel_strata import C  # noqa: E402

RUNS = Path('/scratch/jshen/data/pansoma_net_v2_runs')
PLATS = ('Illumina', 'PacBio', 'ONT')
SEEDS = (0, 1, 2)
RULE = {'Illumina': 'ppr8', 'PacBio': 'ppr8', 'ONT': 'pp'}
TUMORS = ('HG008T', 'COLO829T', 'HCC1395T')
CTX = ('HP>=7', 'HP4-6', 'STR', 'VNTR', 'none', 'complex')
CNAME = {'HP>=7': 'Homopolymer ≥ 7 bp', 'HP4-6': 'Homopolymer 4–6 bp', 'STR': 'Short tandem repeat', 'VNTR': 'VNTR',
         'none': 'Not in a repeat', 'complex': 'complex'}


def ds(t, p):
    return f"{t}_{'fiberseq' if (t, p) == ('COLO829T', 'PacBio') else p}_d46"


def pname(t, p):
    return {'Illumina': 'Illumina', 'ONT': 'ONT', 'PacBio': 'Fiber-seq' if t == 'COLO829T' else 'PacBio HiFi'}[p]


def unit(t, p, seed):
    run = f'release_s{seed}_{p}_INDEL'
    d = RUNS / run / f'vcf_{RULE[p]}_chr1_{ds(t, p)}' / 'eval_bed'
    w = d / 'vcfeval' / 'pon_calls'
    assert (d / 'report.json').exists() and C._rtg_complete(w), d
    u = C.Unit(uid=f'{run}/{d.parent.name}', run=run, set=ds(t, p), kind='INDEL', role='release', variant=f's{seed}', model=run)
    u.rtg['bed'], u.report['bed'] = w, json.loads((d / 'report.json').read_text())
    u.truth_pon = d / 'truth.INDEL.pon.vcf.gz'
    return u


def count(u, classify):
    t, skipped, has_pon = E.strata(u, classify)
    rep = u.report['bed']
    at = rep['pon']['at_threshold']
    a = t[('all', 'all')]
    assert (a[0], a[1], a[2], a[3]) == (at['tp_baseline'], at['fn'], at['tp_call'], at['fp']), u.uid
    assert a[0] + a[1] == rep['pon']['baseline'] == rep['raw']['baseline'], u.uid
    assert has_pon and not skipped, u.uid
    g = lambda c: t.get(('context', c), [0] * 5)
    assert set(c for ax, c in t if ax == 'context') <= set(CTX), u.uid
    return dict(uid=u.uid, truth=a[0] + a[1], tagged=a[4], tp=a[0], fn=a[1], tp_call=a[2], fp=a[3],
                truth_ctx={c: g(c)[0] + g(c)[1] for c in CTX}, tagged_ctx={c: g(c)[4] for c in CTX},
                tp_ctx={c: g(c)[0] for c in CTX}, fp_ctx={c: g(c)[3] for c in CTX})


def main():
    units = {(t, p, s): unit(t, p, s) for t in TUMORS for p in PLATS for s in SEEDS}
    classify = E.Classifier(C.fasta_path(list(units.values())))
    cnt = {k: count(u, classify) for k, u in units.items()}
    for (t, p, s), c in cnt.items():   # one truth split per tumor; totals add up
        r = cnt[(t, 'Illumina', 0)]
        assert (c['truth'], c['tagged'], c['truth_ctx'], c['tagged_ctx']) == (r['truth'], r['tagged'], r['truth_ctx'], r['tagged_ctx']), (t, p, s)
        assert sum(c['truth_ctx'].values()) == c['truth'] and sum(c['tagged_ctx'].values()) == c['tagged'] and sum(c['fp_ctx'].values()) == c['fp']
    # HG008T = b_hp_fp.json
    old = json.loads((RECOUNT / 'b_hp_fp.json').read_text())
    v4 = old['fp_hp7']['ver4 (ppr8 Illumina / PacBio HiFi, pp ONT)']
    for p in PLATS:
        assert [cnt[('HG008T', p, s)]['fp'] for s in SEEDS] == v4[p]['fp'] and [cnt[('HG008T', p, s)]['fp_ctx']['HP>=7'] for s in SEEDS] == v4[p]['fp_hp7'], p
        assert [cnt[('HG008T', p, s)]['fp_ctx'] for s in SEEDS] == [{c: x.get(c, 0) for c in CTX} for x in v4[p]['fp_by_context']], p
    r = cnt[('HG008T', 'Illumina', 0)]
    assert (r['truth'], r['tagged']) == (old['truth']['in_bed'], old['truth']['in_bed_tagged'])
    assert {c: n for c, n in r['truth_ctx'].items() if n} == old['truth']['in_bed_context']
    assert {c: n for c, n in r['tagged_ctx'].items() if n} == old['truth']['in_bed_tagged_context']

    pct = lambda x: f'{100 * x:.1f}%'
    tri = lambda xs: ' / '.join(str(x) for x in xs)
    L = ['# chr1 INDEL truth and false calls by repeat context: HG008T, COLO829T, HCC1395T', '',
         'Generated by `indel_context_three_tumors.py`. Six-tumor release INDEL models `release_s{0,1,2}_<P>_INDEL` on HPRC v2.1, '
         'chr1 (held out), benchmark regions, PASS calls after the population filter; PASS rule ppr8 on Illumina / PacBio HiFi / '
         'Fiber-seq, pp on ONT. Context of a record = `truth_labels.RepeatContext` on GRCh38 (as E17a and `ver4_20261123/recount/b_hp_fp.py`). '
         'HG008T equals `b_hp_fp.json` (asserted).', '']
    S = {}
    for t in TUMORS:
        r = cnt[(t, 'Illumina', 0)]
        ctx = [c for c in CTX if r['truth_ctx'][c] or any(cnt[(t, p, s)]['fp_ctx'][c] for p in PLATS for s in SEEDS)]
        L += [f'## {t}', '', f'### (a) chr1 truth INDELs of {t} by repeat context and population tag', '',
              '| repeat context | chr1 truth INDELs | tagged by the population filter | left to be called |', '|---|---|---|---|']
        for c in ctx:
            L.append(f"| {CNAME[c]} | {r['truth_ctx'][c]} | {r['tagged_ctx'][c]} | {r['truth_ctx'][c] - r['tagged_ctx'][c]} |")
        L.append(f"| all | {r['truth']} | {r['tagged']} ({pct(r['tagged'] / r['truth'])}) | {r['truth'] - r['tagged']} (recall bound {1 - r['tagged'] / r['truth']:.3f}) |")
        L += ['', f'### (b) chr1 INDEL false calls of {t} by repeat context (seed 0 / 1 / 2)', '',
              '| platform | ' + ' | '.join(CNAME[c] for c in ctx) + ' | all chr1 false calls | chr1 TP (truth side) | share in homopolymers ≥ 7 bp | share in any repeat class |',
              '|---|' + '---|' * (len(ctx) + 4)]
        S[t] = dict(truth=r['truth'], tagged=r['tagged'], truth_ctx=r['truth_ctx'], tagged_ctx=r['tagged_ctx'], platforms={})
        for p in PLATS:
            cs = [cnt[(t, p, s)] for s in SEEDS]
            sh = [c['fp_ctx']['HP>=7'] / c['fp'] for c in cs]
            rp = [(c['fp'] - c['fp_ctx']['none']) / c['fp'] for c in cs]
            L.append(f"| {pname(t, p)} | " + ' | '.join(tri(c['fp_ctx'][x] for c in cs) for x in ctx) + f" | {tri(c['fp'] for c in cs)} | {tri(c['tp'] for c in cs)} | "
                     f"{' / '.join(pct(x) for x in sh)} (mean {pct(statistics.mean(sh))}) | {' / '.join(pct(x) for x in rp)} (mean {pct(statistics.mean(rp))}) |")
            S[t]['platforms'][pname(t, p)] = dict(rule=RULE[p], uid=[c['uid'] for c in cs], fp=[c['fp'] for c in cs], tp=[c['tp'] for c in cs],
                                                  fp_ctx=[c['fp_ctx'] for c in cs], tp_ctx=[c['tp_ctx'] for c in cs], share_hp7=sh, share_hp7_mean=statistics.mean(sh),
                                                  share_repeat=rp, share_repeat_mean=statistics.mean(rp))
        L.append('')
    L += ['## Checks', '', f'- {len(cnt)} call sets; TP / FN / TP-call / FP of each equal report.json `pon.at_threshold`; no record skipped.',
          '- Truth, tagged truth and their split by context are identical across platforms and seeds within a tumor.',
          '- HG008T: false calls by context per seed, truth and tagged truth by context equal `ver4_20261123/recount/b_hp_fp.json`.']
    (HERE / 'indel_context_three_tumors.md').write_text('\n'.join(L) + '\n')
    (HERE / 'indel_context_three_tumors.json').write_text(json.dumps(S, indent=1) + '\n')


if __name__ == '__main__':
    main()
