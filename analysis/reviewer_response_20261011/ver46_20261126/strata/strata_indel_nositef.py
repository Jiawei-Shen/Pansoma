#!/usr/bin/env python3
"""Response Table 2.8 with one row per reference and no population site features in any model (user 2026-11-26).

HG008T chr1 INDELs, benchmark regions, PASS calls after the population filter, by the number of HG008-N germline
variants within 50 bp of the variant (0 / 1 / >=2). The stratification is E19's (experiments/E19_germline_density:
germline_density.process, strata_latest.stats; recall by the truth INDEL's group, precision by the call's group).
Six-tumor INDEL models, seed 0, none with the site features as a model input (R = pansoma_net_v2_runs):

  GRCh38-only  R/m4m6_graphs_20261110/multicancer6_<P>_INDEL_linear_nositef/vcf_<rule>_chr1_HG008T   (the letter's rows)
  HPRC v1.1    R/m6_nositef_graphs_20261118/multicancer6_<P>_INDEL_d9_nositef/vcf_<rule>_chr1_HG008T
  HPRC v2.1    R/m6_nositef_graphs_20261118/multicancer6_<P>_INDEL_d46_nositef/vcf_<rule>_chr1_HG008T
  rule = ppr8 (Illumina, PacBio HiFi), pp (ONT).

Checks (asserted): totals of every call set = its eval_bed/report.json (pon, at_threshold); truth groups 452 / 84 / 51
in every call set; the GRCh38-only rows equal the rows of the letter (ver4.5, Response Table 2.8).
Per-record rows are cached in ./cache (E19's own cache is not written).
    /wanglab/jshen/anaconda3/bin/python strata_indel_nositef.py      -> strata_indel_nositef.md, strata_indel_nositef.json
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
E19 = HERE.parents[1] / "experiments/E19_germline_density"
sys.path.insert(0, str(E19))
import strata_latest as S  # noqa: E402

G, L = S.G, S.L
G.OUT = HERE / "cache"
R = Path("/scratch/jshen/data/pansoma_net_v2_runs")
ARMS = (("linear", "GRCh38-only", R / "m4m6_graphs_20261110", "linear_nositef"),
        ("d9", "HPRC v1.1", R / "m6_nositef_graphs_20261118", "d9_nositef"),
        ("d46", "HPRC v2.1", R / "m6_nositef_graphs_20261118", "d46_nositef"))
PLATS = ("Illumina", "PacBio", "ONT")
SL = ("0", "1", "2+")
T = "HG008T"
TRUTH = (452, 84, 51)
# GRCh38-only rows of the letter (ver4.5): FP and F1 per group
LETTER = {"Illumina": ((139, 34, 17), ("0.294", "0.066", "0.057")),
          "PacBio": ((325, 137, 79), ("0.240", "0.078", "0.074")),
          "ONT": ((197, 28, 9), ("0.094", "0.018", "0.033"))}
MINUS = "−"


def call_set(p, arm, root, suffix):
    v = root / f"multicancer6_{p}_INDEL_{suffix}" / f"vcf_{'pp' if p == 'ONT' else 'ppr8'}_chr1_{T}"
    assert L.complete(v), v
    lin = sorted(v.glob("*.INDEL.linear.vcf.gz"))
    assert len(lin) == 1, v
    st = lin[0].name[: -len(".INDEL.linear.vcf.gz")]
    sample, platform, a, purity = L.set_parts(st)
    assert sample == T and a == arm and purity == "P100", (st, arm)
    run = v.parent
    return L.CallSet(run=f"{run.parent.name}__{run.name}", vcf_dir=v, group="insample", variant="main", model=run.name,
                     model_sample="m6", model_platform=p, kind="INDEL", set=st, sample=T, platform=platform, arm=arm,
                     purity=purity, prefix=f"{st}.INDEL")


def sgn(x):
    return "–" if x is None else f"{x:+.3f}".replace("-", MINUS)


def main():
    G.OUT.mkdir(exist_ok=True)
    res, meta = {}, {}
    for p in PLATS:
        for arm, _, root, suffix in ARMS:
            cs = call_set(p, arm, root, suffix)
            rows = G.process(cs)
            rep = cs.report("eval_bed")["pon"]["at_threshold"]
            a = S.stats(rows, "all")
            assert (a["tpb"], a["truth"] - a["tpb"], a["tpc"], a["fp"]) == (rep["tp_baseline"], rep["fn"], rep["tp_call"], rep["fp"]), cs.id
            st = {s: S.stats(rows, s) for s in SL + ("all",)}
            assert tuple(st[s]["truth"] for s in SL) == TRUTH, (cs.id, [st[s]["truth"] for s in SL])
            res[p, arm] = st
            meta[p, arm] = str(cs.vcf_dir)
        fp, f1 = LETTER[p]
        b = res[p, "linear"]
        assert tuple(b[s]["fp"] for s in SL) == fp and tuple(S.f3(b[s]["f"]) for s in SL) == f1, (p, "GRCh38-only row differs from the letter")

    d = {(p, arm): [None if res[p, arm][s]["f"] is None or res[p, "linear"][s]["f"] is None
                    else res[p, arm][s]["f"] - res[p, "linear"][s]["f"] for s in SL]
         for p in PLATS for arm in ("d9", "d46")}
    out = ["# Response Table 2.8 without the population site features in any model (HG008T chr1 INDEL)", "",
           "Generated by `strata_indel_nositef.py`. chr1, benchmark regions, PASS calls after the population filter "
           "(ppr8; ONT pp). Stratum = germline variants of HG008-N within 50 bp of the variant (0 / 1 / ≥2), the "
           "variant's own interval excluded; recall by the truth INDEL's stratum, precision by the call's stratum. "
           "Six-tumor INDEL models, seed 0, none with the population site features as a model input: GRCh38-only = "
           "`m4m6_graphs_20261110/multicancer6_<P>_INDEL_linear_nositef` (the letter's rows, recomputed and equal), "
           "HPRC v1.1 / v2.1 = `m6_nositef_graphs_20261118/multicancer6_<P>_INDEL_{d9,d46}_nositef`. ΔF1 = HPRC − "
           "GRCh38-only of the same platform, from the unrounded F1. Truth INDELs 0 / 1 / ≥2: 452 / 84 / 51.", "",
           "| Platform | Reference | False positives (0 / 1 / ≥2) | Precision (0 / 1 / ≥2) | Recall (0 / 1 / ≥2) | F1 (0 / 1 / ≥2) | ΔF1, HPRC − GRCh38-only (0 / 1 / ≥2) |",
           "|---|---|---|---|---|---|---|"]
    cells = []
    for p in PLATS:
        for i, (arm, gname, _, _) in enumerate(ARMS):
            st = res[p, arm]
            dd = "–" if arm == "linear" else " / ".join(sgn(x) for x in d[p, arm])
            out.append(f"| {S.pname(T, p) if i == 0 else ''} | {gname} | {S.tri([st[s]['fp'] for s in SL])} | "
                       f"{S.tri([st[s]['p'] for s in SL])} | {S.tri([st[s]['r'] for s in SL])} | "
                       f"{S.tri([st[s]['f'] for s in SL])} | {dd} |")
            cells.append(dict(platform=S.pname(T, p), reference=gname, vcf_dir=meta[p, arm],
                              groups={s: {k: st[s][k] for k in ("truth", "tpb", "tpc", "fp", "p", "r", "f")} for s in SL + ("all",)},
                              dF1=None if arm == "linear" else dict(zip(SL, d[p, arm]))))
    out += ["", "## Whole chr1 (the call sets' report.json), and counts per stratum", "",
            "| Platform | Reference | chr1 all: TP / FP / P / R / F1 | TP truth (0 / 1 / ≥2) | TP calls (0 / 1 / ≥2) |", "|---|---|---|---|---|"]
    for p in PLATS:
        for arm, gname, _, _ in ARMS:
            a = res[p, arm]["all"]
            out.append(f"| {S.pname(T, p)} | {gname} | {a['tpb']} / {a['fp']} / {S.tri([a[k] for k in ('p', 'r', 'f')])} | "
                       f"{S.tri([res[p, arm][s]['tpb'] for s in SL])} | {S.tri([res[p, arm][s]['tpc'] for s in SL])} |")

    hp = [(p, arm) for p in PLATS for arm in ("d9", "d46")]
    gl = {"0": "no nearby germline variant", "1": "one", "2+": "at least two"}
    out += ["", "## Over the six HPRC rows (three platforms × v1.1, v2.1), against GRCh38-only of the same platform", "",
            "| group | ΔF1 range | ΔF1 > 0 | precision higher | recall higher / equal / lower | FP, GRCh38-only → HPRC (range of the change) |",
            "|---|---|---|---|---|---|"]
    facts = {}
    for j, s in enumerate(SL):
        dv = [d[k][j] for k in hp]
        ph = sum((res[k][s]["p"] or 0) > (res[k[0], "linear"][s]["p"] or 0) for k in hp)
        rh = sum(res[k][s]["tpb"] > res[k[0], "linear"][s]["tpb"] for k in hp)
        re_ = sum(res[k][s]["tpb"] == res[k[0], "linear"][s]["tpb"] for k in hp)
        red = [1 - res[k][s]["fp"] / res[k[0], "linear"][s]["fp"] for k in hp]
        fps = "; ".join(f"{S.pname(T, p)} {res[p, 'linear'][s]['fp']} → {res[p, 'd9'][s]['fp']} / {res[p, 'd46'][s]['fp']}" for p in PLATS)
        out.append(f"| {gl[s]} | {sgn(min(dv))} to {sgn(max(dv))} | {sum(x > 0 for x in dv)} of 6 | {ph} of 6 | "
                   f"{rh} / {re_} / {6 - rh - re_} | {fps} (v1.1 / v2.1; {100 * min(red):.0f}% to {100 * max(red):.0f}% fewer) |")
        facts[s] = dict(dF1_min=min(dv), dF1_max=max(dv), dF1_positive=sum(x > 0 for x in dv), precision_higher=ph,
                        recall_higher=rh, recall_equal=re_, recall_lower=6 - rh - re_,
                        fp_reduction_min=min(red), fp_reduction_max=max(red))
    out += ["", "## Checks", "",
            "- totals of every call set equal its `eval_bed/report.json` (pon, at_threshold; asserted)",
            "- truth strata of every call set are 452 / 84 / 51 (asserted)",
            "- the GRCh38-only rows equal the letter's rows: FP 139 / 34 / 17, 325 / 137 / 79, 197 / 28 / 9 and F1 "
            "0.294 / 0.066 / 0.057, 0.240 / 0.078 / 0.074, 0.094 / 0.018 / 0.033 (asserted)"]
    (HERE / "strata_indel_nositef.md").write_text("\n".join(out) + "\n")
    (HERE / "strata_indel_nositef.json").write_text(json.dumps(dict(truth=dict(zip(SL, TRUTH)), rows=cells, ranges=facts), indent=1) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
